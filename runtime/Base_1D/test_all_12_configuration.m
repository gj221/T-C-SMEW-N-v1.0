function test_all_12_configuration
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Pin the calibrated CEC 13 all-12 campaign: parameter identity with the
%% sweep, workbook and parameter-script facts, wrapper options, Slurm
%% resources and controller graph.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

one_d_dir = fileparts(mfilename('fullpath'));
repo_root = fileparts(fileparts(one_d_dir));
one_d_tag = ...
    'Base_1D';
two_d_tag = ...
    'Base_2D';
sweep_tag = 'Calibration_Sweep_1D';
two_d_dir = fullfile(repo_root,'runtime',two_d_tag);
sweep_dir = fullfile(repo_root,'runtime',sweep_tag);
code_dir = fullfile(repo_root,'v2','T&C_Code');
assert(strcmp(fullfile(repo_root,'runtime',one_d_tag),one_d_dir), ...
    'Bouchet_Kantola_CEC13:CampaignDirectory', ...
    'The 1-D campaign directory must be runtime/%s.',one_d_tag);
assert(isfolder(two_d_dir) && isfolder(sweep_dir), ...
    'Bouchet_Kantola_CEC13:MissingCampaignDirectory', ...
    'The 2-D campaign and the CEC 13 sweep directories must both exist.');
addpath(one_d_dir);

%% Parameter identity with the sweep that produced the calibration.
P = Campaign_Parameters;
alpha_grid = linspace(1.3,3.4,5);
assert(P.AppeloAlpha == alpha_grid(5) && P.AppeloAlpha == 3.4 && ...
    isequal(P.AppeloLogKH,P.reference_logKH + ...
    P.charge*(P.AppeloAlpha-P.reference_alpha)*P.seed_f_H) && ...
    P.sweep_combination_id == 65 && isequal(P.sweep_case_ids,[193 194 195]) && ...
    P.KNmaxd == 0.0048 && ...
    isnan(P.Kbot) && P.CEC_cmolc_kg == 13 && P.CECpHSensitivity == 0 && ...
    strcmp(P.exchange_scheme,'appelo') && P.NDays == 1826 && ...
    P.StartDate == datenum(2016,1,1), ... %#ok<DATNM>
    'Bouchet_Kantola_CEC13:ParameterValues', ...
    'The calibrated parameter set changed.');
old_path = addpath(sweep_dir);
path_cleanup = onCleanup(@() path(old_path));
cases = Sweep_Cases;
for k = 1:3
    c = cases(P.sweep_case_ids(k));
    assert(c.combination_id == P.sweep_combination_id && ...
        strcmp(c.combination_tag,P.sweep_combination_tag) && ...
        c.run_id == 9+k && ...
        isequal(c.AppeloAlpha,P.AppeloAlpha) && ...
        isequal(c.AppeloLogKH,P.AppeloLogKH) && ...
        isequal(c.KNmaxd,P.KNmaxd) && isequaln(c.Kbot,P.Kbot) && ...
        isequal(c.CEC_cmolc_kg,P.CEC_cmolc_kg), ...
        'Bouchet_Kantola_CEC13:SweepIdentity', ...
        'Sweep case %d does not match the calibrated set bit for bit.', ...
        P.sweep_case_ids(k));
end

%% CEC 13 comes from the workbook and the Appelo scheme from the parameter
%% script; neither is an option, so both are pinned here.
workbook = fullfile(code_dir,'Inputs','ERW_MOD_PARAM_parameters.xlsx');
T = readtable(workbook,'Sheet','ERW_MOD');
assert(all(abs(T.CEC_tot_in(1:5)-P.CEC_cmolc_kg) < eps(13)), ...
    'Bouchet_Kantola_CEC13:WorkbookCEC', ...
    'The parameter workbook no longer carries CEC 13 for every treatment.');
param_text = fileread(fullfile(code_dir,'Parameters', ...
    'MOD_PARAM_Kantola_Maize_Soy.m'));
assert(contains(param_text,'bulk_pH_params.scheme = ''appelo'';'), ...
    'Bouchet_Kantola_CEC13:ExchangeScheme', ...
    'MOD_PARAM_Kantola_Maize_Soy.m no longer selects the Appelo scheme.');

%% Wrappers pass the tuple from the parameter function and nothing else.
option_tokens = { ...
    '''AppeloAlpha'',P.AppeloAlpha,''AppeloLogKH'',P.AppeloLogKH, ...', ...
    '''KNmaxd'',P.KNmaxd,''Kbot'',P.Kbot,'};
one_d_task = fileread(fullfile(one_d_dir,'Run_Base_1D_Task.m'));
two_d_task = fileread(fullfile(two_d_dir, ...
    'Run_Base_2D_Task.m'));
identity_text = fileread(fullfile(one_d_dir, ...
    'Validate_Preapplication_Identity.m'));
smoke_text = fileread(fullfile(one_d_dir,'Validate_All12_Smoke.m'));
for text = {one_d_task,two_d_task,identity_text,smoke_text}
    assert(all(cellfun(@(t) contains(text{1},t),option_tokens)), ...
        'Bouchet_Kantola_CEC13:WrapperOptions', ...
        'A wrapper does not pass the calibrated tuple from the parameter function.');
end
campaign_files = [dir(fullfile(one_d_dir,'*.m')); dir(fullfile(two_d_dir,'*.m')); ...
    dir(fullfile(one_d_dir,'*.sbatch')); dir(fullfile(two_d_dir,'*.sbatch')); ...
    dir(fullfile(one_d_dir,'*.sh'))];
for k = 1:numel(campaign_files)
    text = fileread(fullfile(campaign_files(k).folder,campaign_files(k).name));
    assert(~contains(text,'''AppeloAlpha'',1.3') && ...
        ~contains(text,'''AppeloAlpha'',2.35') && ...
        ~contains(text,'''AppeloAlpha'',3.4'), ...
        'Bouchet_Kantola_CEC13:LiteralAlpha', ...
        '%s spells alpha instead of reading the parameter function.', ...
        campaign_files(k).name);
end
assert(contains(one_d_task,'Assert_Base_Provenance(saved.run_provenance,run_id,1,0,') && ...
    contains(two_d_task,'Assert_Base_Provenance(saved.run_provenance,run_id,12,workers,') && ...
    contains(one_d_task,'''ParallelWorkers'',0,''SaveResults'',true') && ...
    contains(two_d_task,'''GridNx'',2,''GridNy'',2') && ...
    contains(two_d_task,'''ParallelWorkers'',workers,''SaveResults'',true') && ...
    contains(two_d_task,'Resolve_2D_Parfor_Workers(12)') && ...
    contains(two_d_task,'Check_Lateral_Conservation('), ...
    'Bouchet_Kantola_CEC13:WrapperChecks', ...
    'A production wrapper lost its provenance, worker or conservation check.');

%% Names must not shadow shared code.
shared = [dir(fullfile(repo_root,'v2','run','*.m')); dir(fullfile(code_dir,'*.m')); ...
    dir(fullfile(code_dir,'Tests','*.m'))];
own = [dir(fullfile(one_d_dir,'*.m')); dir(fullfile(two_d_dir,'*.m'))];
clash = intersect({shared.name},{own.name});
assert(isempty(clash),'Bouchet_Kantola_CEC13:NameShadow', ...
    'Campaign files shadow shared code: %s',strjoin(clash,', '));

%% Slurm resources and identity strings.
one_d_sbatch = fileread(fullfile(one_d_dir,'submit_base_1d.sbatch'));
two_d_sbatch = fileread(fullfile(two_d_dir,'submit_base_2d.sbatch'));
one_d_tokens = {'#SBATCH --job-name=Base1D','#SBATCH --partition=day', ...
    '#SBATCH --constraint=cpumodel:9575f','#SBATCH --nodes=1', ...
    '#SBATCH --ntasks=3','#SBATCH --cpus-per-task=1','#SBATCH --mem=24G', ...
    '#SBATCH --time=06:00:00','#SBATCH --requeue', ...
    ['export TC_CAMPAIGN_TAG="' one_d_tag '${case_suffix}"'], ...
    'export TC_NUMERICAL_IDENTITY=''cpumodel=9575f;matlab_release=2025a;single_comp_thread=1;parallel_workers=0''', ...
    'export TC_CKPT_MINUTES=30','export TC_PARALLEL_WORKERS=0', ...
    'TC_ALL12_CONTROLLER_TOKEN','CEC13_ALL12_V1', ...
    'Validate_Base_1D','Run_Base_1D_Task', ...
    'runs=(10 11 12)','--mem=8G'};
two_d_tokens = {'#SBATCH --job-name=Base2D','#SBATCH --array=1-9%9', ...
    '#SBATCH --partition=week','#SBATCH --constraint=cpumodel:9575f', ...
    '#SBATCH --nodes=1','#SBATCH --ntasks=1','#SBATCH --cpus-per-task=6', ...
    '#SBATCH --mem=48G','#SBATCH --time=4-00:00:00','#SBATCH --requeue', ...
    ['export TC_CAMPAIGN_TAG="' two_d_tag '${case_suffix}"'], ...
    'export TC_NUMERICAL_IDENTITY=''cpumodel=9575f;matlab_release=2025a;single_comp_thread=1;parallel_workers=6''', ...
    'export TC_CKPT_MINUTES=10','export TC_PARALLEL_WORKERS=6', ...
    'TC_ALL12_CONTROLLER_TOKEN','CEC13_ALL12_V1', ...
    'Run_Base_2D_Task'};
assert(all(cellfun(@(t) contains(one_d_sbatch,t),one_d_tokens)), ...
    'Bouchet_Kantola_CEC13:OneDBatch','The 1-D batch file lost a pinned setting.');
assert(all(cellfun(@(t) contains(two_d_sbatch,t),two_d_tokens)), ...
    'Bouchet_Kantola_CEC13:TwoDBatch','The 2-D batch file lost a pinned setting.');
assert(~contains(one_d_sbatch,'TC_SCENARIO=EQUIV_1D_TMP') && ...
    ~contains(two_d_sbatch,'TC_SCENARIO=EQUIV_1D_TMP'), ...
    'Bouchet_Kantola_CEC13:BaselineRebuild', ...
    'The batch files must never rebuild the equivalence baseline.');
%% The audit holds the 2-D driver to the baseline bit for bit, so the script
%% that builds the baseline must run under the campaign's numerical identity.
regen = fileread(fullfile(repo_root,'regen_equiv_1d.sbatch'));
regen_tokens = {'#SBATCH --constraint=cpumodel:9575f', ...
    '#SBATCH --ntasks=1','#SBATCH --cpus-per-task=1', ...
    'export OMP_NUM_THREADS=1','export MKL_NUM_THREADS=1', ...
    'export OPENBLAS_NUM_THREADS=1','export TC_CKPT_MINUTES=0', ...
    'export TC_CASE=5','export TC_SCENARIO=EQUIV_1D_TMP','export TC_NDAYS=10', ...
    'matlab -singleCompThread -batch', ...
    'assert(strcmp(version(''-release''),''2025a'')'};
assert(all(cellfun(@(t) contains(regen,t),regen_tokens)), ...
    'Bouchet_Kantola_CEC13:BaselineScript', ...
    'regen_equiv_1d.sbatch must build the baseline on cpumodel:9575f with one computational thread.');

%% Controller graph.
controller = fileread(fullfile(one_d_dir,'submit_all_12.sh'));
controller_tokens = { ...
    ['campaign_name_1d=''' one_d_tag ''''],['campaign_name_2d=''' two_d_tag ''''], ...
    'TC_ALL12_CONTROLLER_TOKEN=CEC13_ALL12_V1', ...
    '--partition=day --ntasks=1 --cpus-per-task=6 --mem=40G --time=04:00:00', ...
    '--job-name="Base1Dcheck${case_suffix}"', ...
    '--partition=day --array=1 --ntasks=1 --cpus-per-task=6 --mem=32G --time=04:00:00', ...
    '--job-name="Base2Dcheck${case_suffix}"', ...
    'production_dependency="afterok:${validation_1d_job}:${validation_2d_job}"', ...
    '--kill-on-invalid-dep=yes','scontrol release "${submitted_jobs[@]}"', ...
    'TC_ALL12_STAGE','shared_pins.sha256', ...
    'dims="${TC_ALL12_DIMS:-all}"','production_dependency="afterok:${validation_1d_job}"', ...
    'if [[ "$dims" == all ]]; then', ...
    'TC_ERW_results_Kantola_crop_control.mat', ...
    'TC_BOUCHET_ACCOUNT','sbatch --parsable --hold --account="$TC_BOUCHET_ACCOUNT"'};
assert(all(cellfun(@(t) contains(controller,t),controller_tokens)), ...
    'Bouchet_Kantola_CEC13:Controller','The controller lost a pinned setting.');
assert(numel(strfind(controller,'TC_VALIDATE_ONLY=1')) == 2 && ...
    ~contains(controller,'TC_REBUILD_EQUIVALENCE=1'), ...
    'Bouchet_Kantola_CEC13:ControllerModes', ...
    'The controller must submit two validations and no baseline rebuild.');
%% With TC_ALL12_DIMS=1d the 2-D validation and the 2-D production are the
%% only submissions left out, and the 1-D production waits for its own
%% validation.
gate = 'if [[ "$dims" == all ]]; then';
gate_at = strfind(controller,gate);
only_all = {};
for k = 1:numel(gate_at)
    words = strsplit(strtrim(strtok(strtrim(controller(gate_at(k)+numel(gate):end)),newline)));
    if strcmp(words{1},'submit_job')
        only_all{end+1} = words{2}; %#ok<AGROW>
    end
end
assert(isequal(sort(only_all),{'production_2d_job','validation_2d_job'}) && ...
    numel(strfind(controller,'submit_job validation_1d_job')) == 1 && ...
    numel(strfind(controller,'submit_job production_1d_job')) == 1, ...
    'Bouchet_Kantola_CEC13:ControllerDims', ...
    'TC_ALL12_DIMS=1d must leave out the 2-D validation and production only.');

%% Documentation sentinels.
one_d_readme = fileread(fullfile(one_d_dir,'README.md'));
two_d_readme = fileread(fullfile(two_d_dir,'README.md'));
assert(contains(one_d_readme,one_d_tag) && contains(one_d_readme,'Do not call') && ...
    contains(one_d_readme,'a3p4_kn0p0048_kbfree') && ...
    contains(two_d_readme,two_d_tag) && contains(two_d_readme,'Do not call') && ...
    contains(two_d_readme,'4-00:00:00'), ...
    'Bouchet_Kantola_CEC13:Readme','A campaign README lost its sentinels.');

fprintf('PASS: calibrated CEC 13 all-12 campaign configuration\n');
end
