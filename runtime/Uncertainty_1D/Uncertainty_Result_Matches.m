function same = Uncertainty_Result_Matches(p,file_name,C,K,campaign,digest)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Whether a saved result is the run the ensemble expects: campaign C's arm
%% run with knobs K (Uncertainty_Knobs) under the campaign tag given.
%%   p          the result's run_provenance
%%   file_name  its file name, which alone carries the scenario and the
%%              calcite case (the provenance records neither)
%%   digest     the validation digest the result must carry, or '' for the
%%              original, whose campaign has its own
%% Alpha and the exchange constants are recorded per column (N_col x 1 and
%% N_col x 5), so every column is compared with the set's value. The
%% worker count is not compared: it moves no number, and the digest of a
%% member already covers the declared identity.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

fields = {'campaign','validation_fingerprint','n_days','n_columns', ...
    'last_application_year','KNmaxd','Kbot','biogeo_overrides', ...
    'dissolution_factor','saturation_exponent','AppeloAlpha','AppeloLogKH'};
same = isstruct(p) && all(isfield(p,fields));
if ~same; return; end

scenario_tag = '';
if ~isempty(C.scenario); scenario_tag = ['__' C.scenario]; end
case_tag = '';
if ~isempty(C.calcite_case); case_tag = sprintf('__case%d',C.calcite_case); end
logKH_tol = eps(max(abs(K.AppeloLogKH)));
same = strcmp(p.campaign,campaign) && ...
    (isempty(digest) || strcmp(p.validation_fingerprint,digest)) && ...
    p.n_days == C.n_days && p.n_columns == C.n_columns && ...
    p.last_application_year == C.last_application_year && ...
    abs(p.KNmaxd-K.KNmaxd) <= eps(K.KNmaxd) && isequaln(p.Kbot,K.Kbot) && ...
    isequaln(p.biogeo_overrides,K.BiogeoOverrides) && ...
    isequaln(p.dissolution_factor,K.DissolutionFactor) && ...
    p.saturation_exponent == K.SaturationExponent && ...
    isequal(size(p.AppeloAlpha),[C.n_columns 1]) && ...
    all(abs(p.AppeloAlpha-K.AppeloAlpha) <= eps(K.AppeloAlpha)) && ...
    isequal(size(p.AppeloLogKH),[C.n_columns numel(K.AppeloLogKH)]) && ...
    all(abs(p.AppeloLogKH-K.AppeloLogKH(:).') <= logKH_tol,'all') && ...
    strcmp(regexp(file_name,'__ssp[0-9]{3}(?=__)','match','once'),scenario_tag) && ...
    strcmp(regexp(file_name,'__case[0-9]+(?=__)','match','once'),case_tag);
end
