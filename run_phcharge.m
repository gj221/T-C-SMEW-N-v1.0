function run_phcharge(run_id)
root = fileparts(mfilename('fullpath'));
addpath(fullfile(root,'v2','run'), ...
    fullfile(root,'runtime','Base_1D'));
P = Campaign_Parameters;
setenv('TC_CKPT_MINUTES','30');
Run_One_Subfield(run_id,'NDays',P.NDays,'StartDate',P.StartDate, ...
    'AppeloAlpha',P.AppeloAlpha,'AppeloLogKH',P.AppeloLogKH, ...
    'KNmaxd',P.KNmaxd,'Kbot',P.Kbot,'ParallelWorkers',0, ...
    'SaveResults',true,'ResultDirectory',fullfile(root,'results'));
end
