function summary = Field_Grid_Summary_Table(setups,source_indices,field_name)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Per-polygon area, cell-size, grid and geometry-fidelity summary.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

cell_size = reshape([setups.cell_size_m],[],1);
grid_columns = reshape([setups.main_grid_nx],[],1);
grid_rows = reshape([setups.main_grid_ny],[],1);
grid_slot_count = reshape([setups.grid_slot_count],[],1);
cell_count = reshape([setups.N_cells],[],1);
field_area = reshape([setups.field_area_m2],[],1);
simulated_area = reshape([setups.simulated_area_m2],[],1);
outside_area = simulated_area-field_area;
source_vertex_count = reshape([setups.source_finite_vertex_count],[],1);
polygon_vertex_count = reshape( ...
    [setups.projected_polygon_vertex_count],[],1);
projection_roundtrip_error = reshape( ...
    [setups.projection_roundtrip_max_error_m],[],1);
source_to_polygon_error = reshape( ...
    [setups.source_to_polygon_max_error_m],[],1);
summary = table((1:numel(setups))',reshape(source_indices,[],1), ...
    reshape(field_name,[],1),cell_size,grid_columns,grid_rows, ...
    grid_slot_count,cell_count,field_area,field_area/4046.8564224, ...
    simulated_area,outside_area,field_area./simulated_area, ...
    outside_area./simulated_area,source_vertex_count, ...
    polygon_vertex_count,projection_roundtrip_error, ...
    source_to_polygon_error, ...
    'VariableNames',{'Polygon','SourceFeatureIndices','Field', ...
    'CellSizeM','GridColumns','GridRows','GridSlotCount','CellCount', ...
    'FieldAreaM2','FieldAreaAcres','SimulatedAreaM2','OutsideAreaM2', ...
    'FieldFraction','OutsideFraction','SourceVertexCount', ...
    'ProjectedPolygonVertexCount','ProjectionRoundTripMaxM', ...
    'SourceToPolygonMaxM'});

end
