function w = Daily_WFPS_From_Hourly(O,p,n_state)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Daily_WFPS_From_Hourly
%%
%% Depth-weighted WFPS of the biogeochemical layer [%]. The hourly day
%% ending at retained state row j is stored in output row j.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

if ndims(O) == 3
    assert(size(O,3) == 1, ...
        'Plot_1D_Then_All_12:WFPSColumnCount', ...
        'A 1-D WFPS trace must contain one model column.');
    O = O(:,:,1);
end
assert(isnumeric(O) && ismatrix(O) && all(isfinite(O(:))), ...
    'Plot_1D_Then_All_12:BadWFPS', ...
    'Hourly soil moisture must be a finite numeric matrix.');
assert(isscalar(n_state) && isfinite(n_state) && ...
    n_state == floor(n_state) && n_state >= 2, ...
    'Plot_1D_Then_All_12:BadWFPSStateCount', ...
    'The retained WFPS state count must be an integer of at least two.');

n_day = n_state-1;
assert(size(O,1) == 24*n_day, ...
    'Plot_1D_Then_All_12:WFPSLength', ...
    'Hourly soil moisture has %d rows; expected 24 x %d days.', ...
    size(O,1),n_day);

Bio_Zs = double(p.Bio_Zs(:).');
Osat = double(p.Soil_Param.Osat(:).');
assert(size(O,2) == numel(Bio_Zs) && numel(Osat) == numel(Bio_Zs) && ...
    all(isfinite(Bio_Zs)) && all(Bio_Zs >= 0) && ...
    all(isfinite(Osat)) && all(Osat > 0), ...
    'Plot_1D_Then_All_12:WFPSLayerShape', ...
    'Soil moisture, biogeochemical depth and saturation must share one valid layer axis.');

sat_water = sum(Bio_Zs.*Osat);
assert(isfinite(sat_water) && sat_water > 0, ...
    'Plot_1D_Then_All_12:BadWFPSSaturation', ...
    'Depth-integrated saturated water storage must be positive.');
hourly = O*Bio_Zs.'/sat_water*100;
%% BIOGEO fills state row j at 01:00 from the previous 24 hours, so row 2
%% holds hour 1 alone and later rows run from 01:00 to 00:00.
daily = mean(reshape(hourly(2:24*(n_day-1)+1),24,n_day-1),1).';
w = [NaN; hourly(1); daily];
end
