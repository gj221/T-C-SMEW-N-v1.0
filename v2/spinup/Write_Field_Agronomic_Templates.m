function files = Write_Field_Agronomic_Templates(shape_file,output_directory, ...
        cell_size_m,feature_indices,required_field_fraction)
%% required_field_fraction: optional grid coverage rule passed to
%% Build_Shapefile_Grid_Setups (default 0.95; lower only for a coarse
%% diagnostic grid, and then use the same value everywhere downstream).
if nargin < 5; required_field_fraction = []; end
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Write one cell input template for each disconnected shapefile polygon.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

if nargin < 3
    cell_size_m = [];
end
if nargin < 4
    feature_indices = [];
end
if ~isfile(shape_file)
    error('Write_Field_Agronomic_Templates:MissingShapefile', ...
        'Shapefile does not exist: %s',char(string(shape_file)));
end
if ~(ischar(output_directory) || ...
        (isstring(output_directory) && isscalar(output_directory)))
    error('Write_Field_Agronomic_Templates:BadOutput', ...
        'output_directory must be a character vector or scalar string.');
end
output_directory = char(output_directory);
if ~exist(output_directory,'dir')
    mkdir(output_directory);
end

spinup_directory = fileparts(mfilename('fullpath'));
code_directory = fullfile(fileparts(spinup_directory),'T&C_Code');
addpath(code_directory);
setups = Build_Shapefile_Grid_Setups(shape_file,cell_size_m,feature_indices, ...
    required_field_fraction);
[~,shape_name] = fileparts(shape_file);
files = cell(numel(setups),1);
for p = 1:numel(setups)
    topo = setups(p);
    n = topo.N_cells;
    source_features = strjoin(arrayfun(@num2str,topo.source_feature_indices, ...
        'UniformOutput',false),'_');
    %% Exchangeable base saturation (Ca, Mg, K as fractions of CEC) has no
    %% pedotransfer baseline -- the spin-up's own exchanger IS the
    %% baseline -- so it carries measured_ columns and a toggle only.
    T = table(topo.cell_id,repmat(p,n,1),repmat(string(source_features),n,1), ...
        topo.cell_xc_projected_m,topo.cell_yc_projected_m, ...
        nan(n,1),nan(n,1),false(n,1),nan(n,1),nan(n,1), ...
        nan(n,1),nan(n,1),false(n,1),nan(n,1),nan(n,1),false(n,1), ...
        nan(n,1),nan(n,1),false(n,1), ...
        nan(n,1),nan(n,1),nan(n,1),false(n,1), ...
        'VariableNames',{'cell_id','polygon_index','source_feature_indices', ...
        'cell_x_projected_m','cell_y_projected_m','baseline_bulk_pH', ...
        'measured_bulk_pH','use_measured_bulk_pH','baseline_sand_fraction', ...
        'baseline_clay_fraction','measured_sand_fraction', ...
        'measured_clay_fraction','use_measured_texture','baseline_OM_fraction', ...
        'measured_OM_fraction','use_measured_OM','baseline_CEC_cmolc_kg', ...
        'measured_CEC_cmolc_kg','use_measured_CEC', ...
        'measured_bs_Ca_fraction','measured_bs_Mg_fraction', ...
        'measured_bs_K_fraction','use_measured_base_saturation'});
    files{p} = fullfile(output_directory,sprintf( ...
        'Cell_Agronomic_%s_polygon_%02d.csv',shape_name,p));
    if isfile(files{p})
        error('Write_Field_Agronomic_Templates:FileExists', ...
            'Template already exists: %s',files{p});
    end
    writetable(T,files{p});
end
end
