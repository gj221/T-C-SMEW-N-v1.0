function report = Calibrate_Kantola_Bulk_pH(varargin)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Calibrate the Appelo alpha against Beerling bulk-soil observations.
%%
%% This is a screening calibration, not an automatic parameter fit. It
%% runs paired control and basalt columns to one year after the first rock
%% application, then reports bulk-pH and base-saturation errors separately.
%% CEC, selectivity constants, weathering kinetics and boundary inputs are
%% not adjusted.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

opt = struct('AlphaGrid',[0.4 0.8 1.3],'NDays',679, ...
    'ObservationBoundary','pre_application', ...
    'MaxConcurrent',2,'PollSeconds',60,'DryRun',false,'Overwrite',false, ...
    'ResultDirectory','','LogDirectory','');
if mod(numel(varargin),2) ~= 0
    error('Calibrate_Kantola_Bulk_pH:BadOptions', ...
        'Options must be name/value pairs.');
end
for k = 1:2:numel(varargin)
    name = char(varargin{k});
    if ~isfield(opt,name)
        error('Calibrate_Kantola_Bulk_pH:BadOptions','Unknown option %s.',name);
    end
    opt.(name) = varargin{k+1};
end
if ~(isnumeric(opt.AlphaGrid) && isvector(opt.AlphaGrid) && ...
        ~isempty(opt.AlphaGrid) && all(isfinite(opt.AlphaGrid)) && ...
        all(opt.AlphaGrid >= 0) && ...
        numel(unique(opt.AlphaGrid)) == numel(opt.AlphaGrid))
    error('Calibrate_Kantola_Bulk_pH:BadOptions', ...
        'AlphaGrid must contain unique finite nonnegative values.');
end
if ~(isnumeric(opt.NDays) && isscalar(opt.NDays) && isfinite(opt.NDays) && ...
        opt.NDays == fix(opt.NDays) && opt.NDays >= 679)
    error('Calibrate_Kantola_Bulk_pH:BadOptions', ...
        'NDays must reach day 679, one year after the first application.');
end
if ~(islogical(opt.DryRun) && isscalar(opt.DryRun) && ...
        islogical(opt.Overwrite) && isscalar(opt.Overwrite))
    error('Calibrate_Kantola_Bulk_pH:BadOptions', ...
        'DryRun and Overwrite must be scalar logical values.');
end
if ~(ischar(opt.ResultDirectory) || ...
        (isstring(opt.ResultDirectory) && isscalar(opt.ResultDirectory))) || ...
        ~(ischar(opt.LogDirectory) || ...
        (isstring(opt.LogDirectory) && isscalar(opt.LogDirectory)))
    error('Calibrate_Kantola_Bulk_pH:BadOptions', ...
        'ResultDirectory and LogDirectory must be character vectors or scalar strings.');
end
boundary = lower(string(opt.ObservationBoundary));
if ~isscalar(boundary) || ~ismember(boundary,["pre_application","post_application"])
    error('Calibrate_Kantola_Bulk_pH:BadOptions', ...
        'ObservationBoundary must be pre_application or post_application.');
end
opt.ObservationBoundary = char(boundary);

here = fileparts(mfilename('fullpath'));
v2 = fileparts(here);
addpath(fullfile(v2,'run'),fullfile(v2,'T&C_Code'));
obs_file = fullfile(v2,'Experimental observations','Web plot digitizer', ...
    'Data_Beerling.mat');
data = load(obs_file,'pH_Exp','CEC_Exp');
targets = observation_targets(data);
output_dir = char(opt.ResultDirectory);
if isempty(output_dir); output_dir = fullfile(v2,'SIM','Calibration_Kantola_pH'); end
log_dir = char(opt.LogDirectory);

template = struct('alpha',NaN,'control_file','','basalt_file','', ...
    'control_pre_application_bulk_pH',NaN, ...
    'basalt_pre_application_bulk_pH',NaN, ...
    'control_post_application_bulk_pH',NaN, ...
    'basalt_post_application_bulk_pH',NaN, ...
    'delta_pre_application_bulk_pH',NaN, ...
    'delta_post_application_bulk_pH',NaN, ...
    'control_pre_application_base_sat_pct',NaN, ...
    'basalt_pre_application_base_sat_pct',NaN, ...
    'control_post_application_base_sat_pct',NaN, ...
    'basalt_post_application_base_sat_pct',NaN, ...
    'delta_pre_application_base_sat_pct',NaN, ...
    'delta_post_application_base_sat_pct',NaN, ...
    'pre_bulk_pH',NaN,'control_bulk_pH',NaN,'basalt_bulk_pH',NaN, ...
    'delta_bulk_pH',NaN,'pH_rmse',NaN,'pH_response_error_by_depth',[NaN NaN], ...
    'pre_base_sat_pct',NaN,'control_base_sat_pct',NaN, ...
    'basalt_base_sat_pct',NaN,'delta_base_sat_pct',NaN, ...
    'base_sat_rmse_pct',NaN,'base_sat_response_error_pct_by_depth',[NaN NaN], ...
    'exchange_closure_max',NaN);
candidates = repmat(template,numel(opt.AlphaGrid),1);

fprintf('\n=== Kantola bulk-pH alpha screen ===\n');
fprintf('target date: %s   depth representation: 0-30 cm\n', ...
    datestr(targets.sample_date,'dd-mmm-yyyy'));
fprintf('observation boundary: %s\n',opt.ObservationBoundary);
fprintf(['observed basalt-control response: pH 0-10 %+.3f, 10-30 %+.3f; ' ...
    'base saturation 0-10 %+.2f %%, 10-30 %+.2f %%\n'], ...
    targets.delta_bulk_pH,targets.delta_base_sat_pct);

for q = 1:numel(opt.AlphaGrid)
    alpha = opt.AlphaGrid(q);
    plan = Run_All_12_Parallel('Runs',[10 11],'NDays',opt.NDays, ...
        'AppeloAlpha',alpha,'MaxConcurrent',opt.MaxConcurrent, ...
        'PollSeconds',opt.PollSeconds,'DryRun',opt.DryRun, ...
        'Overwrite',opt.Overwrite,'ResultDirectory',output_dir, ...
        'LogDirectory',log_dir);
    candidates(q).alpha = alpha;
    candidates(q).control_file = plan(1).result_file;
    candidates(q).basalt_file = plan(2).result_file;
    if opt.DryRun
        continue
    end

    control = Kantola_Bulk_pH_Model_Summary(plan(1).result_file,targets.sample_date, ...
        opt.ObservationBoundary);
    basalt = Kantola_Bulk_pH_Model_Summary(plan(2).result_file,targets.sample_date, ...
        opt.ObservationBoundary);
    metrics = calibration_metrics(control,basalt,targets);
    names = fieldnames(metrics);
    for n = 1:numel(names)
        candidates(q).(names{n}) = metrics.(names{n});
    end
    fprintf(['alpha %.3g: bulk pH control %.3f, basalt %.3f, delta %+.3f, ' ...
        'pH RMSE %.3f, base-saturation RMSE %.2f %%\n'], ...
        alpha,metrics.control_bulk_pH,metrics.basalt_bulk_pH, ...
        metrics.delta_bulk_pH,metrics.pH_rmse,metrics.base_sat_rmse_pct);
    persist_report(output_dir,opt,targets,candidates);
end

report = struct('options',opt,'targets',targets,'candidates',candidates);

end

function targets = observation_targets(data)
%% The model has one 0-30 cm state, while observations remain separate at
%% 0-10 and 10-30 cm.  pH is not arithmetically mixed and base saturation
%% is not combined without soil-mass and CEC weights.
pH_control = [data.pH_Exp.control_0(:) data.pH_Exp.control_10(:)];
pH_basalt = [data.pH_Exp.basalt_0(:) data.pH_Exp.basalt_10(:)];
base_control = [data.CEC_Exp.control_0(:) data.CEC_Exp.control_10(:)];
base_basalt = [data.CEC_Exp.basalt_0(:) data.CEC_Exp.basalt_10(:)];

targets.sample_date = datenum(2017,11,10);
targets.depth_cm = [0 10; 10 30];
targets.pre_bulk_pH = -log10(0.5*(10.^(-pH_control(1,:))+10.^(-pH_basalt(1,:))));
targets.control_bulk_pH = pH_control(2,:);
targets.basalt_bulk_pH = pH_basalt(2,:);
targets.delta_bulk_pH = pH_basalt(2,:)-pH_control(2,:);
targets.pre_base_sat_pct = 0.5*(base_control(1,:)+base_basalt(1,:));
targets.control_base_sat_pct = base_control(2,:);
targets.basalt_base_sat_pct = base_basalt(2,:);
targets.delta_base_sat_pct = base_basalt(2,:)-base_control(2,:);
end

function metrics = calibration_metrics(control,basalt,targets)
metrics.control_pre_application_bulk_pH = control.pre_application_bulk_pH;
metrics.basalt_pre_application_bulk_pH = basalt.pre_application_bulk_pH;
metrics.control_post_application_bulk_pH = control.post_application_bulk_pH;
metrics.basalt_post_application_bulk_pH = basalt.post_application_bulk_pH;
metrics.delta_pre_application_bulk_pH = ...
    basalt.pre_application_bulk_pH-control.pre_application_bulk_pH;
metrics.delta_post_application_bulk_pH = ...
    basalt.post_application_bulk_pH-control.post_application_bulk_pH;
metrics.control_pre_application_base_sat_pct = control.pre_application_base_sat_pct;
metrics.basalt_pre_application_base_sat_pct = basalt.pre_application_base_sat_pct;
metrics.control_post_application_base_sat_pct = control.post_application_base_sat_pct;
metrics.basalt_post_application_base_sat_pct = basalt.post_application_base_sat_pct;
metrics.delta_pre_application_base_sat_pct = ...
    basalt.pre_application_base_sat_pct-control.pre_application_base_sat_pct;
metrics.delta_post_application_base_sat_pct = ...
    basalt.post_application_base_sat_pct-control.post_application_base_sat_pct;
metrics.pre_bulk_pH = -log10(mean(10.^(-[control.pre_bulk_pH basalt.pre_bulk_pH])));
metrics.control_bulk_pH = control.sample_bulk_pH;
metrics.basalt_bulk_pH = basalt.sample_bulk_pH;
metrics.delta_bulk_pH = metrics.basalt_bulk_pH-metrics.control_bulk_pH;
pH_residual = [metrics.pre_bulk_pH-targets.pre_bulk_pH(:); ...
    metrics.control_bulk_pH-targets.control_bulk_pH(:); ...
    metrics.basalt_bulk_pH-targets.basalt_bulk_pH(:); ...
    metrics.delta_bulk_pH-targets.delta_bulk_pH(:)];
metrics.pH_rmse = sqrt(mean(pH_residual.^2));
metrics.pH_response_error_by_depth = ...
    metrics.delta_bulk_pH-targets.delta_bulk_pH;

metrics.pre_base_sat_pct = mean([control.pre_base_sat_pct basalt.pre_base_sat_pct]);
metrics.control_base_sat_pct = control.sample_base_sat_pct;
metrics.basalt_base_sat_pct = basalt.sample_base_sat_pct;
metrics.delta_base_sat_pct = metrics.basalt_base_sat_pct-metrics.control_base_sat_pct;
base_residual = [metrics.pre_base_sat_pct-targets.pre_base_sat_pct(:); ...
    metrics.control_base_sat_pct-targets.control_base_sat_pct(:); ...
    metrics.basalt_base_sat_pct-targets.basalt_base_sat_pct(:); ...
    metrics.delta_base_sat_pct-targets.delta_base_sat_pct(:)];
metrics.base_sat_rmse_pct = sqrt(mean(base_residual.^2));
metrics.base_sat_response_error_pct_by_depth = ...
    metrics.delta_base_sat_pct-targets.delta_base_sat_pct;
metrics.exchange_closure_max = max(control.exchange_closure_max, ...
    basalt.exchange_closure_max);
end

function persist_report(out_dir,opt,targets,candidates)
if ~exist(out_dir,'dir'); mkdir(out_dir); end
stem = sprintf('kantola_bulk_pH_alpha_screen_%dd',opt.NDays);
save(fullfile(out_dir,[stem '.mat']),'opt','targets','candidates');
writetable(struct2table(candidates),fullfile(out_dir,[stem '.csv']));
end
