function [P43_after,P_weathering_release_umol] = ...
    ERW_Return_Weathered_Phosphorus(P43_before,PO4_tot_end,aP, ...
        P_weathering_release_by_step)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Return the current ERW-window mineral P release to T&C in g P m^-2.
%% The aP = 1 path already transfers the complete dissolved inventory.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

if ~(isnumeric(P43_before) && isreal(P43_before) && isscalar(P43_before) && ...
        isfinite(P43_before) && P43_before >= 0) || ...
        ~(isnumeric(PO4_tot_end) && isreal(PO4_tot_end) && ...
        isscalar(PO4_tot_end) && isfinite(PO4_tot_end) && PO4_tot_end >= 0) || ...
        ~(isnumeric(aP) && isreal(aP) && isscalar(aP) && ...
        isfinite(aP) && aP >= 0 && aP <= 1)
    error('ERW:invalidPhosphorusState', ...
        'P43, PO4_tot and aP must be finite, nonnegative scalars with 0 <= aP <= 1.');
end
if ~(isnumeric(P_weathering_release_by_step) && ...
        isreal(P_weathering_release_by_step)) || ...
        any(~isfinite(P_weathering_release_by_step(:))) || ...
        any(P_weathering_release_by_step(:) < 0)
    error('ERW:invalidPhosphorusRelease', ...
        'Weathered phosphorus release must be finite and nonnegative.');
end
P_weathering_release_umol = sum(P_weathering_release_by_step(:));
if ~isfinite(P_weathering_release_umol)
    error('ERW:invalidPhosphorusRelease', ...
        'Weathered phosphorus release must have a finite sum.');
end

expected_PO4_tot = aP*P43_before/31*1e6 + P_weathering_release_umol;
budget_scale = max([1,abs(expected_PO4_tot),abs(PO4_tot_end)]);
if abs(PO4_tot_end-expected_PO4_tot) > 1e-10*budget_scale
    error('ERW:phosphorusBudget', ...
        'ERW phosphorus inventory does not close across the current window.');
end

if aP == 1
    P43_after = PO4_tot_end*31/1e6;
else
    P43_after = P43_before + P_weathering_release_umol*31/1e6;
end
end
