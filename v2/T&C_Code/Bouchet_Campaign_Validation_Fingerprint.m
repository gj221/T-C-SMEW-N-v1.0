function fp = Bouchet_Campaign_Validation_Fingerprint( ...
    v2_dir,runtime_dir,campaign_tag,n_columns,parallel_workers,varargin)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Content and numerical-platform identity for a Bouchet campaign gate.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

if ~(ischar(campaign_tag) || (isstring(campaign_tag) && isscalar(campaign_tag)))
    error('Bouchet:ValidationCampaign','campaign_tag must be text.');
end
if ~(isscalar(n_columns) && isfinite(n_columns) && ...
        n_columns == fix(n_columns) && n_columns >= 1)
    error('Bouchet:ValidationColumns','n_columns must be a positive integer.');
end
if ~(isscalar(parallel_workers) && isfinite(parallel_workers) && ...
        parallel_workers == fix(parallel_workers) && parallel_workers >= 0)
    error('Bouchet:ValidationWorkers', ...
        'parallel_workers must be a nonnegative integer.');
end

expected_identity = sprintf(['cpumodel=9575f;matlab_release=2025a;' ...
    'single_comp_thread=1;parallel_workers=%d'],parallel_workers);
matlab_release = version('-release');
if ~strcmp(matlab_release,'2025a')
    error('Bouchet:ValidationMatlabRelease', ...
        'Bouchet campaign validation requires MATLAB R2025a.');
end
actual_identity = strtrim(getenv('TC_NUMERICAL_IDENTITY'));
if ~strcmp(actual_identity,expected_identity)
    error('Bouchet:ValidationNumericalIdentity', ...
        'TC_NUMERICAL_IDENTITY must be %s.',expected_identity);
end

v2_dir = char(v2_dir);
runtime_dir = char(runtime_dir);
code_dir = fullfile(v2_dir,'T&C_Code');
blas = regexprep(strtrim(evalc('version -blas')),'\s+',' ');
runtime_identity = sprintf( ...
    ['campaign=%s;%s;matlab=%s;computer=%s;blas=%s;' ...
     'max_threads=%d'], ...
    char(campaign_tag),actual_identity,version,computer,blas,maxNumCompThreads);
dependencies = { ...
    fullfile(code_dir,'*.m'), ...
    fullfile(code_dir,'Parameters','*.m'), ...
    fullfile(code_dir,'Tests','*.m'), ...
    fullfile(code_dir,'Tests','Fixtures','*.mat'), ...
    fullfile(code_dir,'Inputs','Data_Kantola.mat'), ...
    fullfile(code_dir,'Inputs','Data_Kantola_BG.mat'), ...
    fullfile(code_dir,'Inputs','Ca_Data.mat'), ...
    fullfile(code_dir,'Inputs','All_deposition_data.mat'), ...
    fullfile(code_dir,'Inputs','ERW_MOD_PARAM_parameters.xlsx'), ...
    fullfile(code_dir,'Inputs','blueridge_CDF_data.json'), ...
    fullfile(v2_dir,'run','*.m'), ...
    fullfile(v2_dir,'audit','*.m'), ...
    fullfile(v2_dir,'plotting','*.m'), ...
    fullfile(v2_dir,'SIM','EQUIV_1D_TMP', ...
        'TC_ERW_results_Kantola_crop_control.mat'), ...
    fullfile(runtime_dir,'*.m'), ...
    fullfile(runtime_dir,'*.sbatch'), ...
    fullfile(runtime_dir,'*.sh'), ...
    fullfile(runtime_dir,'README.md')};
dependencies = [dependencies varargin];
fp = ERW_Checkpoint_Fingerprint( ...
    1826*24,n_columns,runtime_identity,dependencies{:});
end
