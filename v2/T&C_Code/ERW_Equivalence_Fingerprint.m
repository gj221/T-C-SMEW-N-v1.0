function fp = ERW_Equivalence_Fingerprint(v2_dir,n_days)
% Content identity for the saved single-column equivalence baseline.
%
% The inputs are the four files the Kantola control baseline reads
% (Run_One_Subfield, Biogeochemistry_IO), named one by one. Hashing every
% Inputs/*.mat tied the baseline to files it never opens: the scenario
% forcings Data_Kantola_ssp*.mat are copied into a root separately, and a
% baseline built before that copy was refused as stale by every campaign
% validation afterwards although nothing it depends on had changed.

if ~(isscalar(n_days) && isfinite(n_days) && n_days == fix(n_days) && n_days > 0)
    error('ERW:equivalenceDuration','n_days must be a positive integer.');
end

v2_dir = char(v2_dir);
code_dir = fullfile(v2_dir,'T&C_Code');
runtime_identity = sprintf( ...
    'case=5;layout=vertical_1d;scenario=control;matlab_release=%s', ...
    version('-release'));
fp = ERW_Checkpoint_Fingerprint(n_days*24,1, ...
    runtime_identity, ...
    fullfile(code_dir,'*.m'), ...
    fullfile(code_dir,'Parameters','*.m'), ...
    fullfile(code_dir,'Inputs','Data_Kantola.mat'), ...
    fullfile(code_dir,'Inputs','Data_Kantola_BG.mat'), ...
    fullfile(code_dir,'Inputs','Ca_Data.mat'), ...
    fullfile(code_dir,'Inputs','All_deposition_data.mat'), ...
    fullfile(code_dir,'Inputs','ERW_MOD_PARAM_parameters.xlsx'), ...
    fullfile(code_dir,'Inputs','blueridge_CDF_data.json'), ...
    fullfile(v2_dir,'run','*.m'));
v2_dir = strrep(v2_dir,char(92),'/');
fp = strrep(fp,char(92),'/');
fp = strrep(fp,v2_dir,'<V2>');
end
