       contains(submit_text,'count_production_results') && ...
       contains(summary_text,'assert_result_stamp_accepted(S.run_provenance') && ...
       contains(summary_text,'Bouchet_Joint_Sweep:ResultStampNotAccepted') && ...
       contains(summary_text,'row.row1_placeholder_plant_N_gN_m2') && ...
       contains(summary_text,'steps_per_day = nrow/nd;') && ...
       contains(summary_text,'row.ERW_steps_per_day') && ...
       contains(summary_text,'function season = pH_season_means(dates,pH)') && ...
       contains(summary_text,'function skill = n2o_cumulative_skill(dates,model,obs,treatment,case_tag)') && ...
       contains(summary_text,'objectives = [combination_table.N2O_cumulative_log_ratio_RMS, ...') && ...
       contains(summary_text,'combination_table.pH_season_discrete_RMSE, ...') && ...
       contains(summary_text,'combination_table.pH_difference_discrete_RMSE, ...') && ...
       contains(summary_text,'skill.discrete = residual_skill( ...') && ...
       contains(summary_text,'[season.mean-shallow, season.mean-deep],[shallow, deep]);') && ...
       contains(summary_text,'row.pH_season_discrete_RMSE = pH_season_skill.discrete.rmse;') && ...
       contains(summary_text,'r.pH_difference_discrete_RMSE = sqrt(mean([ ...') && ...
       contains(summary_text,'combination_table.Front_N2O_pH_season = pareto_minimize(objectives(:,[1 2]));') && ...
