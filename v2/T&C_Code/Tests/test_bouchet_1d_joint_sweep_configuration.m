    cases(1).id,stamp_digest,campaign_tag,n_days,start_date,results_dir);
Assert_Sweep_Provenance(independent_provenance,cases(1), ...
    stamp_digest,campaign_tag,n_days,start_date,results_dir);
packed_provenance = valid_provenance(cases(2),'packed', ...
    cases(2).combination_id,stamp_digest,campaign_tag,n_days,start_date,results_dir);
Assert_Sweep_Provenance(packed_provenance,cases(2), ...
    stamp_digest,campaign_tag,n_days,start_date,results_dir);
