assert(isscalar(baseline_at) && isscalar(validation_at) && ...
       isscalar(review_at) && isscalar(pilot_at) && ...
       isscalar(production_at) && isscalar(summary_at) && ...
       baseline_at < validation_at && validation_at < review_at && ...
       review_at < pilot_at && ...
       pilot_at < production_at && ...
       production_at < summary_at && ...
       contains(submit_text,'--dependency="afterok:${baseline_job}"') && ...
       contains(submit_text,'--dependency="afterok:${validation_job}"') && ...
       contains(submit_text, ...
           '--dependency="afterok:${exploratory_review_job}"') && ...
       contains(submit_text,'--dependency="afterok:${pilot_job}"') && ...
       contains(submit_text,'pilot_array=336') && ...
       contains(submit_text,'pilot_array=112') && ...
       contains(submit_text,'--array="$pilot_array"') && ...
       contains(submit_text,'--dependency="afterany:${production_job}"') && ...
       ~contains(submit_text,'--dependency="afterok:${production_job}"'), ...
    'Bouchet_Joint_Sweep:SubmissionGraph', ...
    'The baseline, validation, production or summary dependency changed.');

assert(contains(submit_text,'TC_EQUIVALENCE_BASELINE:-keep') && ...
       contains(submit_text,'rebuild_baseline=1') && ...
       contains(submit_text,'if (( rebuild_baseline )); then') && ...
