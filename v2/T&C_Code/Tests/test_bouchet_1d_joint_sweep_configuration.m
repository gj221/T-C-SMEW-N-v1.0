       contains(submit_text,'"$stamp_root/v2/plotting/*.m"') && ...
       contains(submit_text,'"$stamp_root/v2/audit/*.m"') && ...
       contains(submit_text,'"$stamp_root/runtime/$campaign_name/*.sh"') && ...
       contains(submit_text,'gate_result_count != 1') && ...
       contains(submit_text, ...
           'would fail with Bouchet:StaleResult after validation') && ...
       contains(submit_text, ...
           'find "$controller_lock_root" -type d -name ''run_*.lock''') && ...
       contains(submit_text,'Bouchet:RunLocked') && ...
       contains(readme_text,'Recovering a stale one-year gate') && ...
       contains(readme_text,'three job IDs') && ...
       contains(readme_text,'TC_EQUIVALENCE_BASELINE=rebuild'), ...
    'Bouchet_Joint_Sweep:BaselinePolicy', ...
    ['The equivalence-baseline policy, the full-stage stamp preflight ' ...
     'or its README changed.']);

runner_tokens = {'validation_stamp.txt', ...
    'Sweep_Fingerprint', ...
