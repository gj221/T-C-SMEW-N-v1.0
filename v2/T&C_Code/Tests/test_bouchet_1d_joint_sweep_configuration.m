bad_release_provenance.dissolution_factor = 0.5;
assert_throws(@() Assert_Sweep_Provenance( ...
    bad_release_provenance,cases(1),stamp_digest,campaign_tag,n_days, ...
    start_date,results_dir),'Bouchet_Joint_Sweep:WrongProvenance');

