function check_lineage_acceptance(campaign_dir)
% Exercise Accepted_Stamp_Digests on synthetic stamps in a
% temporary tree: a prior stamp that differs only in scoring-side files is
% accepted, every other difference is refused, and the archive must digest
% to its name.
repo = fullfile(tempname,'repo');
logs = fullfile(repo,'v2','logs','Subfield_12', ...
    'Calibration_Sweep_1D');
archive = fullfile(logs,'validation_stamps');
mkdir(archive);
cleanup = onCleanup(@() rmdir(fileparts(repo),'s')); %#ok<NASGU>
old_env = getenv('TC_ACCEPTED_RESULT_DIGESTS');
restore_env = onCleanup(@() setenv('TC_ACCEPTED_RESULT_DIGESTS',old_env)); %#ok<NASGU>
audit = fullfile(repo,'v2','T&C_Code','Tests','Kantola_N_Magnitude_Audit.m');
model = fullfile(repo,'v2','T&C_Code','BIOGEOCHEMISTRY_DYNAMIC3.m');
readme = fullfile(repo,'runtime', ...
    'Calibration_Sweep_1D','README.md');
h = @(k) repmat(dec2hex(k,1),1,64);
header = 'NN=43824;N_col=1|runtime=campaign=x;cpumodel=9575f;max_threads=1';
current = [header '|' audit ':' lower(h(1)) '|' model ':' lower(h(2)) '|' readme ':' lower(h(3))];
prior_ok = [header '|' audit ':' lower(h(4)) '|' model ':' lower(h(2)) '|' readme ':' lower(h(3))];
prior_bad = [header '|' audit ':' lower(h(1)) '|' model ':' lower(h(5)) '|' readme ':' lower(h(3))];
prior_runtime = ['NN=43824;N_col=1|runtime=campaign=y' '|' audit ':' lower(h(1)) '|' model ':' lower(h(2)) '|' readme ':' lower(h(3))];
write_stamp = @(text) write_text(fullfile(archive, ...
    [Fingerprint_Digest(text) '.txt']),text);
write_stamp(prior_ok); write_stamp(prior_bad); write_stamp(prior_runtime);
setenv('TC_ACCEPTED_RESULT_DIGESTS','');
[accepted,lineage] = Accepted_Stamp_Digests(current,logs,repo);
assert(isequal(accepted,{Fingerprint_Digest(current)}) && isempty(lineage), ...
    'Without a request only the current digest is accepted.');
setenv('TC_ACCEPTED_RESULT_DIGESTS',Fingerprint_Digest(prior_ok));
[accepted,lineage] = Accepted_Stamp_Digests(current,logs,repo);
assert(numel(accepted) == 2 && strcmp(accepted{2},Fingerprint_Digest(prior_ok)) && ...
       numel(lineage) == 1 && isequal(lineage(1).changed,{audit}), ...
    'A prior stamp differing only in a scoring-side file must be accepted.');
expect_rejected(current,logs,repo,Fingerprint_Digest(prior_bad), ...
    'Bouchet_Joint_Sweep:LineageRejected');
expect_rejected(current,logs,repo,Fingerprint_Digest(prior_runtime), ...
    'Bouchet_Joint_Sweep:LineageRuntime');
expect_rejected(current,logs,repo,lower(h(9)), ...
    'Bouchet_Joint_Sweep:LineageArchiveMissing');
write_text(fullfile(archive,[lower(h(9)) '.txt']),prior_ok);
expect_rejected(current,logs,repo,lower(h(9)), ...
    'Bouchet_Joint_Sweep:LineageArchiveMismatch');
% a rejected stamp does not block accepted ones offered alongside it; the
% controller joins digests with ':' because sbatch --export splits on ','
setenv('TC_ACCEPTED_RESULT_DIGESTS',[Fingerprint_Digest(prior_bad) ':' ...
    Fingerprint_Digest(prior_ok)]);
[accepted,lineage,rejected] = Accepted_Stamp_Digests(current,logs,repo);
assert(numel(accepted) == 2 && strcmp(accepted{2},Fingerprint_Digest(prior_ok)) && ...
       numel(lineage) == 1 && numel(rejected) == 1 && ...
       strcmp(rejected(1).identifier,'Bouchet_Joint_Sweep:LineageRejected'), ...
    'A rejected prior stamp must not block an accepted one.');
setenv('TC_ACCEPTED_RESULT_DIGESTS','not-a-digest');
assert_throws(@() Accepted_Stamp_Digests(current,logs,repo), ...
    'Bouchet_Joint_Sweep:LineageDigest');
end

function expect_rejected(current,logs,repo,digest,identifier)
setenv('TC_ACCEPTED_RESULT_DIGESTS',digest);
[accepted,lineage,rejected] = Accepted_Stamp_Digests(current,logs,repo);
assert(isequal(accepted,{Fingerprint_Digest(current)}) && isempty(lineage) && ...
       numel(rejected) == 1 && strcmp(rejected(1).digest,digest) && ...
       strcmp(rejected(1).identifier,identifier), ...
    'Prior stamp %s must be rejected as %s.',digest,identifier);
end

function write_text(file,text)
fid = fopen(file,'wt');
assert(fid >= 0,'Cannot write %s',file);
fprintf(fid,'%s\n',text);
fclose(fid);
end

function assert_throws(f,id)
threw = false;
try
    f();
catch ME
    threw = strcmp(ME.identifier,id);
end
assert(threw,'Bouchet_Joint_Sweep:ExpectedError', ...
    'Expected error %s was not raised.',id);
end

