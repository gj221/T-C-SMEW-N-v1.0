function test_bouchet_1d_joint_sweep_configuration(campaign_dir,run_dir)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Fixed configuration and runner contract for the joint 1-D sweep.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

if nargin < 1 || isempty(campaign_dir)
    test_dir = fileparts(mfilename('fullpath'));
    v2_dir = fileparts(fileparts(test_dir));
    repo_root = fileparts(v2_dir);
    campaign_dir = fullfile(repo_root,'runtime', ...
        'Calibration_Sweep_1D');
end
if nargin < 2 || isempty(run_dir)
    test_dir = fileparts(mfilename('fullpath'));
    run_dir = fullfile(fileparts(fileparts(test_dir)),'run');
end
addpath(campaign_dir,run_dir);

required_campaign_files = { ...
    'Sweep_Cases.m', ...
    'Pre_Control_pH_Score.m', ...
    'Run_Sweep_Task.m', ...
    'Validate_Sweep.m', ...
    'Summarize_Sweep.m', ...
    'Load_Sweep_Observations.m', ...
    'Sweep_Fingerprint.m', ...
    'Assert_Sweep_Provenance.m', ...
    'Fingerprint_Digest.m', ...
    'submit_sweep.sbatch', ...
    'submit_sweep.sh','README.md'};
assert(all(cellfun(@(x) isfile(fullfile(campaign_dir,x)), ...
        required_campaign_files)), ...
    'Bouchet_Joint_Sweep:IncompleteCampaign', ...
    'The deployed joint-sweep campaign is incomplete.');

cases = Sweep_Cases;
expected_alpha = [linspace(1.3,3.4,5) 4.5 6];
expected_knmaxd = [0.0016 0.0032 0.0048 0.0064];
expected_kbot = [NaN 0.07 0.03 0.01];
expected_release = 1;
expected_runs = 10:12;

assert(numel(cases) == 336, ...
    'Bouchet_Joint_Sweep:CaseCount', ...
    'The joint sweep must contain 336 one-dimensional trajectories.');
assert(isequal(unique([cases.AppeloAlpha]),expected_alpha), ...
    'Bouchet_Joint_Sweep:AlphaGrid', ...
    'The alpha grid must contain the five values from 1.3 to 3.4 and then 4.5 and 6.');
assert(isequal(unique([cases.DissolutionFactor]),expected_release), ...
    'Bouchet_Joint_Sweep:ReleaseFactorGrid', ...
    'Every sweep case must run at dissolution factor 1.');
assert(isequal(unique([cases.KNmaxd]),expected_knmaxd), ...
    'Bouchet_Joint_Sweep:KNmaxdGrid', ...
    'The KNmaxd grid lost a requested or current-baseline value.');
actual_kbot = [cases.Kbot];
assert(nnz(isnan(actual_kbot)) == numel(expected_alpha)*numel(expected_knmaxd)*numel(expected_release)*numel(expected_runs) && ...
       isequal(unique(actual_kbot(isfinite(actual_kbot))),sort(expected_kbot(2:end))), ...
    'Bouchet_Joint_Sweep:KbotGrid', ...
    'The Kbot grid must include free drainage and 0.07, 0.03 and 0.01 mm h^-1.');
assert(isequal(unique([cases.run_id]),expected_runs), ...
    'Bouchet_Joint_Sweep:RunGrid', ...
    'Every joint-sweep parameter tuple must contain runs 10 to 12.');
assert(all([cases.CEC_cmolc_kg] == 13), ...
    'Bouchet_Joint_Sweep:CECGrid', ...
    'Every sweep case must use the direct 13 cmolc kg-1 site measurement.');
reference_logKH = [4.71627429367 3.61627429367 8.10254858734 ...
    8.41854858734 12.918822881];
charge = [1 1 2 2 3];
assert(all(arrayfun(@(x) max(abs(x.AppeloLogKH-(reference_logKH + ...
        charge*(x.AppeloAlpha-1.3)*0.20))) < 1e-12,cases)), ...
    'Bouchet_Joint_Sweep:AppeloConvention', ...
    'Alpha and code-input logKH must hold selectivity at the seed f_H of 0.20.');
assert(isequal([cases(1:3).run_id],expected_runs) && ...
       all([cases(1:3).AppeloAlpha] == 1.3) && ...
       all([cases(1:3).KNmaxd] == 0.0048) && ...
       all([cases(1:3).DissolutionFactor] == 1) && ...
       all(isnan([cases(1:3).Kbot])), ...
    'Bouchet_Joint_Sweep:BaselineFirst', ...
    'The accepted baseline must be the first three resumable array tasks.');

%% A 366-day run dates its rows 31 December 2015 (the lone first hour)
%% through 30 December 2016, its last complete BIOGEO day.
pre_dates = datenum(2015,12,31)+(0:365).'; %#ok<DATNM>
pre_observations.control.shallow_0_10 = repmat(6.1,5,1);
pre_observations.control.deep_10_30 = repmat(6.3,5,1);
pre_observations.control.profile_0_30 = -log10((10*10.^(-6.1) + ...
    20*10.^(-6.3))/30)*ones(5,1);
pre_bulk_pH = [5.0; repmat(6.0,157,1); repmat(7.0,157,1); repmat(4.0,51,1)];
pre_score = Pre_Control_pH_Score( ...
    pre_dates,pre_bulk_pH,pre_observations);
expected_pre_observation = pre_observations.control.profile_0_30(1);
expected_pre_model = -log10(mean([repmat(10^-6,157,1); ...
    repmat(10^-7,157,1)]));
expected_pre_residual = expected_pre_model-expected_pre_observation;
assert(pre_score.n_days == 366 && pre_score.n_pre_days == 314 && ...
       abs(pre_score.model_bulk_pH_pre-expected_pre_model) < 1e-12 && ...
       abs(pre_score.model_bulk_pH_pre-mean(pre_bulk_pH(2:315))) > 0.1 && ...
       abs(pre_score.observed_bulk_pH_pre-expected_pre_observation) < 1e-12 && ...
       abs(pre_score.residual-expected_pre_residual) < 1e-12 && ...
       abs(pre_score.bias-expected_pre_residual) < 1e-12 && ...
       abs(pre_score.rmse-abs(expected_pre_residual)) < 1e-12, ...
    'Bouchet_Joint_Sweep:PreControlScore', ...
    'The one-year control gate must use only the 314-day manuscript pre period.');
pre_bulk_pH([1 316:end]) = 9.0;
post_changed_score = Pre_Control_pH_Score( ...
    pre_dates,pre_bulk_pH,pre_observations);
assert(isequal(pre_score.model_bulk_pH_pre, ...
        post_changed_score.model_bulk_pH_pre), ...
    'Bouchet_Joint_Sweep:PreControlWindowLeak', ...
    'The first hour and 10 November to 30 December must not affect the pre-period score.');
full_dates = datenum(2015,12,31)+(0:1825).'; %#ok<DATNM>
full_bulk_pH = [pre_bulk_pH; repmat(8.0,1826-366,1)];
full_pre_score = Pre_Control_pH_Score( ...
    full_dates,full_bulk_pH,pre_observations);
assert(full_pre_score.n_days == 1826 && ...
       isequal(full_pre_score.model_bulk_pH_pre, ...
           post_changed_score.model_bulk_pH_pre), ...
    'Bouchet_Joint_Sweep:FullPreControlOperator', ...
    'The full summary must reuse the exact exploratory pre-period operator.');
assert_throws(@() Pre_Control_pH_Score( ...
    pre_dates(1:end-1),pre_bulk_pH(1:end-1),pre_observations), ...
    'Bouchet_Joint_Sweep:PreControlWindow');

tags = {cases.tag};
assert(numel(unique(tags)) == numel(tags) && ...
       all(cellfun(@(x) ~isempty(regexp(x, ...
           '^a[0-9p]+_kn[0-9p]+_kb(?:free|[0-9p]+)_fd[0-9p]+_run(?:10|11|12)$','once')),tags)), ...
    'Bouchet_Joint_Sweep:CaseTags', ...
    'Every trajectory requires one unique, filesystem-safe parameter tag.');

tuples = [[cases.AppeloAlpha]' [cases.KNmaxd]' [cases.DissolutionFactor]' [cases.run_id]'];
kbot_key = actual_kbot(:);
kbot_key(isnan(kbot_key)) = -1;
assert(size(unique([tuples(:,1:3) kbot_key tuples(:,4)],'rows'),1) == numel(cases), ...
    'Bouchet_Joint_Sweep:DuplicateTuple', ...
    'The case table contains a repeated parameter/run tuple.');

campaign_tag = ...
    'Calibration_Sweep_1D';
stamp_digest = repmat('a',1,64);
n_days = 1826;
start_date = datenum(2016,1,1); %#ok<DATNM>
results_dir = fullfile(tempdir,'joint_sweep_provenance_test');
