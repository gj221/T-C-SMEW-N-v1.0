    'Bouchet_Joint_Sweep:ValidationSafety', ...
    'The validation entry point lost its R2025a, audit or fingerprint gate.');
assert(contains(validation_text,"fullfile(logs_dir,'validation_stamps', ...") && ...
       contains(validation_text, ...
           'Bouchet_Write_Validation_Stamp(archive_file,fingerprint_before)'), ...
    'Bouchet_Joint_Sweep:StampArchive', ...
    'Validation must archive every stamp under its digest.');

