    'AppeloAlpha',2.35,'KNmaxd',0.0048,'Kbot',NaN, ...
    'DryRun',true);
batch = [plan.batch];
assert(numel(plan) == 3 && ...
       all(contains(batch,'''KNmaxd'',0.0048')) && ...
       all(contains(batch,'''Kbot'',NaN')) && ...
       all(contains({plan.result_file}, ...
           '__alpha2p35__knmaxd0p0048__kbotfree__1d.mat')), ...
    'Bouchet_Joint_Sweep:LauncherPropagation', ...
       'The all-12 launcher must propagate and tag the selected tuple.');

legacy_plan = Run_All_12_Parallel('Runs',10,'NDays',1, ...
    'AppeloAlpha',1.3,'DryRun',true);
assert(~contains(legacy_plan.batch,'''KNmaxd''') && ...
       ~contains(legacy_plan.batch,'''Kbot''') && ...
       ~contains(legacy_plan.result_file,'__knmaxd') && ...
       ~contains(legacy_plan.result_file,'__kbot'), ...
    'Bouchet_Joint_Sweep:LegacyCallChanged', ...
    'Omitting the new options must retain the existing launcher contract.');

main_file = fullfile(fileparts(run_dir),'T&C_Code','MAIN_FRAME_BG_ERW_2D.m');
main_text = fileread(main_file);
assert(contains(main_text,'kbot=%s') && ...
       contains(main_text,'mat2str(PAR{c}.Kbot,17)'), ...
    'Bouchet_Joint_Sweep:CheckpointIdentity', ...
    'Kbot must be part of the checkpoint runtime identity.');

bio_text = fileread(fullfile(fileparts(run_dir), ...
    'T&C_Code','BIOGEOCHEMISTRY_DYNAMIC3.m'));
assert(contains(bio_text,'fmoist=Se^(1/0.5);'), ...
    'Bouchet_Joint_Sweep:MoistureResponse', ...
    'The sweep must retain the active legacy Se-squared moisture response.');

summary_text = fileread(fullfile(campaign_dir,'Summarize_Sweep.m'));
assert(contains(summary_text,'dates = dates-1;') && ...
       count(summary_text,'reshape(x(2:24*(nd-1)+1),24,nd-1)') + ...
       count(summary_text,'reshape(hourly(2:24*(nd-1)+1),24,nd-1)') == 2, ...
    'Bouchet_Joint_Sweep:DailyAxis', ...
    'Scored daily rows must be dated, and hourly drainage and WFPS windowed, by the BIOGEO day they hold.');

batch_text = fileread(fullfile(campaign_dir, ...
    'submit_sweep.sbatch'));
submit_text = fileread(fullfile(campaign_dir, ...
    'submit_sweep.sh'));
readme_text = fileread(fullfile(campaign_dir,'README.md'));
task_text = fileread(fullfile(campaign_dir, ...
    'Run_Sweep_Task.m'));
pre_score_text = fileread(fullfile(campaign_dir, ...
    'Pre_Control_pH_Score.m'));
summary_text = fileread(fullfile(campaign_dir, ...
    'Summarize_Sweep.m'));
assert_throws(@() Summarize_Sweep('invalid'), ...
    'Bouchet_Joint_Sweep:BadSummaryScope');
validation_text = fileread(fullfile(campaign_dir, ...
    'Validate_Sweep.m'));
provenance_text = fileread(fullfile(campaign_dir, ...
    'Assert_Sweep_Provenance.m'));
joint_fingerprint_text = fileread(fullfile(campaign_dir, ...
    'Sweep_Fingerprint.m'));
fingerprint_text = fileread(fullfile(fileparts(run_dir), ...
    'T&C_Code','Bouchet_Campaign_Validation_Fingerprint.m'));

assert(contains(batch_text,'#SBATCH --constraint=cpumodel:9575f') && ...
       contains(batch_text,'#SBATCH --nodes=1') && ...
       contains(batch_text,'#SBATCH --ntasks=1') && ...
       contains(batch_text,'#SBATCH --cpus-per-task=1') && ...
       contains(batch_text,'#SBATCH --mem=8G') && ...
       contains(batch_text,'#SBATCH --time=05:00:00') && ...
       contains(batch_text,'#SBATCH --array=1') && ...
       contains(batch_text,'TC_CKPT_MINUTES=30') && ...
       contains(batch_text,'unset TC_CKPT_FORCE_RESUME') && ...
       contains(batch_text,'MATLAB/2025a') && ...
       contains(batch_text, ...
         'cpumodel=9575f;matlab_release=2025a;single_comp_thread=1;parallel_workers=0') && ...
       contains(batch_text,'matlab -singleCompThread -batch') && ...
       contains(submit_text,'TC_SWEEP_MAX_CONCURRENT:-48') && ...
       contains(submit_text,'TC_SWEEP_LAYOUT:-independent') && ...
       contains(submit_text,'production_array="1-336%${production_concurrency}"') && ...
       contains(submit_text,'production_array="1-112%${packed_concurrency}"') && ...
       contains(submit_text,'--array="$production_array"') && ...
       contains(submit_text,'--cpus-per-task=1 --mem="$production_mem"') && ...
       contains(submit_text,'if ! submitted="$(sbatch') && ...
       contains(submit_text,'if ! scontrol show jobid="$job_id" -dd |'), ...
    'Bouchet_Joint_Sweep:SlurmContract', ...
    'The Bouchet release, node, resource or checkpoint contract changed.');

% The rescore graph (validation then summary only) precedes the main graph;
% the main graph is checked from the baseline submission onward.
rescore_start = strfind(submit_text, ...
    [newline 'if [[ "$sweep_stage" == "rescore" ]]; then']);
rescore_end = strfind(submit_text,'RESCORE: no trajectory is recomputed');
assert(isscalar(rescore_start) && isscalar(rescore_end) && ...
       rescore_start < rescore_end, ...
    'Bouchet_Joint_Sweep:RescoreGraph','The rescore graph is missing.');
rescore_text = submit_text(rescore_start:rescore_end);
assert(numel(strfind(rescore_text,'submit_job validation_job')) == 1 && ...
       numel(strfind(rescore_text,'submit_job summary_job')) == 1 && ...
       ~contains(rescore_text,'submit_job baseline_job') && ...
       ~contains(rescore_text,'submit_job pilot_job') && ...
       ~contains(rescore_text,'submit_job production_job') && ...
       contains(rescore_text,'summary_dependency=(--dependency="afterok:${validation_job}"') && ...
       contains(rescore_text,'TC_SUMMARIZE_ONLY=1,TC_SWEEP_SCOPE=full,TC_SWEEP_SUMMARY_SCOPE=full,TC_ACCEPTED_RESULT_DIGESTS=$accepted_digests'), ...
    'Bouchet_Joint_Sweep:RescoreGraph', ...
    'The rescore graph must submit validation and the full summary only.');
main_text = submit_text(rescore_end:end);
