       contains(submit_text,'"$reviewed_digest" != "$current_digest"') && ...
       contains(submit_text, ...
           'TC_SWEEP_CONTROLLER_TOKEN TC_EQUIVALENCE_BASELINE') && ...
       contains(submit_text,'assert_stamp_current') && ...
       contains(submit_text,'gate_results_glob=') && ...
       contains(submit_text,'stamp_divergence appeared "$file"') && ...
       contains(submit_text,'stamp_divergence changed "$path"') && ...
