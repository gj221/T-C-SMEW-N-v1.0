function assert_moved_only(base,moved,literals,values)
for k = 1:numel(literals)
    name = literals{k};
    expected = base.(name);
    if isfield(values,name); expected = values.(name); end
    assert(moved.(name) == expected, ...
        'Kantola_Uncertainty:OverrideSpill', ...
        'BiogeoPar.%s is %g where the set expects %g.',name,moved.(name),expected);
end
end

function assert_error(fun,identifier)
try
    fun();
catch ME
    assert(strcmp(ME.identifier,identifier), ...
        'Expected %s, got %s: %s',identifier,ME.identifier,ME.message);
    return
end
error('Expected error %s was not raised.',identifier);
end
