function test_uncertainty_campaign
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Pin the Kantola uncertainty ensemble: three parameter sets (the
%% calibrated original, reused from the Base and SSP campaigns, and the
%% lower and upper sets, each moving all sixteen parameters to one end of
%% its range), the arms and horizons each array covers, the knobs a member
%% runs with, the provenance a saved result must carry, and the batch
%% files and controller that submit the lower and upper runs.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

test_dir = fileparts(mfilename('fullpath'));
code_dir = fileparts(test_dir);
repo_root = fileparts(fileparts(code_dir));
campaign_dir = fullfile(repo_root,'runtime','Uncertainty_1D');
campaign_2d_dir = fullfile(repo_root,'runtime','Uncertainty_2D');
calibrated_dir = fullfile(repo_root,'runtime','Base_1D');
addpath(code_dir,campaign_dir,calibrated_dir);
for file = {fullfile(campaign_dir,'Uncertainty_Members.m'), ...
        fullfile(campaign_dir,'Uncertainty_Campaign.m'), ...
        fullfile(campaign_dir,'Uncertainty_Knobs.m'), ...
        fullfile(campaign_dir,'Uncertainty_Result_Matches.m'), ...
        fullfile(campaign_dir,'Uncertainty_Result_State.m'), ...
        fullfile(campaign_dir,'Run_Uncertainty_Task.m'), ...
        fullfile(campaign_dir,'submit_uncertainty.sbatch'), ...
        fullfile(campaign_dir,'submit_uncertainty.sh'), ...
        fullfile(campaign_dir,'same_model_code.sh'), ...
        fullfile(campaign_dir,'requeue_near_limit.sh'), ...
        fullfile(campaign_dir,'README.md'), ...
        fullfile(campaign_2d_dir,'Run_Uncertainty_2D_Task.m'), ...
        fullfile(campaign_2d_dir,'submit_uncertainty_2d.sbatch')}
    assert(isfile(file{1}),'Kantola_Uncertainty:MissingFile','%s is missing.',file{1});
end

%% The parameter sets.
members = Uncertainty_Members;
assert(numel(members) == 3 && isequal([members.id],1:3) && ...
    isequal({members.tag},{'original','lower','upper'}) && ...
    isequal([members.reused],[true false false]), ...
    'The ensemble must hold the reused original, then the lower and upper sets.');
original = members(1); lower = members(2); upper = members(3);
assert(isempty(original.BiogeoOverrides) && isempty(original.DissolutionFactor) && ...
    isempty(original.SaturationExponent) && isempty(original.KNmaxd) && ...
    isempty(original.AppeloAlpha), ...
    'The original must move nothing: it is the calibrated campaign run itself.');
%% Table S2 of the T&C-SMEW supplement: original, minimum and maximum.
table_s2 = struct('Vm',[100 1.2 528],'Vpc',[200 4.8 792], ...
    'Km',[0.25 0.057 0.95],'rem',[0.018 0.0075 0.075], ...
    'rep',[0.018 0.0075 0.075],'pepf',[0.006 0.0031 0.031], ...
    'mrb',[0.005 0.0012 0.03],'mrf',[0.002 0.0012 0.03], ...
    'fd',[0.4 0.2 0.8],'Vpl',[23 4.8 792], ...
    'Vdb',[0.04 0.0024 0.06],'Vdf',[0.02 0.0024 0.06]);
%% The legacy T&C-SMEW code, which Data_Kantola_BG.mat was spun up with,
%% ships mrb and mrf at 0.010 and 0.005 instead of the table's originals.
legacy = struct('mrb',0.010,'mrf',0.005);
literals = fieldnames(table_s2);
base = Biogeochemistry_Parameter(1);
for k = 1:numel(literals)
    name = literals{k};
    expected = table_s2.(name)(1);
    if isfield(legacy,name); expected = legacy.(name); end
    assert(abs(base.(name)-expected) <= 1e-12*expected, ...
        'The shipped %s must be %g.',name,expected);
end
assert(isequal(sort(fieldnames(lower.BiogeoOverrides)),sort(literals)) && ...
    isequal(sort(fieldnames(upper.BiogeoOverrides)),sort(literals)), ...
    'The lower and upper sets must move all twelve literals.');
for k = 1:numel(literals)
    name = literals{k};
    assert(lower.BiogeoOverrides.(name) == table_s2.(name)(2) && ...
        upper.BiogeoOverrides.(name) == table_s2.(name)(3) && ...
        table_s2.(name)(2) < base.(name) && base.(name) < table_s2.(name)(3), ...
        'Literal %s must sit at its Table S2 ends around the shipped value.',name);
end
%% The soil model builds its parameters this way (BIOGEO_UNIT), so the
%% overrides move the twelve literals and nothing else.
assert_moved_only(base,Biogeochemistry_Parameter(1,[],lower.BiogeoOverrides), ...
    literals,lower.BiogeoOverrides);
assert_moved_only(base,Biogeochemistry_Parameter(1,[],upper.BiogeoOverrides), ...
    literals,upper.BiogeoOverrides);
%% Table S2's dissolution factor runs 0.8 to 1.2 about an original of 1, and
%% the sets give it outright, so every feedstock row must ship 1.
workbook = readtable(fullfile(code_dir,'Inputs','ERW_MOD_PARAM_parameters.xlsx'), ...
    'Sheet','ERW_MOD');
shipped_diss_f = workbook.diss_f(isfinite(workbook.diss_f));
assert(~isempty(shipped_diss_f) && all(shipped_diss_f == 1), ...
    'Every feedstock row must ship the Table S2 dissolution factor of 1.');
assert(lower.DissolutionFactor == 0.8 && upper.DissolutionFactor == 1.2 && ...
    lower.SaturationExponent == 2 && upper.SaturationExponent == 0.5 && ...
    lower.KNmaxd == 0.002 && upper.KNmaxd == 0.01, ...
    'Dissolution factor, saturation exponent and KNmaxd must sit at their range ends.');
%% Alpha is formed as the sweep forms it: the ends of the sweep grid around
%% the campaign's 3.4.
alpha_grid = linspace(1.3,3.4,5);
P = Campaign_Parameters;
assert(isequal(P.AppeloAlpha,alpha_grid(5)) && P.AppeloAlpha == 3.4 && ...
    isequal(lower.AppeloAlpha,alpha_grid(1)) && lower.AppeloAlpha == 1.3 && ...
    isequal(upper.AppeloAlpha,6) && ...
    lower.AppeloAlpha < P.AppeloAlpha && P.AppeloAlpha < upper.AppeloAlpha, ...
    'Alpha must run from 1.3 to 6 around the campaign''s 3.4.');

%% The knobs a set runs with.
K0 = Uncertainty_Knobs(original,P);
assert(isequaln(K0.options,{'AppeloAlpha',P.AppeloAlpha,'AppeloLogKH',P.AppeloLogKH, ...
    'KNmaxd',P.KNmaxd,'Kbot',P.Kbot}) && K0.SaturationExponent == 1 && ...
    isempty(K0.BiogeoOverrides) && isempty(K0.DissolutionFactor), ...
    'The original must run exactly the knobs the Base and SSP tasks pass.');
KL = Uncertainty_Knobs(lower,P);
assert(isequal(KL.AppeloAlpha,P.reference_alpha) && isequal(KL.AppeloLogKH,P.reference_logKH) && ...
    all(KL.AppeloLogKH < P.AppeloLogKH), ...
    'The lower set sits at the rule''s reference alpha, so its constants must be the reference ones bit for bit.');
KU = Uncertainty_Knobs(upper,P);
rule = P.reference_logKH + P.charge*(upper.AppeloAlpha-P.reference_alpha)*P.seed_f_H;
slid = arrayfun(@(v) str2double(sprintf('%.12g',v)),rule);
assert(isequal(KU.AppeloLogKH,slid) && ...
    isequaln(KU.options,{'AppeloAlpha',upper.AppeloAlpha,'AppeloLogKH',slid, ...
    'KNmaxd',0.01,'Kbot',P.Kbot,'BiogeoOverrides',upper.BiogeoOverrides, ...
    'DissolutionFactor',1.2,'SaturationExponent',0.5}) && KU.SaturationExponent == 0.5, ...
    'The upper set must slide the exchange constants by the campaign rule and pass every knob.');
assert(all(KU.AppeloLogKH > P.AppeloLogKH) && max(abs(slid-rule)) < 1e-10 && ...
    max(abs(KU.AppeloLogKH-[5.65627429367 4.55627429367 9.98254858734 10.29854858734 15.738822881])) < 1e-9 && ...
    max(abs(P.AppeloLogKH-[5.13627429367 4.03627429367 8.94254858734 9.25854858734 14.178822881])) < 1e-9, ...
    'The campaign and upper constants must be the reference ones slid to alpha 3.4 and 6.');
%% A knob that does not print exactly at twelve significant figures adds
%% its hexadecimal form to a result name (number_tag in Run_One_Subfield).
%% Every knob of every set must therefore print exactly, and the longest
%% name the ensemble can ask for, a 35-year 2-D 5 t/ha run of the upper
%% set, must stay clear of the 255 characters a file name may have.
prints_exactly = @(v) all(arrayfun(@(x) str2double(sprintf('%.12g',x)) == x,v));
for K = {K0,KL,KU}
    assert(prints_exactly([K{1}.AppeloAlpha K{1}.AppeloLogKH K{1}.KNmaxd ...
        K{1}.DissolutionFactor K{1}.SaturationExponent]), ...
        'A knob of an ensemble set does not print exactly at twelve significant figures.');
end
number_tag = @(v) strrep(sprintf('%.12g',v),'.','p');
longest = ['TC_2D_run09_calcite__margin_prairie__ssp585__case8__grid2x2__alpha' ...
    number_tag(KU.AppeloAlpha) '__logkh' ...
    strjoin(arrayfun(number_tag,KU.AppeloLogKH,'UniformOutput',false),'_') ...
    '__knmaxd' number_tag(KU.KNmaxd) '__bg12fields_0a1b2c3d__fd' ...
    number_tag(KU.DissolutionFactor) '__sexp' number_tag(KU.SaturationExponent) ...
    '__kbotfree__12784d__from20160101.mat'];
assert(numel(longest) <= 240, ...
    'The longest ensemble result name has %d characters, too near the 255 a file name may have.', ...
    numel(longest));

%% Arms and horizons: each array runs the lower and upper sets over the
%% runs of one dimension, calcite case and horizon, and names the Base or
%% SSP campaign whose result is its original.
env = {'TC_SSP','TC_HORIZON','TC_CALCITE_CASE','TC_UC_WITH_ORIGINAL'};
saved = cellfun(@getenv,env,'UniformOutput',false);
restore = onCleanup(@() cellfun(@setenv,env,saved)); %#ok<NASGU>
set_env('','','');
C = Uncertainty_Campaign('1D');
assert(strcmp(C.tag,'Uncertainty_1D') && strcmp(C.original_tag,'Base_1D') && ...
    isempty(C.scenario) && strcmp(C.horizon,'5yr') && C.n_days == 1826 && ...
    C.last_application_year == 2019 && isequal(C.runs,[10 11 12]) && ...
    C.n_columns == 1 && C.workers == 0 && isempty(C.calcite_case) && isempty(C.options), ...
    'The 5-year 1-D ensemble must run runs 10-12 on the legacy forcing.');
assert(isequal([C.elements.run_id],[10 11 12 10 11 12]) && ...
    isequal(element_tags(C),{'lower','lower','lower','upper','upper','upper'}), ...
    'Elements must be member-major over the run list.');
set_env('','5yr','8');
C = Uncertainty_Campaign('1D');
assert(strcmp(C.tag,'Uncertainty_1D_case8') && strcmp(C.original_tag,'Base_1D_case8') && ...
    C.calcite_case == 8 && isequal(C.runs,12) && isequal(C.options,{'CalciteCase',8}) && ...
    isequal(element_tags(C),{'lower','upper'}), ...
    'The 5 t/ha arm must run calcite run 12 only, under its own tag.');
set_env('','','');
C = Uncertainty_Campaign('2D');
assert(strcmp(C.tag,'Uncertainty_2D') && strcmp(C.original_tag,'Base_2D') && ...
    isequal(C.runs,1:9) && C.n_columns == 12 && C.workers == 6 && ...
    isequal(C.options,{'GridNx',2,'GridNy',2}) && numel(C.elements) == 18, ...
    'The 5-year 2-D ensemble must run runs 1-9 on the 2x2 grid with the Base workers.');
set_env('ssp245','35yr','8');
C = Uncertainty_Campaign('2D');
assert(strcmp(C.tag,'Uncertainty_2D_35yr_ssp245_case8') && ...
    strcmp(C.original_tag,'SSP_2D_35yr_ssp245_case8') && strcmp(C.scenario,'ssp245') && ...
    strcmp(C.horizon,'35yr') && C.n_days == 12784 && C.last_application_year == 2050 && ...
    isequal(C.runs,[3 6 9]) && C.workers == 12 && ...
    isequal(C.options,{'GridNx',2,'GridNy',2,'Scenario','ssp245', ...
    'LastApplicationYear',2050,'CalciteCase',8}) && numel(C.elements) == 6, ...
    'A 35-year 5 t/ha 2-D ensemble must run runs 3, 6 and 9 as the SSP campaign does.');
set_env('ssp126','35yr','');
C = Uncertainty_Campaign('1D');
assert(strcmp(C.tag,'Uncertainty_1D_35yr_ssp126') && ...
    strcmp(C.original_tag,'SSP_1D_35yr_ssp126') && isequal(C.runs,[10 11 12]) && ...
    isequal(C.options,{'Scenario','ssp126','LastApplicationYear',2050}), ...
    'A 35-year 1-D ensemble must run runs 10-12 on the scenario forcing to 2050.');
assert(any(contains(C.dependencies,'Data_Kantola_ssp126.mat')) && ...
    any(contains(C.dependencies,'Campaign_Parameters.m')), ...
    'The scenario forcing and the calibrated set must be part of the fingerprint.');
assert_error(@() campaign_with('ssp245','5yr',''),'Kantola_Uncertainty:BadHorizon');
assert_error(@() campaign_with('ssp245','',''),'Kantola_Uncertainty:BadHorizon');
assert_error(@() campaign_with('','35yr',''),'Kantola_Uncertainty:BadHorizon');
assert_error(@() campaign_with('ssp370','35yr',''),'Kantola_Uncertainty:BadScenario');
assert_error(@() campaign_with('','','5.5'),'Bouchet_Kantola_CEC13:BadCalciteCase');
set_env('','','');
assert_error(@() Uncertainty_Campaign('3D'),'Kantola_Uncertainty:BadDimension');
%% On request the original runs here too, first, as the reused one ran.
set_env('ssp245','35yr','');
setenv('TC_UC_WITH_ORIGINAL','1');
C = Uncertainty_Campaign('2D');
assert(numel(C.elements) == 27 && isequal([C.elements(1:9).run_id],1:9) && ...
    isequal(unique(element_tags(C),'stable'),{'original','lower','upper'}) && ...
    isequaln(Uncertainty_Knobs(C.elements(1).member,P).options,K0.options), ...
    'With TC_UC_WITH_ORIGINAL=1 the original runs first, with the calibrated knobs.');
setenv('TC_UC_WITH_ORIGINAL','yes');
assert_error(@() Uncertainty_Campaign('1D'),'Kantola_Uncertainty:BadWithOriginal');
setenv('TC_UC_WITH_ORIGINAL','');
set_env('','','');
%% The originals' tags and horizons are the ones their campaigns write.
assert(contains(fileread(fullfile(calibrated_dir,'Run_Base_1D_Task.m')), ...
    "campaign_tag = ['Base_1D' case_suffix];") && ...
    contains(fileread(fullfile(repo_root,'runtime','Base_2D','Run_Base_2D_Task.m')), ...
    "campaign_tag = ['Base_2D' case_suffix];"), ...
    'The Base campaigns must still tag their results as the ensemble expects.');
ssp_controller = fileread(fullfile(repo_root,'runtime','SSP_1D','submit_ssp.sh'));
ssp_2d = fileread(fullfile(repo_root,'runtime','SSP_2D','Run_SSP_2D_Task.m'));
assert(contains(ssp_controller,'tag_1d="SSP_1D_${TC_HORIZON}_${TC_SSP}${case_suffix}"') && ...
    contains(ssp_controller,'tag_2d="SSP_2D_${TC_HORIZON}_${TC_SSP}${case_suffix}"') && ...
    contains(ssp_2d,'n_days = 12784;') && contains(ssp_2d,'last_application_year = 2050;'), ...
    'The SSP campaigns must still tag and size their 35-year results as the ensemble expects.');

%% A saved result must carry its set's provenance, as the driver records
%% it: per-column alpha and constants, the horizon, the calcite case and
%% scenario in the file name.
set_env('','','8');
C = Uncertainty_Campaign('2D');
name = ['TC_2D_run09_calcite__margin_prairie__case8__grid2x2__alpha6' ...
    '__knmaxd0p01__bg12fields_0a1b2c3d__fd1p2__sexp0p5__kbotfree__1826d__from20160101.mat'];
p = provenance(C,KU,'Uncertainty_2D_case8','d1');
assert(Uncertainty_Result_Matches(p,name,C,KU,'Uncertainty_2D_case8','d1'), ...
    'A twelve-column upper result must match the upper set.');
mutations = {@(q) setfield(q,'campaign','Uncertainty_2D'), ...
    @(q) setfield(q,'validation_fingerprint','d2'), ...
    @(q) setfield(q,'n_days',1827), ...
    @(q) setfield(q,'n_columns',1), ...
    @(q) setfield(q,'last_application_year',2050), ...
    @(q) setfield(q,'KNmaxd',P.KNmaxd), ...
    @(q) setfield(q,'Kbot',1), ...
    @(q) setfield(q,'biogeo_overrides',[]), ...
    @(q) setfield(q,'dissolution_factor',[]), ...
    @(q) setfield(q,'saturation_exponent',1), ...
    @(q) setfield(q,'AppeloAlpha',[q.AppeloAlpha(1:11); P.AppeloAlpha]), ...
    @(q) setfield(q,'AppeloLogKH',[q.AppeloLogKH(1:11,:); P.AppeloLogKH]), ...
    @(q) setfield(q,'AppeloLogKH',q.AppeloLogKH(1,:)), ...
    @(q) rmfield(q,'campaign')};
for k = 1:numel(mutations)
    assert(~Uncertainty_Result_Matches(mutations{k}(p),name,C,KU,'Uncertainty_2D_case8','d1'), ...
        'Provenance mutation %d must not pass as the upper set.',k);
end
assert(~Uncertainty_Result_Matches(p,strrep(name,'__case8',''),C,KU,'Uncertainty_2D_case8','d1') && ...
    ~Uncertainty_Result_Matches(p,strrep(name,'__case8','__ssp245__case8'),C,KU,'Uncertainty_2D_case8','d1'), ...
    'The file name must carry the arm''s calcite case and scenario, and no other.');
%% The original is another campaign's result: its own tag, its own stamp.
p0 = provenance(C,K0,'Base_2D_case8','base stamp');
name0 = strrep(strrep(name,'alpha6','alpha3p4'),'__bg12fields_0a1b2c3d__fd1p2__sexp0p5','');
assert(Uncertainty_Result_Matches(p0,name0,C,K0,'Base_2D_case8','') && ...
    ~Uncertainty_Result_Matches(p0,name0,C,KL,'Base_2D_case8',''), ...
    'The original must match the calibrated knobs and nothing else.');
set_env('ssp585','35yr','');
C = Uncertainty_Campaign('1D');
p1 = provenance(C,KL,'Uncertainty_1D_35yr_ssp585','d3');
name1 = 'TC_2D_run11_basalt__vertical_1d__ssp585__alpha1p3__knmaxd0p002__kbotfree__12784d__from20160101.mat';
assert(Uncertainty_Result_Matches(p1,name1,C,KL,'Uncertainty_1D_35yr_ssp585','d3') && ...
    ~Uncertainty_Result_Matches(p1,strrep(name1,'ssp585','ssp245'),C,KL,'Uncertainty_1D_35yr_ssp585','d3'), ...
    'A projection result must carry its own scenario.');

%% The result on disk: none, this set's, another's, or ambiguous.
folder = tempname;
mkdir(folder);
cleanup_folder = onCleanup(@() rmdir(folder,'s')); %#ok<NASGU>
[state,file] = Uncertainty_Result_State(folder,11,C,KL,'Uncertainty_1D_35yr_ssp585','d3');
assert(strcmp(state,'none') && isempty(file),'An empty directory holds no result.');
run_provenance = p1; %#ok<NASGU>
save(fullfile(folder,name1),'run_provenance');
[state,file] = Uncertainty_Result_State(folder,11,C,KL,'Uncertainty_1D_35yr_ssp585','d3');
assert(strcmp(state,'complete') && strcmp(file,fullfile(folder,name1)), ...
    'A result with the set''s provenance is complete.');
[state,~] = Uncertainty_Result_State(folder,11,C,KU,'Uncertainty_1D_35yr_ssp585','d3');
assert(strcmp(state,'stale'),'A result of another set is stale.');
[state,~] = Uncertainty_Result_State(folder,10,C,KL,'Uncertainty_1D_35yr_ssp585','d3');
assert(strcmp(state,'none'),'Another run''s result does not count.');
other = strrep(name1,'__from','x__from');
no_provenance = 1; %#ok<NASGU>
save(fullfile(folder,other),'no_provenance');
assert_error(@() Uncertainty_Result_State(folder,11,C,KL,'Uncertainty_1D_35yr_ssp585','d3'), ...
    'Kantola_Uncertainty:AmbiguousResult');
delete(fullfile(folder,name1));
[state,~] = Uncertainty_Result_State(folder,11,C,KL,'Uncertainty_1D_35yr_ssp585','d3');
assert(strcmp(state,'stale'),'A result without provenance is stale.');

%% The tasks forward every knob and check the provenance back.
task = fileread(fullfile(campaign_dir,'Run_Uncertainty_Task.m'));
task_2d = fileread(fullfile(campaign_2d_dir,'Run_Uncertainty_2D_Task.m'));
shared_tokens = {'K = Uncertainty_Knobs(member,P);', ...
    "Bouchet_Single_Thread_Runtime('Kantola_Uncertainty');", ...
    'digest = Fingerprint_Digest(fingerprint);', ...
    "setenv('TC_VALIDATION_FINGERPRINT',digest);", ...
    "setenv('TC_CAMPAIGN_TAG',C.tag);", ...
    'Uncertainty_Result_State(results_dir,run_id,C,K,C.tag,digest)', ...
    "{'NDays',C.n_days,'StartDate',P.StartDate}, K.options, C.options", ...
    "error('Kantola_Uncertainty:StaleResult'", ...
    "error('Kantola_Uncertainty:SourceChangedDuringRun'", ...
    "error('Kantola_Uncertainty:Provenance'"};
for k = 1:numel(shared_tokens)
    assert(contains(task,shared_tokens{k}) && contains(task_2d,shared_tokens{k}), ...
        'An uncertainty task omits %s.',shared_tokens{k});
end
assert(contains(task,"C = Uncertainty_Campaign('1D');") && ...
    contains(task,"fullfile(repo_root,'v2'),here,C.tag,1,0,C.dependencies{:})") && ...
    contains(task,"'ParallelWorkers',0"), ...
    'The 1-D task must run one serial column.');
assert(contains(task_2d,"C = Uncertainty_Campaign('2D');") && ...
    contains(task_2d,'workers = Resolve_2D_Parfor_Workers(C.n_columns);') && ...
    contains(task_2d,'if workers ~= C.workers') && ...
    contains(task_2d,"getenv('SLURM_CPUS_PER_TASK')") && ...
    contains(task_2d,"license('test','Distrib_Computing_Toolbox')") && ...
    contains(task_2d,"getenv('TC_CKPT_FORCE_RESUME')") && ...
    contains(task_2d,"fullfile(repo_root,'v2'),here,C.tag,C.n_columns,workers,C.dependencies{:})") && ...
    contains(task_2d,'Bouchet_Acquire_Run_Lock(') && ...
    contains(task_2d,'Run_Subfield_Worker(run_id,status_file,options{:});') && ...
    contains(task_2d,"'ParallelWorkers',workers") && ...
    numel(strfind(task_2d,"Check_Lateral_Conservation(result_file,'Kantola_Uncertainty');")) == 2, ...
    'The 2-D task must run the SSP campaign''s parallel, locked and conservation-checked path.');
for source = {task,task_2d}
    assert(isscalar(strfind(source{1},"Bouchet_Single_Thread_Runtime('Kantola_Uncertainty');")) && ...
        all(strfind(source{1},"Bouchet_Single_Thread_Runtime('Kantola_Uncertainty');") < ...
        strfind(source{1},'Uncertainty_Result_State(results_dir,run_id,C,K,C.tag,digest)')), ...
        'The numerical-platform gate must run before an existing result is accepted.');
end
assert(isscalar(strfind(task_2d,'Bouchet_Acquire_Run_Lock(')) && ...
    all(strfind(task_2d,'Bouchet_Acquire_Run_Lock(') < ...
    strfind(task_2d,'Uncertainty_Result_State(results_dir,run_id,C,K,C.tag,digest)')), ...
    'The 2-D task must hold its run lock before it looks at the result.');

%% Batch files: one CPU per 1-D element; the 2-D element's workers are the
%% CPUs the controller reserved, declared in the numerical identity. Both
%% run on the day partition and requeue themselves when Slurm signals the
%% time limit one checkpoint interval ahead, so a longer run continues
%% from its last checkpoint.
sbatch = fileread(fullfile(campaign_dir,'submit_uncertainty.sbatch'));
sbatch_2d = fileread(fullfile(campaign_2d_dir,'submit_uncertainty_2d.sbatch'));
for source = {sbatch,sbatch_2d}
    assert(contains(source{1},'if [[ "${TC_UC_CONTROLLER_TOKEN:-}" != "UNCERTAINTY_CAMPAIGN_V2" ]]; then') && ...
        contains(source{1},'#SBATCH --requeue') && ...
        contains(source{1},'#SBATCH --partition=day') && ...
        contains(source{1},'#SBATCH --signal=B:USR1@1800') && ...
        contains(source{1},'#SBATCH --open-mode=append') && ...
        contains(source{1},'source runtime/Uncertainty_1D/requeue_near_limit.sh') && ...
        contains(source{1},'#SBATCH --constraint=cpumodel:9575f') && ...
