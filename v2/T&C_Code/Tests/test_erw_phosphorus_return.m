function test_erw_phosphorus_return
%%% Weathered mineral P returns once to the total T&C mineral-P pool.

test_dir = fileparts(mfilename('fullpath'));
code_dir = fileparts(test_dir);
addpath(code_dir);

EW = [4 3; 0 8; 2 5];             % umol mineral m^-2 d^-1
nu_P = [0.5; 0];                  % mol P mol^-1 mineral
dtw = 1/144;                      % d
release_by_step = EW*nu_P*dtw;   % umol P m^-2
release_umol = sum(release_by_step);

P43_before = 2.25;                % g P m^-2
aP = 0.005;
PO4_tot_end = aP*P43_before/31*1e6 + release_umol;
[P43_after,actual_release] = ERW_Return_Weathered_Phosphorus( ...
    P43_before,PO4_tot_end,aP,release_by_step);
assert(abs(actual_release-release_umol) < 1e-15, ...
    'The ERW-window phosphorus source was not summed exactly once.');
assert(abs(P43_after-P43_before-release_umol*31/1e6) < 1e-15, ...
    'Weathered P does not return additively in elemental-P units.');

next_anchor = aP*P43_after/31*1e6;
expected_anchor = aP*(P43_before/31*1e6 + release_umol);
assert(abs(next_anchor-expected_anchor) < 1e-12, ...
    'The next dissolved-P anchor does not partition the returned total pool.');

P43_day2 = P43_after-0.08;
[P43_day2_after,day2_release] = ERW_Return_Weathered_Phosphorus( ...
    P43_day2,aP*P43_day2/31*1e6,aP,zeros(0,1));
assert(P43_day2_after == P43_day2 && day2_release == 0, ...
    'The next daily boundary replayed the previous weathering source.');

final_release = [0.25; 0.75];
[P43_flushed,flushed_umol] = ERW_Return_Weathered_Phosphorus( ...
    P43_day2,aP*P43_day2/31*1e6+sum(final_release),aP,final_release);
[P43_resumed,resumed_umol] = ERW_Return_Weathered_Phosphorus( ...
    P43_flushed,aP*P43_flushed/31*1e6,aP,zeros(0,1));
assert(flushed_umol == 1 && resumed_umol == 0 && ...
    P43_resumed == P43_flushed, ...
    'A final flush or resumed window replayed weathered phosphorus.');

[P43_zero,zero_release] = ERW_Return_Weathered_Phosphorus( ...
    P43_before,aP*P43_before/31*1e6,aP,EW*zeros(2,1)*dtw);
assert(P43_zero == P43_before && zero_release == 0, ...
    'A P-free feedstock must return exactly zero phosphorus.');

[P43_aP0,aP0_release] = ERW_Return_Weathered_Phosphorus( ...
    P43_before,release_umol,0,release_by_step);
assert(P43_aP0 == P43_after && aP0_release == release_umol, ...
    'The zero-dissolved-fraction boundary lost weathered phosphorus.');

PO4_tot_full = P43_before/31*1e6 + release_umol;
[P43_full,full_release] = ERW_Return_Weathered_Phosphorus( ...
    P43_before,PO4_tot_full,1,release_by_step);
expected_full = PO4_tot_full*31/1e6;
assert(abs(P43_full-expected_full) < 1e-15 && ...
    full_release == release_umol, ...
    'The full-pool path must write the dissolved level without double counting.');
double_counted_full = expected_full + release_umol*31/1e6;
assert(abs(P43_full-double_counted_full) > 1e-9, ...
    'The aP = 1 test does not distinguish level writeback from addition.');

assert_error(@() ERW_Return_Weathered_Phosphorus( ...
    P43_before,PO4_tot_end,aP,[1; -0.5]), ...
    'ERW:invalidPhosphorusRelease');
assert_error(@() ERW_Return_Weathered_Phosphorus( ...
    P43_before,PO4_tot_end,aP,[0; NaN]), ...
    'ERW:invalidPhosphorusRelease');
assert_error(@() ERW_Return_Weathered_Phosphorus( ...
    P43_before,PO4_tot_end,1.1,release_by_step), ...
    'ERW:invalidPhosphorusState');
assert_error(@() ERW_Return_Weathered_Phosphorus( ...
    -P43_before,PO4_tot_end,aP,release_by_step), ...
    'ERW:invalidPhosphorusState');
assert_error(@() ERW_Return_Weathered_Phosphorus( ...
    P43_before,-PO4_tot_end,aP,release_by_step), ...
    'ERW:invalidPhosphorusState');
assert_error(@() ERW_Return_Weathered_Phosphorus( ...
    P43_before,PO4_tot_end,aP,[release_by_step; 1]), ...
    'ERW:phosphorusBudget');

erw = fileread(fullfile(code_dir,'ERW_function.m'));
frame_1d = fileread(fullfile(code_dir,'MAIN_FRAME_BG_ERW_10mins.m'));
step_2d = fileread(fullfile(code_dir,'ERW_Daily_Step_2D.m'));

assert(contains(erw, ...
    "P_weathering_release = sum(min_st(:,7)'.*EW(j_only,:))*dtw;") && ...
    contains(erw,'PO4_tot= PO4_tot(j_only)+P_weathering_release+dPO4_tot(1)*dtw;') && ...
    contains(erw,'dAlk_PO4_w = -P_weathering_release;') && ...
    contains(erw,'ERW_weathering.P_weathering_release = P_weathering_release;'), ...
    'ERW must expose the exact P increment already booked to PO4_tot.');

assert(contains(frame_1d,'ERW_biogeochem.PO4_tot(anchor_row,:)') && ...
    contains(step_2d,'bg.PO4_tot(anchor_row,:)'), ...
    'Both drivers must anchor dissolved P at every daily boundary.');
assert(count(frame_1d,'ERW_Return_Weathered_Phosphorus') == 1 && ...
    count(step_2d,'ERW_Return_Weathered_Phosphorus') == 1, ...
    'The 1-D and 2-D drivers must use the same phosphorus-return operator.');
assert(contains(frame_1d, ...
    'ERW_weathering.P_weathering_release(max(dm_start,2):dm_end,:)') && ...
    contains(step_2d, ...
    'weath.P_weathering_release(max(dm_start,2):dm_end,:)'), ...
    'Both drivers must return only the current ERW-window release.');

fprintf('PASS: weathered phosphorus returns once and is repartitioned daily.\n');
end

function assert_error(f,identifier)
try
    f();
catch ME
    assert(strcmp(ME.identifier,identifier), ...
        'Expected %s, got %s.',identifier,ME.identifier);
    return
end
error('Expected %s, but no error was raised.',identifier);
end
