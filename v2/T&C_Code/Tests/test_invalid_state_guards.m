function test_invalid_state_guards
%%% Shared daily state updates must reject invalid numerical states.

test_dir = fileparts(mfilename('fullpath'));
code_dir = fullfile(test_dir,'..');
biogeo_source = fileread(fullfile(code_dir,'BIOGEO_UNIT.m'));
plant_source = fileread(fullfile(code_dir,'Plant_Exports.m'));
nutrient_source = fileread(fullfile(code_dir,'Nutrients_Available.m'));

assert(contains(biogeo_source,'~isreal(dP) || any(~isfinite(dP))'), ...
    'Biogeochemistry increments must reject complex and nonfinite values.');
assert(contains(biogeo_source,'BIOGEO_UNIT:InvalidPoolIncrement'), ...
    'Invalid biogeochemistry increments require an explicit error.');
assert(contains(biogeo_source,'~isreal(P) || any(~isfinite(P))'), ...
    'Updated biogeochemistry pools must reject invalid values.');
assert(contains(biogeo_source,'BIOGEO_UNIT:ExcessivePoolState'), ...
    'Excessive biogeochemistry pools require an explicit error.');
assert(~contains(biogeo_source,"disp('Issue in the Biogeochemistry Pools')"), ...
    'Excessive pools must not return silently after a diagnostic message.');
assert(contains(plant_source,'~isreal(IS) || any(~isfinite(IS))'), ...
    'Litter transfers must reject complex and nonfinite values.');
assert(contains(plant_source,'Plant_Exports:InvalidLitterTransfer'), ...
    'Invalid litter transfers require an explicit error.');
assert(isempty(regexp(nutrient_source, ...
    'Nutrient Concentrations outside allowed bounds!!''\)\s*return','once')), ...
    'A nutrient-concentration diagnostic must not return with unassigned outputs.');
assert(contains(nutrient_source,'persistent nw_Nl'), ...
    'Nutrient concentration warnings must retain the TC-SMEW episode guard.');

fprintf('PASS: shared daily state updates reject invalid numerical states.\n');
end
