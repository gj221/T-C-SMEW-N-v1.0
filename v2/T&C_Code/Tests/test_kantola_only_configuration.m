function test_kantola_only_configuration
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Kantola-only input and launcher contract.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

fprintf('\n=== test_kantola_only_configuration ===\n');
n_pass = 0;

test_dir = fileparts(mfilename('fullpath'));
v2 = fileparts(fileparts(test_dir));
input_dir = fullfile(v2,'T&C_Code','Inputs');
parameter_dir = fullfile(v2,'T&C_Code','Parameters');
wb = fullfile(input_dir,'ERW_MOD_PARAM_parameters.xlsx');

M = readtable(wb,'Sheet','MOD_PARAM');
E = readtable(wb,'Sheet','ERW_MOD');
M = M(~ismissing(M.Number),:);
E = E(~ismissing(E.Number),:);

check(isequal(M.Number(:),(3:7)') && isequal(E.Number(:),(3:8)'), ...
    'the five Kantola workbook cases are retained');
check(all(string(M.Location) == "Kantola") && ...
      all(string(E.Location) == "Kantola"), ...
    'all workbook rows are Kantola configurations');
check(all(string(M.MOD_PARAM) == "MOD_PARAM_Kantola_Maize_Soy"), ...
    'all model rows use the Kantola parameter file');

required_files = { ...
    fullfile(input_dir,'Data_Kantola.mat'); ...
    fullfile(input_dir,'Data_Kantola_BG.mat'); ...
    fullfile(input_dir,'Ca_Data.mat'); ...
    fullfile(input_dir,'All_deposition_data.mat'); ...
    fullfile(input_dir,'blueridge_CDF_data.json'); ...
    fullfile(parameter_dir,'MOD_PARAM_Kantola_Maize_Soy.m'); ...
    fullfile(parameter_dir,'PFT_Prairie_Margin.m')};
check(all(cellfun(@isfile,required_files)), ...
    'Kantola and shared inputs remain available');

removed_files = { ...
    fullfile(v2,'plotting','Benchmarking_final_Kelland_TConly.m'); ...
    fullfile(v2,'run','Run_Matrix_9.m'); ...
    fullfile(v2,'run','Run_All_9_Parallel.m'); ...
    fullfile(test_dir,'test_run_matrix_launcher.m'); ...
    fullfile(input_dir,'Data_Kelland.mat'); ...
    fullfile(input_dir,'Data_Kelland_BG.mat'); ...
    fullfile(input_dir,'Ca_Data_Ann.mat'); ...
    fullfile(input_dir,'psd.json'); ...
    fullfile(parameter_dir,'MOD_PARAM_General.m'); ...
    fullfile(parameter_dir,'PFT_selection_parameters.m'); ...
    fullfile(parameter_dir,'Table_Sites_PFT_LOOKUP_latest.xlsx')};
check(~any(cellfun(@isfile,removed_files)), ...
    'superseded and non-Kantola configuration files are absent');

entry_text = fileread(fullfile(v2,'run','ERW_run.m'));
check(~isempty(regexp(entry_text,"id_location\s*=\s*'Kantola'",'once')) && ...
      ~contains(entry_text,'TC_LOCATION') && ~contains(entry_text,'Kelland'), ...
    'the legacy single-column entry point is fixed to Kantola');

fprintf('  ---------------------------------------\n');
fprintf('  %d passed, 0 failed\n',n_pass);

    function check(ok,label)
        assert(ok,'test_kantola_only_configuration:Failed','%s',label);
        n_pass = n_pass + 1;
        fprintf('  PASS  %s\n',label);
    end

end
