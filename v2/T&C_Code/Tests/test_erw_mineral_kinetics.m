function test_erw_mineral_kinetics
%%% Mineral affinities and Arrhenius constants retain physical dimensions.

test_dir = fileparts(mfilename('fullpath'));
code_dir = fullfile(test_dir,'..');
addpath(code_dir);

conv_mol = 1e6;
K_quartz = 1e-4;
Si = 40;
Omega_acid = ERW_Mineral_Saturation('quartz',0,0,0,0,Si,0,0, ...
    10^(-4)*conv_mol,K_quartz,conv_mol,1,0);
Omega_neutral = ERW_Mineral_Saturation('quartz',0,0,0,0,Si,0,0, ...
    10^(-8)*conv_mol,K_quartz,conv_mol,1,0);
assert(abs(Omega_acid-0.4) < 1e-12 && ...
    abs(Omega_neutral-Omega_acid) < 1e-12, ...
    'Quartz saturation must be a(H4SiO4)/K and independent of pH.');

Omega_supersaturated = ERW_Mineral_Saturation('quartz',0,0,0,0,200,0,0, ...
    10^(-6)*conv_mol,K_quartz,conv_mol,1,0);
assert(abs(Omega_supersaturated-2) < 1e-12, ...
    'Reported mineral saturation must retain the raw supersaturated ratio.');
assert(max(0,1-Omega_supersaturated) == 0, ...
    'A supersaturated primary mineral must have zero dissolution affinity.');

K_albite = 10^(2.7645/4);
Omega_albite_1 = ERW_Mineral_Saturation('albite',0,0,0,1e3,1e3,1e3,0, ...
    1,K_albite,conv_mol,1,0);
Omega_albite_2 = ERW_Mineral_Saturation('albite',0,0,0,1e3,1e3,16e3,0, ...
    1,K_albite,conv_mol,1,0);
assert(abs(Omega_albite_2/Omega_albite_1-2) < 1e-12, ...
    'Albite Omega must contain Al activity to the 1/4 power.');

K_anorthite = 10^(26.578/8);
Omega_anorthite_1 = ERW_Mineral_Saturation('anorthite',0,1e3,0,0,1e3,1e3,0, ...
    1,K_anorthite,conv_mol,1,0);
Omega_anorthite_2 = ERW_Mineral_Saturation('anorthite',0,1e3,0,0,16e3,1e3,0, ...
    1,K_anorthite,conv_mol,1,0);
assert(abs(Omega_anorthite_2/Omega_anorthite_1-2) < 1e-12, ...
    'Anorthite Omega must contain dissolved Si to the 1/4 power.');

%% The quotients above are the Al+++ reactions, so their constants are the
%% llnl.dat log K (2.7645 albite, 26.578 anorthite) rooted per proton; a
%% composition at that equilibrium must read Omega = 1.
par = fileread(fullfile(code_dir,'Parameters','ERW_MOD_PARAM_excel.m'));
assert(contains(par,'K_sp = 10^(2.7645/4);') && contains(par,'K_sp = 10^(26.578/8);'), ...
    'Albite and anorthite must carry their Al+++ reaction constants.');
h = 1e-5; na = 1e-3; ca = 1e-3; al_ab = 1e-7; al_an = 1e-4;
si_ab = (10^2.7645*h^4/(na*al_ab))^(1/3);
si_an = sqrt(10^26.578*h^8/(ca*al_an^2));
Omega_ab = ERW_Mineral_Saturation('albite',0,0,0,na*conv_mol,si_ab*conv_mol, ...
    al_ab*conv_mol,0,h*conv_mol,K_albite,conv_mol,1,0);
Omega_an = ERW_Mineral_Saturation('anorthite',0,ca*conv_mol,0,0,si_an*conv_mol, ...
    al_an*conv_mol,0,h*conv_mol,K_anorthite,conv_mol,1,0);
assert(abs(Omega_ab-1) < 1e-10 && abs(Omega_an-1) < 1e-10, ...
    'A composition at llnl.dat equilibrium must give Omega = 1.');

K_zoisite_full = 10^43.85;
H_zoisite_eq = 10^(-43.85/13)*conv_mol;
Omega_zoisite = ERW_Mineral_Saturation('zoisite',0,1e6,0,0,1e6,1e6,0, ...
    H_zoisite_eq,K_zoisite_full,conv_mol,1,0);
assert(abs(Omega_zoisite-1) < 1e-12, ...
    'Zoisite must root its full reaction quotient and equilibrium constant by 13 H+.');

[Omega_epidote,defined_epidote] = ERW_Mineral_Saturation('epidote',0,1e3,0,0, ...
    1e3,1e3,0,1,10^32.23,conv_mol,1,0);
assert(~defined_epidote && isnan(Omega_epidote), ...
    'Fe-bearing epidote must not report a saturation index without aqueous Fe3+.');
[Omega_apatite,defined_apatite] = ERW_Mineral_Saturation('apatite',0,1e3,0,0, ...
    0,0,1e3,1,10^14.34,conv_mol,1,0);
assert(~defined_apatite && isnan(Omega_apatite), ...
    'Apatite must not report a saturation index from an unspeciated total-P pool.');

% Davies activities: the same calls at ionic strength I must scale each
% Omega by the closed-form product of the ions' activity coefficients at
% the exponents the quotient already carries; Si (H4SiO4) is neutral.
I_test = 0.1;
g1 = ERW_Activity_Coefficient(1,I_test);
g2 = ERW_Activity_Coefficient(2,I_test);
g3 = ERW_Activity_Coefficient(3,I_test);
Omega_albite_I = ERW_Mineral_Saturation('albite',0,0,0,1e3,1e3,1e3,0, ...
    1,K_albite,conv_mol,1,I_test);
assert(abs(Omega_albite_I/Omega_albite_1-g1^(1/4)*g3^(1/4)/g1) < 1e-12, ...
    'Albite activity correction must be gamma1^(1/4) gamma3^(1/4) / gamma1.');
Omega_anorthite_I = ERW_Mineral_Saturation('anorthite',0,1e3,0,0,1e3,1e3,0, ...
    1,K_anorthite,conv_mol,1,I_test);
assert(abs(Omega_anorthite_I/Omega_anorthite_1-g2^(1/8)*g3^(2/8)/g1) < 1e-12, ...
    'Anorthite activity correction must be gamma2^(1/8) gamma3^(1/4) / gamma1.');
Omega_quartz_I = ERW_Mineral_Saturation('quartz',0,0,0,0,Si,0,0, ...
    10^(-4)*conv_mol,K_quartz,conv_mol,1,I_test);
assert(abs(Omega_quartz_I-Omega_acid) < 1e-12, ...
    'Quartz (neutral H4SiO4) must take no activity correction.');
Omega_albite_I0 = ERW_Mineral_Saturation('albite',0,0,0,1e3,1e3,1e3,0, ...
    1,K_albite,conv_mol,1,0);
assert(abs(Omega_albite_I0-Omega_albite_1) < 1e-12, ...
    'I = 0 must reproduce the concentration-basis Omega.');

% Al arrives on the solver's Al_CEC_scale basis: the scaled value with the
% scale declared must equal the unscaled value without it.
Omega_albite_scaled = ERW_Mineral_Saturation('albite',0,0,0,1e3,1e3,1e3*1e3,0, ...
    1,K_albite,conv_mol,1e3,0);
assert(abs(Omega_albite_scaled-Omega_albite_1) < 1e-12*Omega_albite_1, ...
    'Al on the Al_CEC_scale basis must be divided by Al_CEC_scale before entering Omega.');
Omega_zoisite_scaled = ERW_Mineral_Saturation('zoisite',0,1e6,0,0,1e6,1e9,0, ...
    H_zoisite_eq,K_zoisite_full,conv_mol,1e3,0);
assert(abs(Omega_zoisite_scaled-1) < 1e-12, ...
    'Zoisite at equilibrium must read Omega = 1 with Al on the scaled basis.');

% The production caller must declare the scale and pass the ionic strength
% its constants were conditioned at, and the rate law must take the proton
% activity rather than the concentration.
erw_source = fileread(fullfile(code_dir,'ERW_function.m'));
assert(contains(erw_source, ...
    'H, K_sp(min_j), conv_mol, Al_CEC_scale, activity_I); %[-]'), ...
    'ERW_function must pass Al_CEC_scale and activity_I to ERW_Mineral_Saturation.');
assert(contains(erw_source,'(gamma_mono*H/conv_mol)^n_H(min_j)') && ...
    contains(erw_source,'(gamma_mono*H/conv_mol)^n_OH(min_j)') && ...
    ~contains(erw_source,'(H/conv_mol)^n_H(min_j)'), ...
    'The silicate rate law must take the proton activity gamma_mono*H.');
assert(contains(erw_source, ...
    'ionic_str = ERW_Ionic_Strength(Ca,Mg,Na,K,Al/Al_CEC_scale,H,NH4,NO3,HCO3,CO3,An,conv_mol, ...') && ...
    contains(erw_source,'PO4,AlOH/Al_CEC_scale,AlOH2/Al_CEC_scale,AlOH4/Al_CEC_scale,k_w/H);'), ...
    'ERW_function must include charged Al hydroxides, phosphate and OH in ionic strength.');

E_a = 65;
R = 8.314;
T_ref = 298.15;
T = 308.15;
ratio = exp(-E_a*1000/R*(1/T-1/T_ref));
assert(ratio > 2.3 && ratio < 2.4, ...
    'A 65 kJ/mol activation energy must produce the expected warming response.');

param_source = fileread(fullfile(code_dir,'Parameters','ERW_MOD_PARAM_excel.m'));
bad_energy = regexp(param_source, ...
    'E_(?:H|w|OH)\s*=\s*[^;\r\n]*/conv_mol\s*;', 'once');
assert(isempty(bad_energy), ...
    'Activation energy is kJ/mol and must not be divided by conv_mol.');
bad_R = regexp(param_source, ...
    'R\s*=\s*8\.314\s*/\s*conv_mol\s*;', 'once');
assert(isempty(bad_R), ...
    'The Arrhenius gas constant must remain 8.314 J mol^-1 K^-1.');
assert(contains(param_source, ...
    'min_st = [2, 0, 0, 0, 2.53, 3, 0]'), ...
    'Epidote release must retain the three Si in Ca2(Al,Fe)3Si3O12(OH).');
assert(contains(param_source, ...
    'H(1), K_sp(min_j), conv_mol, Al_CEC_scale, activity_I(1));'), ...
    'ERW_MOD_PARAM_excel must pass Al_CEC_scale and the seed ionic strength to ERW_Mineral_Saturation.');

%% The amphiboles carry the rate law of Hermanska et al. (2022), measured
%% on tremolite, not the Palandri and Kharaka tremolite row, which is taken
%% from Sverdrup (1990) and is about 60 times faster at pH 6.
amphibole = regexp(param_source, ...
    'strcmp\(mineral, ''(?:ferroactinolite|actinolite)''\).*?K_sp','match');
assert(numel(amphibole) == 2 && ...
    all(cellfun(@(x) contains(x,'k_diss_H = 10^(-11.3)*24*3600*conv_mol;') && ...
        contains(x,'k_diss_w = 10^(-13.1)*24*3600*conv_mol;') && ...
        contains(x,'E_H = 50;') && contains(x,'E_w = 48;') && ...
        contains(x,'n_H = 0.2;'),amphibole)) && ...
    ~contains(param_source,'10^(-8.4)*24*3600*conv_mol'), ...
    'Ferroactinolite and actinolite must carry the Hermanska et al. (2022) amphibole rate law.');
k_pH6 = 10^(-11.3)*(1e-6)^0.2 + 10^(-13.1);
assert(abs(log10(k_pH6)+12.40) < 0.01 && ...
    (10^(-8.4)*(1e-6)^0.7 + 10^(-10.6))/k_pH6 > 60, ...
    'The amphibole rate at pH 6 and 25 C must be 10^-12.4 mol m-2 s-1.');

fprintf('PASS: mineral affinities and Arrhenius constants are dimensionally correct.\n');
end
