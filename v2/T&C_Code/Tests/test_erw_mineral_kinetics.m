function test_erw_mineral_kinetics
%%% Mineral affinities and Arrhenius constants retain physical dimensions.

test_dir = fileparts(mfilename('fullpath'));
code_dir = fullfile(test_dir,'..');
addpath(code_dir);

conv_mol = 1e6;
K_quartz = 1e-4;
Si = 40;
Omega_acid = ERW_Mineral_Saturation('quartz',0,0,0,0,Si,0,0, ...
    10^(-4)*conv_mol,K_quartz,conv_mol);
Omega_neutral = ERW_Mineral_Saturation('quartz',0,0,0,0,Si,0,0, ...
    10^(-8)*conv_mol,K_quartz,conv_mol);
assert(abs(Omega_acid-0.4) < 1e-12 && ...
    abs(Omega_neutral-Omega_acid) < 1e-12, ...
    'Quartz saturation must be a(H4SiO4)/K and independent of pH.');

Omega_supersaturated = ERW_Mineral_Saturation('quartz',0,0,0,0,200,0,0, ...
    10^(-6)*conv_mol,K_quartz,conv_mol);
assert(abs(Omega_supersaturated-2) < 1e-12, ...
    'Reported mineral saturation must retain the raw supersaturated ratio.');
assert(max(0,1-Omega_supersaturated) == 0, ...
    'A supersaturated primary mineral must have zero dissolution affinity.');

K_albite = 10^-0.68;
Omega_albite_1 = ERW_Mineral_Saturation('albite',0,0,0,1e3,1e3,1e3,0, ...
    1,K_albite,conv_mol);
Omega_albite_2 = ERW_Mineral_Saturation('albite',0,0,0,1e3,1e3,16e3,0, ...
    1,K_albite,conv_mol);
assert(abs(Omega_albite_2/Omega_albite_1-2) < 1e-12, ...
    'Albite Omega must contain Al activity to the 1/4 power.');

K_anorthite = 10^9.83;
Omega_anorthite_1 = ERW_Mineral_Saturation('anorthite',0,1e3,0,0,1e3,1e3,0, ...
    1,K_anorthite,conv_mol);
Omega_anorthite_2 = ERW_Mineral_Saturation('anorthite',0,1e3,0,0,16e3,1e3,0, ...
    1,K_anorthite,conv_mol);
assert(abs(Omega_anorthite_2/Omega_anorthite_1-2) < 1e-12, ...
    'Anorthite Omega must contain dissolved Si to the 1/4 power.');

K_zoisite_full = 10^43.85;
H_zoisite_eq = 10^(-43.85/13)*conv_mol;
Omega_zoisite = ERW_Mineral_Saturation('zoisite',0,1e6,0,0,1e6,1e6,0, ...
    H_zoisite_eq,K_zoisite_full,conv_mol);
assert(abs(Omega_zoisite-1) < 1e-12, ...
    'Zoisite must root its full reaction quotient and equilibrium constant by 13 H+.');

[Omega_epidote,defined_epidote] = ERW_Mineral_Saturation('epidote',0,1e3,0,0, ...
    1e3,1e3,0,1,10^32.23,conv_mol);
assert(~defined_epidote && isnan(Omega_epidote), ...
    'Fe-bearing epidote must not report a saturation index without aqueous Fe3+.');
[Omega_apatite,defined_apatite] = ERW_Mineral_Saturation('apatite',0,1e3,0,0, ...
    0,0,1e3,1,10^14.34,conv_mol);
assert(~defined_apatite && isnan(Omega_apatite), ...
    'Apatite must not report a saturation index from an unspeciated total-P pool.');

E_a = 65;
R = 8.314;
T_ref = 298.15;
T = 308.15;
ratio = exp(-E_a*1000/R*(1/T-1/T_ref));
assert(ratio > 2.3 && ratio < 2.4, ...
    'A 65 kJ/mol activation energy must produce the expected warming response.');

param_source = fileread(fullfile(code_dir,'Parameters','ERW_MOD_PARAM_excel.m'));
bad_energy = regexp(param_source, ...
    'E_(?:H|w|OH)\s*=\s*[^;\r\n]*/conv_mol\s*;', 'once');
assert(isempty(bad_energy), ...
    'Activation energy is kJ/mol and must not be divided by conv_mol.');
bad_R = regexp(param_source, ...
    'R\s*=\s*8\.314\s*/\s*conv_mol\s*;', 'once');
assert(isempty(bad_R), ...
    'The Arrhenius gas constant must remain 8.314 J mol^-1 K^-1.');
assert(contains(param_source, ...
    'min_st = [2, 0, 0, 0, 2.53, 3, 0]'), ...
    'Epidote release must retain the three Si in Ca2(Al,Fe)3Si3O12(OH).');

fprintf('PASS: mineral affinities and Arrhenius constants are dimensionally correct.\n');
end
