function test_checkpoint_fingerprint_dependencies
% Checkpoints track code and input files that alter ERW trajectories.

test_dir = fileparts(mfilename('fullpath'));
code_dir = fileparts(test_dir);
addpath(code_dir);
code = fileread(fullfile(code_dir,'MAIN_FRAME_BG_ERW_2D.m'));
fp_source = fileread(fullfile(code_dir,'ERW_Checkpoint_Fingerprint.m'));

assert(contains(code,"fullfile(cd, '*.m')") && ...
       contains(code,"fullfile(cd, 'Parameters', '*.m')"), ...
    'Checkpoint fingerprint must cover all production MATLAB sources.');
assert(contains(fp_source,'SHA-256') && ~contains(fp_source,'.datenum'), ...
    'Checkpoint dependencies must be fingerprinted by content.');
assert(contains(code,'mat2str(appelo_alpha_c,17)') && ...
       contains(code,'mat2str(appelo_logKH_c,17)'), ...
    'Checkpoint identity must include exact effective Appelo constants.');
assert(contains(code,'mat2str(PAR{c}.Pcla,17)') && ...
       contains(code,'mat2str(PAR{c}.Psan,17)') && ...
       contains(code,'mat2str(knmaxd_c,17)'), ...
    'Checkpoint identity must include exact texture and KNmaxd overrides.');
assert(contains(code,"isfield(ColCfg(c),'cec_dpH')") && ...
       contains(code,'mat2str(cec_dpH_c,17)'), ...
    'Checkpoint identity must include the exact variable-CEC sensitivity.');
assert(contains(code,"isfield(ColCfg(c),'appelo_alpha')") && ...
       contains(code,"isfield(ColCfg(c),'appelo_logKH')"), ...
    'Checkpoint identity must preserve legacy ColCfg callers without overrides.');
assert(contains(code,'ERW_runtime_param_c = ERW_PARAM_input;') && ...
       contains(code,"isfield(ColCfg(c),'ERW_PARAM')") && ...
       contains(code,'ERW_runtime_param_c = ColCfg(c).ERW_PARAM;') && ...
       contains(code,'ERW_Runtime_Parameter_Identity(ERW_runtime_param_c)') && ...
       ~contains(code,'ERW_Runtime_Parameter_Identity(ColCfg(c).ERW_PARAM)'), ...
    'Checkpoint identity must serialize the effective ERW table, including the shared fallback.');

runtime_table = table(1.3,string('calcite'),NaN, ...
    'VariableNames',{'diss_f','mineral','M_rock_in'});
table_id_1 = ERW_Runtime_Parameter_Identity(runtime_table);
runtime_table.diss_f = 1.3000000000000003;
table_id_2 = ERW_Runtime_Parameter_Identity(runtime_table);
assert(~strcmp(table_id_1,table_id_2), ...
    'Runtime identity must distinguish adjacent effective double values.');
runtime_table.mineral = string(missing);
table_id_3 = ERW_Runtime_Parameter_Identity(runtime_table);
assert(~strcmp(table_id_2,table_id_3), ...
    'Runtime identity must distinguish missing text from a real value.');

assert(contains(code,"fullfile(cd, 'ERW_Mineral_Molar_Mass_Row.m')"), ...
    'Checkpoint fingerprint omits the mineral molar-mass helper.');
assert(contains(code,"fullfile(cd, 'Inputs', 'ERW_MOD_PARAM_parameters.xlsx')"), ...
    'Checkpoint fingerprint omits the ERW parameter workbook.');

required_sources = {'BIOGEOCHEMISTRY_DYNAMIC3.m','BIOGEO_UNIT.m', ...
    'Biogeochemistry_Parameter.m','Biogeo_Cation_Partition_Rates.m', ...
    'Biogeo_Mobile_Water_Volume.m', ...
    'Biogeo_Nitrification_PH_Response.m','CropHeightType.m','Plant_Exports.m', ...
    'Plant_Reserve_Fraction.m', ...
    'Plant_Nutrient_Suppression.m', ...
    'Plant_Harvest_Reserve_Export.m','Crop_Planting_Harvest.m', ...
    'Plant_Establishment_Element_Boundary.m', ...
    'Plant_Seed_Input_Accumulator.m', ...
    'ERW_AlOH3_LogK.m','ERW_Appelo_Mass_Conserving_State.m', ...
    'ERW_Appelo_State_At_H.m','ERW_CEC_At_H.m', ...
    'ERW_Calcite_Kinetics.m','ERW_Calcite_Reaction_Limit.m', ...
    'ERW_Resolve_CEC.m','ERW_Resolve_CEC_pH_Sensitivity.m', ...
    'ERW_Seed_Water_Loss.m', ...
    'ERW_Feedstock_Pathway.m','ERW_Particle_Mass_Fractions.m', ...
    'ERW_Mineral_DIC_Stoichiometry.m', ...
    'ERW_Total_Calcite_Solid.m','ERW_Should_Apply_TC_Daily_Delta.m', ...
    'ERW_Return_Weathered_Phosphorus.m', ...
    'ERW_Daily_Step_2D.m','ERW_Particle_History.m', ...
    'Invert_Bulk_pH.m','Porewater_to_Bulk_pH.m'};
for k = 1:numel(required_sources)
    pattern = sprintf("fullfile(cd, '%s')",required_sources{k});
    assert(contains(code,pattern), ...
        'Checkpoint fingerprint omits %s.',required_sources{k});
end
listed = regexp(code,"fullfile\(cd, '([^'*]+\.m)'\)",'tokens');
for k = 1:numel(listed)
    assert(isfile(fullfile(code_dir,listed{k}{1})), ...
        'Checkpoint fingerprint lists a missing source %s.',listed{k}{1});
end

assert(contains(code,"fullfile(cd, 'Parameters', 'MOD_PARAM_Kantola_Maize_Soy.m')"), ...
    'Checkpoint fingerprint omits the Kantola crop parameter source.');
assert(contains(code,"fullfile(cd, 'Parameters', 'ERW_MOD_PARAM_excel.m')"), ...
    'Checkpoint fingerprint omits the ERW initialization source.');

tmp = tempname;
mkdir(tmp);
cleanup = onCleanup(@() rmdir(tmp,'s'));
f1 = fullfile(tmp,'a.m');
f2 = fullfile(tmp,'input.xlsx');
write_text(f1,'a');
write_text(f2,'first');
runtime1 = 'alpha=1.3;logKH=[4.71627429367 3.61627429367 8.10254858734 8.41854858734 12.918822881]';
runtime2 = 'alpha=1.3;logKH=[4.71627429368 3.61627429367 8.10254858734 8.41854858734 12.918822881]';
fp1 = ERW_Checkpoint_Fingerprint(24,1,runtime1,f1,f2);
write_text(f2,'second version');
fp2 = ERW_Checkpoint_Fingerprint(24,1,runtime1,f1,f2);
assert(~strcmp(fp1,fp2),'Input-file changes must invalidate a checkpoint.');

write_text(f1,'b');
fp3 = ERW_Checkpoint_Fingerprint(24,1,runtime1,f1,f2);
assert(~strcmp(fp2,fp3), ...
    'A same-size source-content change must invalidate a checkpoint.');

fp4 = ERW_Checkpoint_Fingerprint(24,1,runtime2,f1,f2);
assert(~strcmp(fp3,fp4), ...
    'An exact runtime-chemistry change must invalidate a checkpoint.');

frame_source = fileread(fullfile(fileparts(mfilename('fullpath')), ...
    '..','MAIN_FRAME_BG_ERW_2D.m'));
assert(contains(frame_source,'date_start=%.17g') && ...
    contains(frame_source,'date_end=%.17g'), ...
    'Checkpoint identity must include the exact forcing interval.');
assert(contains(frame_source,'topology_areas=') && ...
    contains(frame_source,'topology_edge_a=') && ...
    contains(frame_source,'column_param='), ...
    'Checkpoint identity must include effective topology and column scenarios.');
assert(contains(frame_source,'TC_NUMERICAL_IDENTITY') && ...
    contains(frame_source,'parallel_workers=%d'), ...
    'Checkpoint identity must include the numerical platform and worker count.');
%% TC_NUMERICAL_IDENTITY is only what the submission script asked for.  A
%% rebuilt MATLAB module can pass campaign validation while an older
%% checkpoint still resumes, so the identity must carry what is really
%% loaded as well.
assert(contains(frame_source,"evalc('version -blas')") && ...
    contains(frame_source,'maxNumCompThreads') && ...
    contains(frame_source,'matlab=%s;computer=%s'), ...
    'Checkpoint identity must include the actual numerical runtime.');
for name = {'Data_Kantola.mat','Data_Kantola_BG.mat','Ca_Data.mat', ...
        'All_deposition_data.mat','blueridge_CDF_data.json', ...
        'Run_One_Subfield.m','Run_Matrix_12.m'}
    assert(contains(frame_source,name{1}), ...
        'Checkpoint dependencies must include %s.',name{1});
end

fprintf('PASS: checkpoint fingerprint tracks code, inputs and runtime identity.\n');
end

function write_text(file,text)
fid = fopen(file,'w');
assert(fid > 0,'Could not create fingerprint test input.');
cleanup = onCleanup(@() fclose(fid));
fprintf(fid,'%s',text);
end
