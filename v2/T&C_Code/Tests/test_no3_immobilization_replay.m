function test_no3_immobilization_replay
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Replay the first negative-NO3 transition from the Kantola control.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

here = fileparts(mfilename('fullpath'));
code = fileparts(here);
addpath(code,fullfile(code,'Inputs'),fullfile(code,'Parameters'));
F = load(fullfile(here,'Fixtures','no3_immobilization_20190906.mat'),'fixture');
F = F.fixture;

assert(isequal(F.date,[2019 9 6]) && F.P1(32) < 0, ...
    'test_no3_immobilization_replay:BadFixture', ...
    'The failed-day fixture is not the 6 September 2019 transition.');

[dP,~,~,~,~,VOL,N2flx,Min_N,~,~,~,~,~,~,N2Oflx] = ...
    BIOGEOCHEMISTRY_DYNAMIC3(F.args{:});
Pnew = F.args{2} + dP;
tol = 1e-10;

assert(isfinite(Min_N) && abs(Min_N) <= abs(F.Min_N)+tol, ...
    'test_no3_immobilization_replay:FluxMismatch', ...
    'Realized mineral-N transfer is invalid: %.16g gN/m2/day.',Min_N);
assert(Pnew(31) >= 0 && Pnew(32) >= 0, ...
    'test_no3_immobilization_replay:NegativeMineralN', ...
    'Mineral N became negative: NH4 %.16g, NO3 %.16g gN/m2.', ...
    Pnew(31),Pnew(32));
[~,mobile] = Biogeo_Lateral_Pools(Pnew);
assert(all(isfinite(mobile) & mobile >= 0), ...
    'test_no3_immobilization_replay:LateralPools', ...
    'The corrected transition is not valid for lateral transport.');

balance_error = sum(Pnew(23:34))-sum(F.P1(23:34)) + ...
    VOL+N2flx+N2Oflx-F.VOL-F.N2flx-F.N2Oflx;
assert(abs(balance_error) < tol, ...
    'test_no3_immobilization_replay:NitrogenBalance', ...
    'The corrected transition changed total N by %.16g gN/m2.',balance_error);

depleted_args = F.args;
depleted_args{2}([31 32]) = 0;
for k = [13 14 25 26 33 34]
    depleted_args{k} = 0;
end
[dP_depleted,~,~,~,~,~,~,Min_N_depleted] = ...
    BIOGEOCHEMISTRY_DYNAMIC3(depleted_args{:});
P_depleted = depleted_args{2} + dP_depleted;
assert(all(isfinite(P_depleted([26 31 32]))) && ...
    P_depleted(31) >= 0 && P_depleted(32) >= 0, ...
    'test_no3_immobilization_replay:DepletedMineralN', ...
    'Depleted mineral N produced NH4 %.16g and NO3 %.16g gN/m2.', ...
    P_depleted(31),P_depleted(32));
assert(abs(Min_N_depleted) < tol, ...
    'test_no3_immobilization_replay:DepletedMineralFlux', ...
    'Depleted mineral N reported a realized transfer of %.16g gN/m2/day.', ...
    Min_N_depleted);

fprintf('PASS  2019-09-06 mineral N remains nonnegative\n');
fprintf('      NH4 %.9g, NO3 %.9g gN/m2\n',Pnew(31),Pnew(32));
fprintf('PASS  depleted mineral N remains finite and nonnegative\n');
end
