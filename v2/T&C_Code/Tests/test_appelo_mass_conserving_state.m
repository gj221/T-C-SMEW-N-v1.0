function test_appelo_mass_conserving_state
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Coupled Appelo exchange and carbonate closure from conserved pools.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

fprintf('\n=== test_appelo_mass_conserving_state ===\n');
here = fileparts(mfilename('fullpath'));
addpath(fileparts(here));

[K_Na_H,K_K_H,K_Ca_H2,K_Mg_H2,K_Al_H3,alpha] = Resolve_Appelo_Constants([]);
CEC_tot = 3.34e7;
soil_water_l = 61.9;
s = 0.4034;
bulk_volume_l = soil_water_l/s;
cation_tot = [1.04525e7,2.42372e6,1.81797e6,2.45141e4];
carbonate = [0.447,4.68e-5,0.01,0.034,1e6];
appelo = [K_Na_H,K_K_H,K_Ca_H2,K_Mg_H2,K_Al_H3,alpha];
gas = [25,15,1/144];                         %% L m-2 d-1, umol L-1, d
al3_fn = @(H) 10^(-1.2)*H.^3;

H_ref = 0.8;
CO2_ref = 66.3;
[f_ref,~] = ERW_Appelo_State_At_H(H_ref,cation_tot,al3_fn(H_ref), ...
    CEC_tot,soil_water_l,alpha,K_Na_H,K_K_H,K_Ca_H2,K_Mg_H2,K_Al_H3);
R_alk_ref = sum(f_ref(1:4))*CEC_tot;
k1 = carbonate(1); k2 = carbonate(2); k_w = carbonate(3); k_H = carbonate(4);
Alk_ref = k1*CO2_ref/H_ref + 2*k1*k2*CO2_ref/H_ref^2 - H_ref + k_w/H_ref;
Alk_tot = R_alk_ref + Alk_ref*soil_water_l;
IC_final_ref = CO2_ref*bulk_volume_l*(s*(1+k1/H_ref+k1*k2/H_ref^2)+(1-s)/k_H);
Fs_ref = gas(1)*(CO2_ref/k_H-gas(2));
IC_pre = IC_final_ref+Fs_ref*gas(3);

state = ERW_Appelo_Mass_Conserving_State(Alk_tot,IC_pre,cation_tot, ...
    soil_water_l,bulk_volume_l,s,carbonate,CEC_tot,appelo,gas,al3_fn);

assert(state.is_valid, 'test_appelo_mass_conserving_state:NoRoot', ...
    'Coupled Appelo fallback did not find the known physical root.');
z = [2 2 1 1];
inventory = state.concentration.*soil_water_l + state.fraction(1:4).*CEC_tot./z;
assert(max(abs(inventory-cation_tot)./cation_tot) <= 1e-10, ...
    'test_appelo_mass_conserving_state:Mass', 'Cation inventory did not close.');
assert(abs(sum(state.fraction)-1) <= 1e-10, ...
    'test_appelo_mass_conserving_state:Sites', 'Exchange sites did not close.');
assert(abs(state.charge_residual) <= 1e-6, ...
    'test_appelo_mass_conserving_state:Charge', 'Charge balance did not close.');
assert(state.IC_tot >= 0 && abs(IC_pre-state.Fs*gas(3)-state.IC_tot) <= 1e-8, ...
    'test_appelo_mass_conserving_state:DIC', 'Implicit gas exchange did not close DIC.');

H_acid_ref = 1.81e4;
CO2_acid_ref = 950;
al3_acid_fn = @(H) zeros(size(H));
[f_acid_ref,~] = ERW_Appelo_State_At_H(H_acid_ref,cation_tot,0, ...
    CEC_tot,soil_water_l,alpha,K_Na_H,K_K_H,K_Ca_H2,K_Mg_H2,K_Al_H3);
R_alk_acid_ref = sum(f_acid_ref(1:4))*CEC_tot;
Alk_acid_ref = k1*CO2_acid_ref/H_acid_ref + ...
    2*k1*k2*CO2_acid_ref/H_acid_ref^2 - H_acid_ref + k_w/H_acid_ref;
Alk_tot_acid = R_alk_acid_ref + Alk_acid_ref*soil_water_l;
IC_final_acid = CO2_acid_ref*bulk_volume_l* ...
    (s*(1+k1/H_acid_ref+k1*k2/H_acid_ref^2)+(1-s)/k_H);
Fs_acid = gas(1)*(CO2_acid_ref/k_H-gas(2));
IC_pre_acid = IC_final_acid+Fs_acid*gas(3);

state_acid = ERW_Appelo_Mass_Conserving_State(Alk_tot_acid,IC_pre_acid, ...
    cation_tot,soil_water_l,bulk_volume_l,s,carbonate,CEC_tot,appelo,gas, ...
    al3_acid_fn,H_acid_ref);

assert(state_acid.is_valid, 'test_appelo_mass_conserving_state:AcidNoRoot', ...
    'The physical root below pH 2 was truncated by the scan boundary.');
pH_acid = -log10(state_acid.H/carbonate(5));
assert(pH_acid > 1.7 && pH_acid < 1.8, ...
    'test_appelo_mass_conserving_state:AcidRoot', ...
    'The acidic charge-balance root was not recovered.');
inventory_acid = state_acid.concentration.*soil_water_l + ...
    state_acid.fraction(1:4).*CEC_tot./z;
assert(max(abs(inventory_acid-cation_tot)./cation_tot) <= 1e-10, ...
    'test_appelo_mass_conserving_state:AcidMass', ...
    'The acidic root did not conserve cation inventory.');
assert(abs(sum(state_acid.fraction)-1) <= 1e-10 && ...
    abs(state_acid.charge_residual) <= 1e-6, ...
    'test_appelo_mass_conserving_state:AcidClosure', ...
    'The acidic root did not close sites and charge.');
assert(state_acid.IC_tot >= 0 && ...
    abs(IC_pre_acid-state_acid.Fs*gas(3)-state_acid.IC_tot) <= 1e-8, ...
    'test_appelo_mass_conserving_state:AcidDIC', ...
    'The acidic root did not close DIC.');

K_AlOH3 = 10.8;
K1 = 10; K2 = 8; K3 = 0.2; K4 = 0.631;
Al_tot_finite = 1.0e3;
Al_CEC_scale = 1000;
finite_al = struct('Al_tot',Al_tot_finite,'Al_CEC_scale',Al_CEC_scale, ...
    'K_AlOH3',K_AlOH3,'K1',K1,'K2',K2,'K3',K3,'K4',K4);
[f_finite,~,Al3_finite,Al_solid_finite,Al_residual_finite] = ...
    ERW_Appelo_State_At_H(H_ref,cation_tot,al3_fn(H_ref),CEC_tot, ...
    soil_water_l,alpha,K_Na_H,K_K_H,K_Ca_H2,K_Mg_H2,K_Al_H3,finite_al);
Al_factor_finite = 1 + K1/H_ref + K1*K2/H_ref^2 + ...
    K1*K2*K3/H_ref^3 + K1*K2*K3*K4/H_ref^4;
Al_aqueous_finite = Al3_finite*Al_CEC_scale*Al_factor_finite*soil_water_l;
Al_exchange_finite = f_finite(5)*CEC_tot*Al_CEC_scale/3;
assert(abs(Al_tot_finite-Al_aqueous_finite-Al_exchange_finite- ...
    Al_solid_finite) <= 1e-10*Al_tot_finite && ...
    abs(Al_residual_finite) <= 1e-10*Al_tot_finite, ...
    'test_appelo_mass_conserving_state:FiniteAlMass', ...
    ['Finite Al must close aqueous, exchange and solid inventory: ', ...
    'total=%.12g aqueous=%.12g exchange=%.12g solid=%.12g residual=%.12g.'], ...
    Al_tot_finite,Al_aqueous_finite,Al_exchange_finite, ...
    Al_solid_finite,Al_residual_finite);
rho_finite = (f_finite(6)/H_ref)*10^(alpha*f_finite(6));
assert(abs(f_finite(5)-K_Al_H3*Al3_finite*rho_finite^3) <= 1e-12, ...
    'test_appelo_mass_conserving_state:FiniteAlAppelo', ...
    'Finite Al must satisfy the Appelo Al/H exchange relation.');

R_alk_finite = sum(f_finite(1:4))*CEC_tot;
Alk_tot_finite = R_alk_finite + Alk_ref*soil_water_l;
state_finite = ERW_Appelo_Mass_Conserving_State(Alk_tot_finite,IC_pre, ...
    cation_tot,soil_water_l,bulk_volume_l,s,carbonate,CEC_tot,appelo,gas, ...
    al3_fn,H_ref,finite_al);
assert(state_finite.is_valid && ...
    abs(state_finite.Al_residual) <= 1e-10*Al_tot_finite, ...
    'test_appelo_mass_conserving_state:FiniteAlRoot', ...
    'The reduced Appelo solver must recover the finite-Al physical root.');

[Al_sat,solid_sat,res_sat] = ERW_Al_Equilibrium_Target(1,1e-4,2.0e6, ...
    soil_water_l,CEC_tot,1000,K_AlOH3,K1,K2,K3,K4);
assert(Al_sat >= 0 && solid_sat >= 0 && abs(res_sat) < 1e-8*2.0e6, ...
    'test_appelo_mass_conserving_state:AlSaturated', ...
    'Saturated Al must close aqueous, exchange and secondary-solid inventory.');
[Al_limited,solid_limited,res_limited] = ERW_Al_Equilibrium_Target(1,0,1.0e3, ...
    soil_water_l,CEC_tot,1000,K_AlOH3,K1,K2,K3,K4);
assert(Al_limited >= 0 && solid_limited < 1e-12*1.0e3 && ...
    abs(res_limited) < 1e-8*1.0e3, ...
    'test_appelo_mass_conserving_state:AlLimited', ...
    'Inventory-limited Al must conserve inventory without creating solid.');

erw_source = fileread(fullfile(fileparts(here),'ERW_function.m'));
assert(contains(erw_source, ...
    'ERW_Al_Equilibrium_Target(sol(3),sol(11),Al_tot'), ...
    'test_appelo_mass_conserving_state:AlFractionIndex', ...
    'The retained Al solid must use f_Al at sol(11), not f_Ca at sol(16).');

fprintf('  PASS  coupled Appelo roots close mass, sites, charge and DIC\n');
end
