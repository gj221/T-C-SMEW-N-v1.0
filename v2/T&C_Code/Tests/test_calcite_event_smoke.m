function test_calcite_event_smoke
%%% Three-day one-column smoke spanning the first calcite application.

v2 = fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(fullfile(v2,'run'),fullfile(v2,'T&C_Code'));
result_dir = tempname;
mkdir(result_dir);
cleanup_dir = onCleanup(@() rmdir(result_dir,'s'));
old_ckpt = getenv('TC_CKPT_MINUTES');
setenv('TC_CKPT_MINUTES','0');
cleanup_env = onCleanup(@() setenv('TC_CKPT_MINUTES',old_ckpt));

result_file = Run_One_Subfield(12,'StartDate','2016-11-09', ...
    'NDays',3,'SaveResults',true,'ResultDirectory',result_dir);
S = load(result_file,'ERW','Date','R','P');
B = S.ERW{1}.bg;
row = S.ERW{1}.dm_end;

alpha_CaCO3 = 5e-10; % mol dm^-3 soil s^-1, Kirk et al. (2015)
r_CaCO3_expected = alpha_CaCO3*1e3*24*3600*S.ERW{1}.const.conv_mol;
assert(abs(S.ERW{1}.const.r_CaCO3-r_CaCO3_expected) <= ...
    1e-12*r_CaCO3_expected, ...
    'Calcite precipitation coefficient does not match the cited soil-volume rate.');
assert(S.ERW{1}.const.r_MgCO3 == S.ERW{1}.const.r_CaCO3, ...
    'Nesquehonite precipitation must use the cited soil-volume carbonate rate.');
assert(S.R.id == 12 && S.Date(1) == datenum(2016,11,9), ...
    'Event smoke did not use the requested calcite window.');
application_row = ERW_Application_Indices(1,1/144,3*144);
assert(application_row == 145 && ...
    all(S.ERW{1}.TC_const.M_rock_add(1:application_row-1) == 0) && ...
    S.ERW{1}.TC_const.M_rock_add(application_row) == 5000, ...
    'Calcite was not placed at the 10 November midnight state boundary.');
assert(all(S.ERW{1}.bg.M_min(1:application_row-1,:) == 0,'all') && ...
    any(S.ERW{1}.bg.M_min(application_row,:) > 0), ...
    'Primary calcite changed before the application boundary or failed to enter it.');
assert(any(B.M_min(:) > 0), ...
    'Calcite application did not enter the primary mineral pool.');
assert(size(B.M_min,2) == 1 && numel(S.ERW{1}.const.MM_min) == 1, ...
    'The event mass ledger expects one primary calcite mineral.');
primary = B.M_min(:,1);
applied = S.ERW{1}.TC_const.M_rock_add(:);
dissolved = S.ERW{1}.weath.EW(:,1)*S.ERW{1}.const.MM_min(1)/144;
mass_error = primary(2:row)-primary(1:row-1)-applied(2:row)+dissolved(1:row-1);
assert(max(abs(mass_error)) <= 1e-8*max(1,max(primary)), ...
    'Primary calcite mass does not close across the application event.');
assert(all(isfinite(B.M_min(:))) && all(B.M_min(:) >= 0) && ...
    all(isfinite(B.CaCO3(:))) && all(B.CaCO3(:) >= 0), ...
    'Primary or secondary calcite inventory is unphysical.');
assert(isfield(B,'dAlk_sil') && isfield(B,'dAlk_carb'), ...
    'Alkalinity source diagnostics are absent from the saved calcite run.');
fprintf('  dissolved P %.5g, TAN %.5g umol/L; Al charge %.5g umolc/L; dAlk_sil %.5g, dAlk_carb %.5g umolc/m2\n', ...
    B.PO4(row),B.NH4(row), ...
    (3*B.Al(row)+2*B.AlOH(row)+B.AlOH2(row)-B.AlOH4(row))/S.ERW{1}.const.Al_CEC_scale, ...
    B.dAlk_sil(row),B.dAlk_carb(row));
fprintf('  Ca %.5g, DIC %.5g umol/L; soil pCO2 %.5g atm\n', ...
    B.Ca(row),B.DIC(row),B.CO2_air(row)*22.41/S.ERW{1}.const.conv_mol);
assert(abs(B.dAlk_sil(row)) <= 1e-8 && B.dAlk_carb(row) > 0, ...
    'Primary calcite alkalinity is assigned to silicate weathering.');
%%% Saturation on the basis the solver itself uses: Ca and CO3 are
%%% concentrations speciated with constants conditioned at activity_I, so
%%% the ion activity product carries gamma_div^2 at that ionic strength,
%%% which must also agree with the solved state's own ionic strength.
ionic_str = ERW_Ionic_Strength(B.Ca(row),B.Mg(row),B.Na(row),B.K(row), ...
    B.Al(row)/S.ERW{1}.const.Al_CEC_scale,B.H(row),B.NH4(row),B.NO3(row), ...
    B.HCO3(row),B.CO3(row),B.An(row),S.ERW{1}.const.conv_mol, ...
    B.PO4(row),B.AlOH(row)/S.ERW{1}.const.Al_CEC_scale, ...
    B.AlOH2(row)/S.ERW{1}.const.Al_CEC_scale, ...
    B.AlOH4(row)/S.ERW{1}.const.Al_CEC_scale,B.k_w(row)/B.H(row));
assert(abs(ionic_str-B.ionic_str(row)) <= 1e-12*max(ionic_str,1) && ...
    abs(B.ionic_str(row)-B.activity_I(row)) <= 1e-2*max(B.ionic_str(row),1e-4), ...
    'The recorded ionic strength must match the state and close on activity_I.');
Omega_CaCO3 = B.Omega_CaCO3(row);
assert(isfinite(Omega_CaCO3) && Omega_CaCO3 >= 0, ...
    'Calcite saturation state is unphysical.');
W_CaCO3 = S.ERW{1}.weath.W_CaCO3(row);
assert(isfinite(W_CaCO3) && (abs(W_CaCO3) < 1e-12 || ...
    sign(W_CaCO3) == sign(1-Omega_CaCO3)), ...
    'Secondary calcite flux points away from saturation.');
if Omega_CaCO3 > 1+1e-12
    assert(B.CaCO3(row) > B.CaCO3(1), ...
        'Supersaturated field water did not accumulate secondary calcite.');
end
assert(isfinite(B.pH(row)) && B.pH(row) > 0 && B.pH(row) < 14 && ...
    isfinite(B.pH_bulk(row)) && B.pH_bulk(row) > 0 && B.pH_bulk(row) < 9, ...
    'Pore-water or bulk-extract pH is unphysical.');
aq_charge = B.H(row)+2*B.Ca(row)+2*B.Mg(row)+B.Na(row)+B.K(row)+B.NH4(row)+ ...
    (3*B.Al(row)+2*B.AlOH(row)+B.AlOH2(row)-B.AlOH4(row))/S.ERW{1}.const.Al_CEC_scale- ...
    (B.k_w(row)/B.H(row)+B.HCO3(row)+2*B.CO3(row)+B.NO3(row)+B.PO4(row)+B.An(row));
assert(abs(aq_charge) <= 1e-8*max(1,B.An(row)) && ...
    abs(B.charge_residual(row)-aq_charge) <= 1e-10*max(1,B.An(row)), ...
    'Calcite event aqueous charge does not close.');
N_pools = S.P(:,23:34,:);
assert(all(isfinite(N_pools(:))) && all(N_pools(:) >= 0), ...
    'Event-window nitrogen pools are unphysical.');

clear cleanup_env cleanup_dir
fprintf('  pH pore %.4f, bulk %.4f, Omega %.4g, W_secondary %.4g umol/m2/d, primary %.4g g/m2, secondary %.4g umol/m2\n', ...
    B.pH(row),B.pH_bulk(row),Omega_CaCO3,W_CaCO3,sum(B.M_min(row,:)),B.CaCO3(row));
fprintf('PASS: calcite event smoke has finite pH and nonnegative primary/secondary solids.\n');
end
