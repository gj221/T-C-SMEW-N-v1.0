function test_pH_conversion
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Bulk-extract pH pipeline in v2 (port of the Model TC_Code machinery).
%%
%% Initialization explicitly chooses a prescribed field state or inversion
%% of an observed air-dried 1:n extract pH.  The solved pore-water state is
%% converted back to the bulk extract pH every day
%% (Porewater_to_Bulk_pH in ERW_Daily_Step_2D and MAIN_FRAME_BG_ERW_10mins).
%% Daily and extract solvers share ONE exchange scheme selected by
%% bulk_pH_params.scheme: 'appelo' (SCEPTER/Appelo H-referenced, default)
%% or 'TC_GT' (Gaines-Thomas, Model constants).
%% (SCEPTER/Appelo H-referenced selectivity).
%%
%% Aqueous reactions use pore-water pH.  Biological response functions use
%% the laboratory bulk-extract pH, retained separately for comparison with
%% measured soil pH.  The production extract is 1:2.5 DI water, open to
%% the laboratory air, in which the plot's solid carbonates dissolve.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

fprintf('\n=== test_pH_conversion ===\n');
n_pass = 0;

v2 = fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(v2, fullfile(v2, 'T&C_Code'));

conv_mol = 1e6;
Al_CEC_scale = 1e3;
k1 = 0.447;
k2 = 4.68e-5;
k_w = 1e-2;
k_nh3 = 5.623413e-4;
k_H = 0.83;
K1_Al = 10; K2_Al = 8; K3_Al = 0.2; K4_Al = 0.631;

%% ---- TC_GT forward/inverse round trip on a prescribed exchange state
f_CEC = [0.647 0.129 0.043 0 0 0.181];
K_CEC = [10^0.1, 10^(-2)*conv_mol, 10^0.38*conv_mol, ...
    10^(-0.86)/conv_mol, 10^(-5.4)*conv_mol];
H_expected = 10^(-5.2) * conv_mol;
Ca = (f_CEC(1)/K_CEC(5)) * (H_expected/f_CEC(6))^2;
Mg = (Ca/f_CEC(1)) * K_CEC(1) * f_CEC(2);
K  = sqrt((Ca/f_CEC(1)) * K_CEC(2)) * f_CEC(3);
Na = 0;
CO2_air = 400/22.41;
CO2_w = 10 * k_H * CO2_air;
[An, ~] = ERW_Residual_An_From_Charge( ...
    H_expected, CO2_w, Ca, Mg, Na, K, 0, 0, 0, 0, ...
    k1, k2, k_w, k_nh3, K1_Al, K2_Al, K3_Al, K4_Al, Al_CEC_scale);
check(An >= 0, 'residual anion from charge closure is non-negative');

CEC_tot = 25 * 1e-5 * 1.15e6 * 0.2 * conv_mol;
bpp = struct('n_extract', 2, 'K_CEC', K_CEC, ...
    'H_extract_anchor_umolL', H_expected, ...
    'H_pore_anchor_umolL', H_expected, ...
    'H_prev', NaN, 'H_prev_valid', false, 'initial_f_CEC', f_CEC, ...
    'field_water_L_m2', 25, ...
    'DIC_field_umol_L', CO2_w*(1+k1/H_expected+k1*k2/H_expected^2));
[pH_bulk,diag_bulk] = Porewater_to_Bulk_pH( ...
    H_expected, Ca, Mg, K, Na, 0, 0, An, 0, 0, 0, CO2_air, ...
    k1, k2, k_w, k_nh3, k_H, K1_Al, K2_Al, K3_Al, K4_Al, ...
    f_CEC(1), f_CEC(2), f_CEC(3), f_CEC(4), f_CEC(5), f_CEC(6), ...
    CEC_tot, 1.15e6, 0.2, conv_mol, bpp, Al_CEC_scale);
check(isfinite(pH_bulk), 'TC_GT forward extraction returns a finite bulk pH');
%% The paste stands open to the laboratory air: its dissolved CO2 is the
%% air's at 25 C, whatever the field pore water carried in, and the carbon
%% it gives up or takes is reported, not conserved.
check(diag_bulk.CO2_ext == k_H*CO2_air, ...
    'the paste holds the dissolved CO2 of the laboratory air');
bpp_dic = bpp;
bpp_dic.DIC_field_umol_L = 2*bpp.DIC_field_umol_L;
[pH_bulk_dic,diag_dic] = Porewater_to_Bulk_pH( ...
    H_expected, Ca, Mg, K, Na, 0, 0, An, 0, 0, 0, CO2_air, ...
    k1, k2, k_w, k_nh3, k_H, K1_Al, K2_Al, K3_Al, K4_Al, ...
    f_CEC(1), f_CEC(2), f_CEC(3), f_CEC(4), f_CEC(5), f_CEC(6), ...
    CEC_tot, 1.15e6, 0.2, conv_mol, bpp_dic, Al_CEC_scale);
check(pH_bulk_dic == pH_bulk && ...
    abs(diag_bulk.CO2_air_exchange_umol_L-diag_dic.CO2_air_exchange_umol_L- ...
    bpp.DIC_field_umol_L*diag_bulk.dilution_factor) < ...
    1e-9*bpp.DIC_field_umol_L, ...
    'the field DIC does not set the reading of an open paste, only the carbon it gives up');
pH_bulk_air = Porewater_to_Bulk_pH( ...
    H_expected, Ca, Mg, K, Na, 0, 0, An, 0, 0, 0, 2*CO2_air, ...
    k1, k2, k_w, k_nh3, k_H, K1_Al, K2_Al, K3_Al, K4_Al, ...
    f_CEC(1), f_CEC(2), f_CEC(3), f_CEC(4), f_CEC(5), f_CEC(6), ...
    CEC_tot, 1.15e6, 0.2, conv_mol, bpp, Al_CEC_scale);
check(pH_bulk_air < pH_bulk && pH_bulk-pH_bulk_air < 0.1, ...
    'more CO2 in the laboratory air lowers an acid paste''s reading, slightly');
assert_error(@() Porewater_to_Bulk_pH( ...
    H_expected, Ca, Mg, K, Na, 0, 0, An, 0, 0, 0, [CO2_air CO2_air], ...
    k1, k2, k_w, k_nh3, k_H, K1_Al, K2_Al, K3_Al, K4_Al, ...
    f_CEC(1), f_CEC(2), f_CEC(3), f_CEC(4), f_CEC(5), f_CEC(6), ...
    CEC_tot, 1.15e6, 0.2, conv_mol, bpp, Al_CEC_scale), 'ERW:invalidParam');
n_pass = n_pass + 1;
bpp_var = bpp;
bpp_var.CEC_cmolc_kg = 25;
bpp_var.dCEC_dpH = 6;
bpp_var.CEC_ref_pH = 5.2;
[pH_bulk_var,diag_bulk_var] = Porewater_to_Bulk_pH( ...
    H_expected, Ca, Mg, K, Na, 0, 0, An, 0, 0, 0, CO2_air, ...
    k1, k2, k_w, k_nh3, k_H, K1_Al, K2_Al, K3_Al, K4_Al, ...
    f_CEC(1), f_CEC(2), f_CEC(3), f_CEC(4), f_CEC(5), f_CEC(6), ...
    CEC_tot, 1.15e6, 0.2, conv_mol, bpp_var, Al_CEC_scale);
check(isfinite(pH_bulk_var) && ...
    abs(diag_bulk_var.CEC_field-CEC_tot) <= eps(CEC_tot), ...
    'TC_GT variable CEC preserves the prescribed field capacity at its anchor');
check(abs(diag_bulk_var.CEC_extract-diag_bulk_var.CEC_field) > 1e-6*CEC_tot, ...
    'TC_GT extraction evaluates CEC at the solved extract pH');
check(max(abs(diag_bulk_var.exchange_mass_residuals_umol_L)) < 1e-6, ...
    'TC_GT variable-CEC extraction conserves every cation inventory');
bpp_offset = bpp;
bpp_offset.pH_offset = 0.25;
assert_error(@() Porewater_to_Bulk_pH( ...
    H_expected, Ca, Mg, K, Na, 0, 0, An, 0, 0, 0, CO2_air, ...
    k1, k2, k_w, k_nh3, k_H, K1_Al, K2_Al, K3_Al, K4_Al, ...
    f_CEC(1), f_CEC(2), f_CEC(3), f_CEC(4), f_CEC(5), f_CEC(6), ...
    CEC_tot, 1.15e6, 0.2, conv_mol, bpp_offset, Al_CEC_scale), ...
    'ERW:bulkPHOffsetNotPhysical');
bad_f_CEC = 2*f_CEC;
assert_error(@() Porewater_to_Bulk_pH( ...
    H_expected, Ca, Mg, K, Na, 0, 0, An, 0, 0, 0, CO2_air, ...
    k1, k2, k_w, k_nh3, k_H, K1_Al, K2_Al, K3_Al, K4_Al, ...
    bad_f_CEC(1), bad_f_CEC(2), bad_f_CEC(3), bad_f_CEC(4), ...
    bad_f_CEC(5), bad_f_CEC(6), CEC_tot, 1.15e6, 0.2, conv_mol, ...
    bpp, Al_CEC_scale), 'ERW:invalidExchangeFractions');
bpp_bad_f = bpp;
bpp_bad_f.initial_f_CEC = bad_f_CEC;
assert_error(@() Invert_Bulk_pH( ...
    pH_bulk, Ca, Mg, K, Na, 0, 0, 0, CO2_air, CO2_w, ...
    k1, k2, k_w, k_nh3, k_H, K1_Al, K2_Al, K3_Al, K4_Al, ...
    CEC_tot, 1.15e6, 0.2, conv_mol, bpp_bad_f, 9.66, Al_CEC_scale), ...
    'ERW:invertBulkPH');
n_pass = n_pass + 1;
bpp_track = bpp;
bpp_track.H_prev = diag_bulk.H;
bpp_track.H_prev_valid = true;
[pH_bulk_track,diag_track] = Porewater_to_Bulk_pH( ...
    H_expected, Ca, Mg, K, Na, 0, 0, An, 0, 0, 0, CO2_air, ...
    k1, k2, k_w, k_nh3, k_H, K1_Al, K2_Al, K3_Al, K4_Al, ...
    f_CEC(1), f_CEC(2), f_CEC(3), f_CEC(4), f_CEC(5), f_CEC(6), ...
    CEC_tot, 1.15e6, 0.2, conv_mol, bpp_track, Al_CEC_scale);
check(diag_track.converged && abs(pH_bulk_track-pH_bulk) < 1e-10, ...
    'previous extract H selects and converges the continuous root');
check(abs(diag_track.anchor_pH+log10(diag_bulk.H/conv_mol)) < 1e-12, ...
    'root scan anchor is the previous converged extract H');

[H, ~, f_Ca, f_Mg, f_K, f_Na, f_Al, f_H, An_eq, ~, Ca_eq, Mg_eq, K_eq, Na_eq] = ...
    Invert_Bulk_pH(pH_bulk, Ca, Mg, K, Na, 0, 0, 0, CO2_air, CO2_w, ...
    k1, k2, k_w, k_nh3, k_H, K1_Al, K2_Al, K3_Al, K4_Al, ...
    CEC_tot, 1.15e6, 0.2, conv_mol, bpp, 9.66, Al_CEC_scale);
check(abs(-log10(H/conv_mol) - 5.2) < 2e-3, ...
    'TC_GT inverse recovers the pore pH to +/-0.002');
check(norm([f_Ca f_Mg f_K f_Na f_Al f_H] - f_CEC, inf) < 2e-5, ...
    'TC_GT inverse reproduces the prescribed exchange fractions');
check(norm([Ca_eq Mg_eq K_eq Na_eq] - [Ca Mg K Na], inf) < ...
    1e-2*max(norm([Ca Mg K Na], inf), 1) + 1e-9, ...
    'TC_GT inverse leaves the dissolved cation inventory unchanged');
check(An_eq >= 0, 'TC_GT inverse returns a non-negative residual anion');

%% ---- appelo forward/inverse round trip on the same state
[f_Ca_a, f_Mg_a, f_K_a, f_Na_a, f_Al_a, f_H_a] = Exchange_Fractions_GT( ...
    H_expected, Ca, Mg, K, Na, 0, K_CEC, ...
    K1_Al, K2_Al, K3_Al, K4_Al, Al_CEC_scale, 'appelo');
check(abs(sum([f_Ca_a f_Mg_a f_K_a f_Na_a f_Al_a f_H_a]) - 1) < 1e-10, ...
    'appelo exchange fractions sum to unity');
bpp_app = bpp;
bpp_app.scheme = 'appelo';
pH_bulk_app = Porewater_to_Bulk_pH( ...
    H_expected, Ca, Mg, K, Na, 0, 0, An, 0, 0, 0, CO2_air, ...
    k1, k2, k_w, k_nh3, k_H, K1_Al, K2_Al, K3_Al, K4_Al, ...
    f_Ca_a, f_Mg_a, f_K_a, f_Na_a, f_Al_a, f_H_a, ...
    CEC_tot, 1.15e6, 0.2, conv_mol, bpp_app, Al_CEC_scale);
check(isfinite(pH_bulk_app), ...
    'appelo forward extraction returns a finite bulk pH');
bpp_app_var = bpp_app;
bpp_app_var.CEC_cmolc_kg = 25;
bpp_app_var.dCEC_dpH = 6;
bpp_app_var.CEC_ref_pH = 5.2;
assert_error(@() Porewater_to_Bulk_pH( ...
    H_expected, Ca, Mg, K, Na, 0, 0, An, 0, 0, 0, CO2_air, ...
    k1, k2, k_w, k_nh3, k_H, K1_Al, K2_Al, K3_Al, K4_Al, ...
    f_Ca_a, f_Mg_a, f_K_a, f_Na_a, f_Al_a, f_H_a, ...
    CEC_tot, 1.15e6, 0.2, conv_mol, bpp_app_var, Al_CEC_scale), ...
    'ERW:scepterFixedCEC');
assert_error(@() Invert_Bulk_pH( ...
    pH_bulk_app, Ca, Mg, K, Na, 0, 0, 0, CO2_air, CO2_w, ...
    k1, k2, k_w, k_nh3, k_H, K1_Al, K2_Al, K3_Al, K4_Al, ...
    CEC_tot, 1.15e6, 0.2, conv_mol, bpp_app_var, 9.66, Al_CEC_scale), ...
    'ERW:scepterFixedCEC');
n_pass = n_pass + 2;

%% The inverse repartitions the dissolved and exchangeable inventories at
%% every trial H, so the state returned by the inversion is the fixed
%% point of ITS operator.  The invariant to hold is therefore that the
%% inverse's own outputs forward-extract back to the observed bulk pH
%% (the semantic guarantee the daily driver relies on), plus a loose
%% anchor proximity on the pore pH (H_pore_anchor_umolL = 5.2 here).
[H_app, bpp_app_r, f_Ca_r, f_Mg_r, f_K_r, f_Na_r, f_Al_r, f_H_r, An_app, ...
    Al_w_app, Ca_eq, Mg_eq, K_eq, Na_eq] = Invert_Bulk_pH( ...
    pH_bulk_app, Ca, Mg, K, Na, 0, 0, 0, CO2_air, CO2_w, ...
    k1, k2, k_w, k_nh3, k_H, K1_Al, K2_Al, K3_Al, K4_Al, ...
    CEC_tot, 1.15e6, 0.2, conv_mol, bpp_app, 9.66, Al_CEC_scale);
check(abs(-log10(H_app/conv_mol) - 5.2) < 0.1, ...
    'appelo inverse stays within 0.1 of the pore pH anchor');
check(An_app >= 0, 'appelo inverse returns a non-negative residual anion');
pH_bulk_rt = Porewater_to_Bulk_pH( ...
    H_app, Ca_eq, Mg_eq, K_eq, Na_eq, Al_w_app, 0, An_app, 0, 0, 0, CO2_air, ...
    k1, k2, k_w, k_nh3, k_H, K1_Al, K2_Al, K3_Al, K4_Al, ...
    f_Ca_r, f_Mg_r, f_K_r, f_Na_r, f_Al_r, f_H_r, ...
    CEC_tot, 1.15e6, 0.2, conv_mol, bpp_app_r, Al_CEC_scale);
check(abs(pH_bulk_rt - pH_bulk_app) < 1e-8, ...
    'appelo inverse outputs forward-extract back to the observed bulk pH');

%% ---- field calcite dissolves in the open bulk extract.  This sample is
%% acid (18 % of its sites hold H), so at the paste's pH the Gaines-Thomas
%% exchanger has no partition until calcite has dissolved; the extent
%% solve treats that as a slurry short of Ca.
bpp_calcite = bpp;
bpp_calcite.solid_CaCO3_umol_m2 = 5e7;
bpp_calcite.K_CaCO3 = 10^(-8.35)*conv_mol^2;
[pH_bulk_calcite, calcite_diag] = Porewater_to_Bulk_pH( ...
    H_expected, Ca, Mg, K, Na, 0, 0, An, 0, 0, 0, CO2_air, ...
    k1, k2, k_w, k_nh3, k_H, K1_Al, K2_Al, K3_Al, K4_Al, ...
    f_CEC(1), f_CEC(2), f_CEC(3), f_CEC(4), f_CEC(5), f_CEC(6), ...
    CEC_tot, 1.15e6, 0.2, conv_mol, bpp_calcite, Al_CEC_scale);
check(isfinite(pH_bulk_calcite), ...
    'solid-bearing field state returns a finite bulk pH');
bulk_source = fileread(fullfile(v2,'T&C_Code','Porewater_to_Bulk_pH.m'));
check(contains(bulk_source,'ERW:nonUniqueBulkRoot'), ...
    'bulk extraction rejects a non-unique cold physical root');
check(contains(bulk_source,'bisect_converged') && ...
    contains(bulk_source,'ERW:bulkPHSolverNoConvergence'), ...
    'bisection exhaustion cannot be labelled converged');
check(pH_bulk_calcite > pH_bulk + 0.2, ...
    'field calcite dissolving in the paste raises its pH above the solid-free extract');
check(calcite_diag.calcite_equilibrium_active && ...
    abs(calcite_diag.Omega_CaCO3-1) < 1e-6, ...
    'an excess of field calcite leaves the paste at calcite saturation');
check(calcite_diag.calcite_input_umol_m2 == 5e7 && ...
    calcite_diag.calcite_remaining_umol_m2 > 0 && ...
    calcite_diag.calcite_remaining_umol_m2 < 5e7 && ...
    calcite_diag.calcite_Ca_residual_umol_m2 == 0, ...
    'only part of an excess calcite inventory dissolves in the paste');
calcite_dissolved_umol_L = (calcite_diag.calcite_input_umol_m2- ...
    calcite_diag.calcite_remaining_umol_m2)/calcite_diag.extract_water_L_m2;
check(calcite_diag.CO2_ext == k_H*CO2_air && ...
    abs(calcite_diag.CO2_air_exchange_umol_L-(calcite_diag.DIC- ...
    bpp.DIC_field_umol_L*25/(bpp.n_extract*1.15e3*0.2)- ...
    calcite_dissolved_umol_L)) < 1e-8*max(1,calcite_dissolved_umol_L) && ...
    calcite_diag.CO2_air_exchange_umol_L < 0, ...
    'the calcite paste holds the air''s CO2 and gives up the carbon its exchange acidity released');
check(abs(calcite_diag.Ca+calcite_diag.cec_factor*calcite_diag.f_Ca/2- ...
    (Ca*calcite_diag.dilution_factor+calcite_diag.cec_inventory_factor*f_CEC(1)/2+ ...
    calcite_dissolved_umol_L)) < 1e-8*(calcite_diag.cec_inventory_factor+Ca), ...
    'the Ca dissolved from calcite joins the conserved Ca inventory');
check(pH_bulk_calcite > 7.9 && pH_bulk_calcite < 8.5 && calcite_diag.n_brackets == 1, ...
    'an excess of calcite reads the calcite-air equilibrium of the paste, on its one root');
pH_bulk_calcite_air = Porewater_to_Bulk_pH( ...
    H_expected, Ca, Mg, K, Na, 0, 0, An, 0, 0, 0, 2*CO2_air, ...
    k1, k2, k_w, k_nh3, k_H, K1_Al, K2_Al, K3_Al, K4_Al, ...
    f_CEC(1), f_CEC(2), f_CEC(3), f_CEC(4), f_CEC(5), f_CEC(6), ...
    CEC_tot, 1.15e6, 0.2, conv_mol, bpp_calcite, Al_CEC_scale);
check(abs(pH_bulk_calcite-pH_bulk_calcite_air-(2/3)*log10(2)) < 0.02, ...
    'doubling the air''s CO2 lowers a calcite paste by two thirds of log10(2)');
bpp_calcite_app = bpp_app;
bpp_calcite_app.solid_CaCO3_umol_m2 = 5e7;
[pH_bulk_calcite_app, calcite_app_diag] = Porewater_to_Bulk_pH( ...
    H_expected, Ca, Mg, K, Na, 0, 0, An, 0, 0, 0, CO2_air, ...
    k1, k2, k_w, k_nh3, k_H, K1_Al, K2_Al, K3_Al, K4_Al, ...
    f_Ca_a, f_Mg_a, f_K_a, f_Na_a, f_Al_a, f_H_a, ...
    CEC_tot, 1.15e6, 0.2, conv_mol, bpp_calcite_app, Al_CEC_scale);
check(pH_bulk_calcite_app > 7.9 && pH_bulk_calcite_app < 8.5 && ...
    calcite_app_diag.calcite_equilibrium_active && ...
    abs(calcite_app_diag.Omega_CaCO3-1) < 1e-6 && ...
    calcite_app_diag.calcite_remaining_umol_m2 > 0 && calcite_app_diag.n_brackets == 1, ...
    'the production exchange scheme reads the same calcite-air equilibrium');
bpp_trace = bpp;
bpp_trace.solid_CaCO3_umol_m2 = 1e3;
[pH_bulk_trace, trace_diag] = Porewater_to_Bulk_pH( ...
    H_expected, Ca, Mg, K, Na, 0, 0, An, 0, 0, 0, CO2_air, ...
    k1, k2, k_w, k_nh3, k_H, K1_Al, K2_Al, K3_Al, K4_Al, ...
    f_CEC(1), f_CEC(2), f_CEC(3), f_CEC(4), f_CEC(5), f_CEC(6), ...
    CEC_tot, 1.15e6, 0.2, conv_mol, bpp_trace, Al_CEC_scale);
check(~trace_diag.calcite_equilibrium_active && ...
    trace_diag.calcite_remaining_umol_m2 == 0 && ...
    trace_diag.Omega_CaCO3 < 1 && abs(pH_bulk_trace-pH_bulk) < 0.05, ...
    'a trace of field calcite dissolves completely, leaves the paste undersaturated and barely moves its pH');
bpp_none = bpp;
bpp_none.solid_CaCO3_umol_m2 = 0;
[pH_bulk_none, none_diag] = Porewater_to_Bulk_pH( ...
    H_expected, Ca, Mg, K, Na, 0, 0, An, 0, 0, 0, CO2_air, ...
    k1, k2, k_w, k_nh3, k_H, K1_Al, K2_Al, K3_Al, K4_Al, ...
    f_CEC(1), f_CEC(2), f_CEC(3), f_CEC(4), f_CEC(5), f_CEC(6), ...
    CEC_tot, 1.15e6, 0.2, conv_mol, bpp_none, Al_CEC_scale);
check(pH_bulk_none == pH_bulk && ~none_diag.calcite_equilibrium_active && ...
    none_diag.calcite_remaining_umol_m2 == 0, ...
    'without solid calcite the paste operator is the solid-free one bit for bit');

%% ---- field Mg carbonate (nesquehonite) dissolves in the open bulk extract
bpp_calcite_no_mg = bpp_calcite;
bpp_calcite_no_mg.solid_MgCO3_umol_m2 = 0;
[pH_bulk_calcite_no_mg, calcite_no_mg_diag] = Porewater_to_Bulk_pH( ...
    H_expected, Ca, Mg, K, Na, 0, 0, An, 0, 0, 0, CO2_air, ...
    k1, k2, k_w, k_nh3, k_H, K1_Al, K2_Al, K3_Al, K4_Al, ...
    f_CEC(1), f_CEC(2), f_CEC(3), f_CEC(4), f_CEC(5), f_CEC(6), ...
    CEC_tot, 1.15e6, 0.2, conv_mol, bpp_calcite_no_mg, Al_CEC_scale);
check(pH_bulk_calcite_no_mg == pH_bulk_calcite && ...
    ~calcite_no_mg_diag.nesquehonite_equilibrium_active && ...
    calcite_no_mg_diag.nesquehonite_remaining_umol_m2 == 0 && ...
    calcite_no_mg_diag.nesquehonite_dissolved_umol_m2 == 0, ...
    'without solid Mg carbonate the paste operator is the calcite one bit for bit');
bpp_mg_trace = bpp;
bpp_mg_trace.solid_MgCO3_umol_m2 = 1e3;
[pH_bulk_mg_trace, mg_trace_diag] = Porewater_to_Bulk_pH( ...
    H_expected, Ca, Mg, K, Na, 0, 0, An, 0, 0, 0, CO2_air, ...
    k1, k2, k_w, k_nh3, k_H, K1_Al, K2_Al, K3_Al, K4_Al, ...
