function test_erw_appelo_exchange_floor
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Replay the Appelo exchange step that ERW_function refused when the
%% exchangeable Al fraction fell below the log-residual floor.
%%
%% Kantola control, margin_prairie layout, prairie column, step 22053
%% (day 153).  Pore water is strongly alkaline (pH 11.0), the Al(OH)3
%% inventory is dissolved as Al(OH)4-, free Al3+ is inventory-limited and
%% the Appelo selectivity product predicts f_Al = 9.52e-25, below the
%% fl_app = 1e-24 floor of the log-space exchange relations.  With the
%% floor applied to the left side only, the f_Al residual could not fall
%% below ln(1e-24/9.52e-25) = 0.049 (scaled 5.1e-3 > 1e-3) and the step
%% was refused at the exact mass-conserving root.  Both sides now share
%% the floor: a fraction at or below fl_app satisfies a prediction at or
%% below fl_app, and above the floor the residual is unchanged.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

fprintf('\n=== test_erw_appelo_exchange_floor ===\n');
here = fileparts(mfilename('fullpath'));
code_dir = fileparts(here);
addpath(code_dir,fullfile(code_dir,'Inputs'),fullfile(code_dir,'Parameters'));

%% Source guard: the right side of every Appelo relation, in the residual
%% system and in its row scale, is clipped at log(fl_app).
erw_source = fileread(fullfile(code_dir,'ERW_function.m'));
assert(count(erw_source,'log_fl_app = log(fl_app);') == 2, ...
    'test_erw_appelo_exchange_floor:Source', ...
    'ERW_function must define log_fl_app next to fl_app in the residual system and in the Appelo row scale.');
assert(count(erw_source,',log_fl_app); ...') == 5, ...
    'test_erw_appelo_exchange_floor:Source', ...
    'All five Appelo exchange relations must clip the selectivity product at log(fl_app).');
assert(count(erw_source,', log_fl_app))') == 5, ...
    'test_erw_appelo_exchange_floor:Source', ...
    'All five Appelo row scales must clip the selectivity product at log(fl_app).');

%% Rebuild the refused call from the fixture.
F = load(fullfile(here,'Fixtures','erw_appelo_al_floor_step22053.mat'),'fixture');
F = F.fixture;
header_start = regexp(erw_source,'ERW_function\(','end','once') + 1;
header_end = regexp(erw_source,'\)\r?\n\r?\n%%%% INPUT','start','once') - 1;
arg_names = strtrim(strsplit(regexprep( ...
    erw_source(header_start:header_end),'\.\.\.',''),','));
assert(numel(arg_names) == nargin('ERW_function'), ...
    'test_erw_appelo_exchange_floor:Signature', ...
    'The ERW_function signature could not be parsed.');
args = cell(1,numel(arg_names));
for k = 1:numel(arg_names)
    if strcmp(arg_names{k},'~')
        args{k} = [];
        continue
    end
    assert(isfield(F.inputs,arg_names{k}), ...
        'test_erw_appelo_exchange_floor:Fixture', ...
        'The fixture carries no value for ERW input %s.',arg_names{k});
    args{k} = F.inputs.(arg_names{k});
end
assert(F.inputs.time_step == 22053 && strcmp(F.refused.dominant,'f_Al') && ...
    F.refused.max_scaled_res > F.constants.res_threshold && ...
    F.refused.f_Al < F.constants.fl_app, ...
    'test_erw_appelo_exchange_floor:Fixture', ...
    'The fixture is not the refused step 22053 with f_Al below the floor.');

warn_state = warning('off','ERW:NoConverge');
cleanup = onCleanup(@() warning(warn_state));
% A small anion decrease keeps the Al fraction below the floor after
% full-charge closure.  On the conditional-constant basis the Al(OH)3 pin
% admits about four times more free Al3+ at I = 0.086 (*Kso*g1^3/g3), so the
% decrease is 2 % rather than 0.1 %; the replay then sits at activity pH 11.29.
args{strcmp(arg_names,'An_tot')} = F.inputs.An_tot*0.98;
[ERW_data,~,~,~,~,ERW_var] = ERW_function(args{:});

%% The accepted state closes the revised full-charge balance.
sol = ERW_data.sol;
K = F.constants.appelo_K; alpha = F.constants.appelo_alpha;
scale = F.constants.Al_CEC_scale; fl = F.constants.fl_app;
assert(ERW_var.max_scaled_res <= F.constants.res_threshold && ~ERW_var.no_converge, ...
    'test_erw_appelo_exchange_floor:Residual', ...
    'The replayed step is still refused: max scaled residual %.3g (%s).', ...
    ERW_var.max_scaled_res,ERW_var.dominant_residual_name);
assert(ERW_data.pH > 10.5 && ERW_data.pH < 11.5, ...
    'test_erw_appelo_exchange_floor:Regime', ...
    'The fixture no longer reproduces the alkaline regime (pH %.3f).',ERW_data.pH);

%% Exchange relations hold in their unfloored form for every cation; the
%% Al prediction and the Al fraction are both below the floor.
rho = sol(15)/sol(3);
f_Al_pred = K(1)*(sol(6)/scale)*rho^3*10^(3*alpha*sol(15));
assert(f_Al_pred < fl && sol(11) <= fl, ...
    'test_erw_appelo_exchange_floor:AlFloor', ...
    'Expected f_Al and its prediction below %g; got %.3g and %.3g.',fl,sol(11),f_Al_pred);
assert(abs(log(sol(11)/f_Al_pred)) <= 1e-8, ...
    'test_erw_appelo_exchange_floor:AlRelation', ...
    'The unfloored Al exchange relation is violated by a log ratio of %.3g.', ...
    log(sol(11)/f_Al_pred));
predicted = [K(2)*sol(7)*rho^2*10^(2*alpha*sol(15)), ...
    K(3)*sol(9)*rho*10^(alpha*sol(15)), ...
    K(4)*sol(10)*rho*10^(alpha*sol(15)), ...
    K(5)*sol(8)*rho^2*10^(2*alpha*sol(15))];
actual = [sol(12) sol(13) sol(14) sol(16)];
assert(all(abs(log(actual./predicted)) <= 1e-8), ...
    'test_erw_appelo_exchange_floor:BaseRelations', ...
    'A base-cation exchange relation is violated (log ratios %s).', ...
    mat2str(log(actual./predicted),3));
assert(abs(sum(sol(11:16)) - 1) <= 1e-10, ...
    'test_erw_appelo_exchange_floor:SiteSum', ...
    'Exchanger fractions sum to %.16g.',sum(sol(11:16)));

%% Mass and charge: the exchanger holds no Al, the inventory closes, the
%% carbonate speciation and the physical check pass.
Al_exchange = sol(11)*F.constants.CEC_tot*scale/3;
Al_dissolved = ERW_data.Al_w*F.constants.soil_water_l;
closure = Al_exchange + Al_dissolved + ERW_data.AlOH3_solid - ERW_data.Al_tot;
assert(Al_exchange < 1e-6 && abs(closure) <= 1e-6*ERW_data.Al_tot, ...
    'test_erw_appelo_exchange_floor:AlInventory', ...
    'Al inventory: exchange %.3g umol m^-2, closure %.3g of %.6g.', ...
    Al_exchange,closure,ERW_data.Al_tot);
assert(abs(ERW_var.raw_residual(3)) <= 1e-6 && ERW_var.physics.is_valid, ...
    'test_erw_appelo_exchange_floor:Physical', ...
    'Charge residual %.3g or physical check failed.',ERW_var.raw_residual(3));

%% Aqueous charge includes dissolved Al.
al_charge = (3*ERW_data.Al + 2*ERW_data.AlOH + ...
    ERW_data.AlOH2 - ERW_data.AlOH4)/scale;
cation_charge = ERW_data.H + 2*ERW_data.Ca + 2*ERW_data.Mg + ...
    ERW_data.Na + ERW_data.K + ERW_data.NH4 + al_charge;
anion_charge = ERW_data.k_w/ERW_data.H + ERW_data.HCO3 + ...
    2*ERW_data.CO3 + ERW_data.NO3 + ERW_data.PO4 + ERW_data.An;
assert(abs(cation_charge-anion_charge) <= ...
    1e-8*max(1,abs(cation_charge)+abs(anion_charge)), ...
    'test_erw_appelo_exchange_floor:AqueousCharge', ...
    'Aqueous charge remains unbalanced by %.6g umolc/L.', ...
    cation_charge-anion_charge);
assert(abs(ERW_data.charge_residual-(cation_charge-anion_charge)) <= ...
    1e-10*max(1,abs(cation_charge)+abs(anion_charge)), ...
    'test_erw_appelo_exchange_floor:StoredCharge', ...
    'The saved charge residual does not include the aqueous Al species.');

%% Above the floor the relation is the full selectivity law: raise the
%% residual-anion inventory so the column is less alkaline, and require
%% the unfloored Al relation with f_Al above fl_app.
acid_args = args;
acid_args{strcmp(arg_names,'An_tot')} = F.inputs.An_tot*1.15;
[acid_data,~,~,~,~,acid_var] = ERW_function(acid_args{:});
sol_a = acid_data.sol;
rho_a = sol_a(15)/sol_a(3);
f_Al_pred_a = K(1)*(sol_a(6)/scale)*rho_a^3*10^(3*alpha*sol_a(15));
assert(~acid_var.no_converge && sol_a(11) > fl && f_Al_pred_a > fl && ...
    abs(log(sol_a(11)/f_Al_pred_a)) <= 1e-6, ...
    'test_erw_appelo_exchange_floor:AboveFloor', ...
    ['Above the floor the Al relation must hold unfloored: f_Al %.3g, ' ...
     'prediction %.3g, pH %.3f, converged %d.'], ...
    sol_a(11),f_Al_pred_a,acid_data.pH,~acid_var.no_converge);

fprintf('PASS  step 22053 accepted at the mass-conserving root: pH %.3f, f_Al %.3g (prediction %.3g), max scaled residual %.2e\n', ...
    ERW_data.pH,sol(11),f_Al_pred,ERW_var.max_scaled_res);
fprintf('PASS  above the floor the Al relation holds unfloored: pH %.3f, f_Al %.3g\n', ...
    acid_data.pH,sol_a(11));
end
