function test_erw_input_guards
%%% Physical-input guards and checkpoint dependencies.

test_dir = fileparts(mfilename('fullpath'));
code_dir = fullfile(test_dir,'..');
addpath(code_dir);
param_source = fileread(fullfile(code_dir,'Parameters','ERW_MOD_PARAM_excel.m'));
frame_1d = fileread(fullfile(code_dir,'MAIN_FRAME_BG_ERW_10mins.m'));
step_2d = fileread(fullfile(code_dir,'ERW_Daily_Step_2D.m'));
frame_2d = fileread(fullfile(code_dir,'MAIN_FRAME_BG_ERW_2D.m'));
erw_source = fileread(fullfile(code_dir,'ERW_function.m'));
application_source = fileread(fullfile(code_dir,'ERW_Application_Indices.m'));

assert(contains(param_source,'numel(rock_f_in) ~= number_min'), ...
    'Mineral fractions must reject a dimension mismatch.');
assert(isempty(regexp(param_source,'An\(1\)\s*=\s*max\(', 'once')), ...
    'The residual-anion seed must not be clamped.');
assert(contains(param_source,'Rainwater Na supply must be finite and nonnegative'), ...
    'Rainwater Na requires a strict physical-domain check.');
assert(~contains(param_source,'I_Na_source(~isfinite(I_Na_source) | I_Na_source < 0) = 0'), ...
    'Invalid sodium boundary forcing must not be replaced silently by zero.');
assert(~contains(param_source,'I_An_source(~isfinite(I_An_source) | I_An_source < 0) = 0'), ...
    'Invalid residual-anion boundary forcing must not be replaced silently by zero.');
assert(contains(param_source,'ERW:invalidBoundarySource'), ...
    'Invalid sodium and residual-anion forcing require an explicit error.');
assert(contains(application_source,'ERW:applicationGrid') && ...
    contains(frame_1d,'ERW_Application_Indices') && ...
    contains(step_2d,'ERW_Application_Indices'), ...
    'Both drivers must use the shared off-grid application guard.');
assert(contains(frame_2d,'ERW_Mineral_Saturation.m'), ...
    'Checkpoint fingerprints must track the mineral saturation equations.');
assert(~contains(erw_source,'pH_scan = linspace(0,16') && ...
    contains(erw_source,'ERW:nonUniquePorePH'), ...
    'Pore-water chemistry must require one root inside 0 < pH < 14.');
assert(contains(erw_source,"inventory_names = {'Ca','Mg','K','Na','An','Al','Si','IC','PO4','NO3','NH4'}") && ...
    contains(erw_source,'inventory_initial') && ...
    contains(erw_source,'inventory_final') && ...
    count(erw_source,"error('ERW:PoolInventory'") >= 2, ...
    'Incoming and updated ERW inventories require finite, nonnegative guards.');
pool0_pattern = ['pool0\s*=\s*\[\s*Ca_tot_prev\s*,\s*Mg_tot_prev\s*,\s*' ...
    'K_tot_prev\s*,\s*Na_tot_prev\s*,\s*An_tot_prev\s*,\s*\.\.\.\s*' ...
    'Al_tot_prev\s*,\s*IC_tot_prev\s*,\s*PO4_tot_prev\s*,\s*' ...
    'NO3_tot_prev\s*,\s*NH4_tot_prev\s*\];'];
assert(~isempty(regexp(erw_source,pool0_pattern,'once')) && ...
    contains(erw_source, ...
    'pool_final = [Ca_tot, Mg_tot, K_tot, Na_tot, An_tot, Al_tot, IC_tot, PO4_tot, NO3_tot, NH4_tot];'), ...
    'The ten-position no-solid solver vectors must not include or reorder Si.');
assert(contains(erw_source,'~isfinite(IC_tot) || IC_tot < 0'), ...
    'The post-gas-exchange IC guard must reject NaN and negative inventories.');
assert(contains(erw_source,'Iw*1000*DIC_rain*dtw'), ...
    'Daily rainwater DIC input must be scaled to the ERW sub-step.');
assert(contains(erw_source,'ERW:invalidPhosphorusRelease'), ...
    'Weathered P must reject a negative or nonfinite source.');

header_start = regexp(erw_source,'ERW_function\(','end','once') + 1;
header_end = regexp(erw_source,'\)\r?\n\r?\n%%%% INPUT','start','once') - 1;
arg_names = strtrim(strsplit(regexprep( ...
    erw_source(header_start:header_end),'\.\.\.',''),','));
assert(numel(arg_names) == nargin('ERW_function'), ...
    'The ERW runtime-guard fixture does not match the function signature.');

args = repmat({1},1,numel(arg_names));
overrides = { ...
    'n',0.4; 's_pre',0.5; 's',0.5; 'Lw',0; 'Tw',0; 'Iw',0; ...
    'Zrw',0.3; 'r_het',0; 'r_aut',0; 'temp_soil',20; ...
    'K_CEC',ones(1,5); 'CEC_tot',1; 'R',8.314; 'T_ref',293.15; ...
    'min_st',zeros(1,7); 'dtw',1/144; 'conv_mol',1e6; ...
    'pH_rain',5.6; 'CO2_atm',18; 'CO2_air',18; ...
    'EW',0; 'I_Ca',0; 'I_Mg',0; 'I_Na',0; 'I_K',0; 'I_An',0; ...
    'W_CaCO3',0; 'W_MgCO3',0; 'rock_app',0; 'mineral',''; ...
    'dCa_tot',0; 'dMg_tot',0; 'dK_tot',0; 'dSi_tot',0; ...
    'M_rock_add',0; 'f_Lk_biogeo',0; 'f_T_biogeo',0; ...
    'dPO4_tot',0; 'dNO3_tot',0; 'dNH4_tot',0; 'keyword_add',0; ...
    'bulk_pH_params',struct()};
for k = 1:size(overrides,1)
    idx = find(strcmp(arg_names,overrides{k,1}),1);
    assert(~isempty(idx),'ERW argument %s is missing.',overrides{k,1});
    args{idx} = overrides{k,2};
end

negative_args = args;
negative_args{strcmp(arg_names,'Ca_tot')} = -1;
assert_error(@() ERW_function(negative_args{:}), ...
    'ERW:PoolInventory','Incoming Ca');
nan_args = args;
nan_args{strcmp(arg_names,'Si_tot')} = NaN;
assert_error(@() ERW_function(nan_args{:}), ...
    'ERW:PoolInventory','Incoming Si');
updated_args = args;
updated_args{strcmp(arg_names,'dSi_tot')} = NaN;
assert_error(@() ERW_function(updated_args{:}), ...
    'ERW:PoolInventory','Updated Si');

%% NO3 and NH4 step between T&C's daily states, so an update that lands a
%% few ulps below zero on a day that empties the pool (the all-minimum
%% member, 15 September 2016) is zero and the step runs on, here to the
%% deliberate CEC stop. A nonfinite update and a negative incoming state
%% are still rejected.
for pool = {'NO3','NH4'}
    roundoff_args = args;
    roundoff_args{strcmp(arg_names,'CEC_tot')} = 0;
    roundoff_args{strcmp(arg_names,[pool{1} '_tot'])} = 1e-15;
    roundoff_args{strcmp(arg_names,['d' pool{1} '_tot'])} = -4.45e-15*144;
    assert_error(@() ERW_function(roundoff_args{:}), ...
        'ERW:invalidParam','CEC_tot');
    nan_update_args = args;
    nan_update_args{strcmp(arg_names,['d' pool{1} '_tot'])} = NaN;
    assert_error(@() ERW_function(nan_update_args{:}), ...
        'ERW:PoolInventory',['Updated ' pool{1}]);
    incoming_args = args;
    incoming_args{strcmp(arg_names,[pool{1} '_tot'])} = -1e-15;
    assert_error(@() ERW_function(incoming_args{:}), ...
        'ERW:PoolInventory',['Incoming ' pool{1}]);
end

negative_p_args = args;
negative_p_args{strcmp(arg_names,'min_st')} = [0 0 0 0 0 0 1];
negative_p_args{strcmp(arg_names,'EW')} = -1;
assert_error(@() ERW_function(negative_p_args{:}), ...
    'ERW:invalidPhosphorusRelease','finite and nonnegative');
nan_p_args = negative_p_args;
nan_p_args{strcmp(arg_names,'EW')} = NaN;
assert_error(@() ERW_function(nan_p_args{:}), ...
    'ERW:invalidPhosphorusRelease','finite and nonnegative');

% Negative Iw is a test-only mutation. With dtw the rain term removes
% 0.5 umol m^-2; without dtw it overdraws IC before the deliberate CEC stop.
rain_args = args;
rain_args{strcmp(arg_names,'CEC_tot')} = 0;
rain_args{strcmp(arg_names,'IC_tot')} = 5;
rain_args{strcmp(arg_names,'Iw')} = -0.00412747990247532;
assert_error(@() ERW_function(rain_args{:}), ...
    'ERW:invalidParam','CEC_tot');

fprintf('PASS: ERW physical-input and checkpoint guards are explicit.\n');
end

function assert_error(f,identifier,message_fragment)
try
    f();
catch ME
    assert(strcmp(ME.identifier,identifier), ...
        'Expected %s, got %s: %s',identifier,ME.identifier,ME.message);
    assert(contains(ME.message,message_fragment), ...
        'The %s error did not identify %s.',identifier,message_fragment);
    return
end
error('Expected %s, but no error was raised.',identifier);
end
