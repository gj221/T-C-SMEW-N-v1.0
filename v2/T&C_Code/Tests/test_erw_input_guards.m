function test_erw_input_guards
%%% Source-level guards for physical inputs and checkpoint dependencies.

test_dir = fileparts(mfilename('fullpath'));
code_dir = fullfile(test_dir,'..');
param_source = fileread(fullfile(code_dir,'Parameters','ERW_MOD_PARAM_excel.m'));
frame_1d = fileread(fullfile(code_dir,'MAIN_FRAME_BG_ERW_10mins.m'));
step_2d = fileread(fullfile(code_dir,'ERW_Daily_Step_2D.m'));
frame_2d = fileread(fullfile(code_dir,'MAIN_FRAME_BG_ERW_2D.m'));
erw_source = fileread(fullfile(code_dir,'ERW_function.m'));

assert(contains(param_source,'numel(rock_f_in) ~= number_min'), ...
    'Mineral fractions must reject a dimension mismatch.');
assert(isempty(regexp(param_source,'An\(1\)\s*=\s*max\(', 'once')), ...
    'The residual-anion seed must not be clamped.');
assert(contains(param_source,'Rainwater Na supply must be finite and nonnegative'), ...
    'Rainwater Na requires a strict physical-domain check.');
assert(~contains(param_source,'I_Na_source(~isfinite(I_Na_source) | I_Na_source < 0) = 0'), ...
    'Invalid sodium boundary forcing must not be replaced silently by zero.');
assert(~contains(param_source,'I_An_source(~isfinite(I_An_source) | I_An_source < 0) = 0'), ...
    'Invalid residual-anion boundary forcing must not be replaced silently by zero.');
assert(contains(param_source,'ERW:invalidBoundarySource'), ...
    'Invalid sodium and residual-anion forcing require an explicit error.');
assert(contains(frame_1d,'ERW:applicationGrid') && ...
    contains(step_2d,'ERW:applicationGrid'), ...
    'Both drivers must reject off-grid application dates.');
assert(contains(frame_2d,'ERW_Mineral_Saturation.m'), ...
    'Checkpoint fingerprints must track the mineral saturation equations.');
assert(~contains(erw_source,'pH_scan = linspace(0,16') && ...
    contains(erw_source,'ERW:nonUniquePorePH'), ...
    'Pore-water chemistry must require one root inside 0 < pH < 14.');

fprintf('PASS: ERW physical-input and checkpoint guards are explicit.\n');
end
