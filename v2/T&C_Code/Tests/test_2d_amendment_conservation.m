function test_2d_amendment_conservation
%%% Check the 2-D invariants during a spatially uneven basalt application.

fprintf('\n=== test_2d_amendment_conservation ===\n');
test_dir = fileparts(mfilename('fullpath'));
code_dir = fileparts(test_dir);
v2 = fileparts(code_dir);
addpath(fullfile(v2,'run'),code_dir, ...
    fullfile(code_dir,'Inputs'),fullfile(code_dir,'Parameters'));

n_pass = 0; n_fail = 0;
    function check(name,cond,detail)
        if nargin < 3; detail = ''; end
        if cond
            n_pass = n_pass + 1; fprintf('  PASS  %s\n',name);
        else
            n_fail = n_fail + 1; fprintf('  FAIL  %s  %s\n',name,detail);
        end
    end

result_dir = tempname; mkdir(result_dir);
old_ckpt = getenv('TC_CKPT_MINUTES');
old_workers = getenv('TC_PARALLEL_WORKERS');
cleanup = onCleanup(@() restore(result_dir,old_ckpt,old_workers)); %#ok<NASGU>
setenv('TC_CKPT_MINUTES','0');
setenv('TC_PARALLEL_WORKERS','');

result_file = Run_One_Subfield(8,'StartDate',datenum(2016,11,5), ...
    'NDays',8,'GridNx',2,'GridNy',2,'AppeloAlpha',1.3, ...
    'ParallelWorkers',6,'SaveResults',true,'ResultDirectory',result_dir);
S = load(result_file,'Domain','ERW','O','V','PH_d','P','PAR','dth','Datam', ...
    'Pr_liq','Pr_sno','IrD','Vice','EG','ELitter','T_L','T_H', ...
    'EIn_L','EIn_H','Rh','Qi_out','Rd','Qi_in','q_runon','EWAT', ...
    'ESN','ESN_In','EIn_urb','EIn_rock','SWE','In_SWE','SP_wc', ...
    'In_H','In_L','In_Litter','In_urb','In_rock','EICE','IP_wc', ...
    'ICE','WAT','FROCK','Vx_H','Vl_H','Vx_L','Vl_L','Ccrown_c', ...
    'CcrownFIX','Ccrown_t','B_H','B_L','RA_H','RA_L','An_H','An_L', ...
    'Rmr_H','Rmc_H','Rms_H','Rg_H','TexC_H', ...
    'Rmr_L','Rmc_L','Rms_L','Rg_L','TexC_L','SeedInput');
last_daily_row = nnz(S.Datam(:,4) == 1) + 1;

%% ---------------------------------------------------------------------
%% The amendment actually happened inside the window
%% ---------------------------------------------------------------------
applied = cellfun(@(E) sum(E.TC_const.M_rock_add),S.ERW);
amended = applied > 0;
margin = ~strcmp(S.Domain.cell_region,'main');
check('only margin cells receive basalt',isequal(amended(:),margin(:)), ...
    sprintf('%d amended cells, %d margin cells',sum(amended),sum(margin)));
check('each amended cell receives 5000 g/m2', ...
    all(abs(applied(amended)-5000) < 1e-9), ...
    sprintf('range %.6g to %.6g',min(applied(amended)),max(applied(amended))));
event_rows = zeros(sum(amended),1);
amended_index = find(amended);
for k = 1:numel(amended_index)
    event_rows(k) = find(S.ERW{amended_index(k)}.TC_const.M_rock_add > 0,1);
end
expected_row = 5*144 + 1;
check('the application lands on the 10 November row', ...
    all(event_rows == expected_row), ...
    sprintf('rows %s, expected %d',mat2str(unique(event_rows).'),expected_row));

has_mineral = arrayfun(@(c) any(S.ERW{c}.bg.M_min(end,:) > 0), ...
    (1:numel(S.ERW)).');
check('primary mineral remains in each amended cell', ...
    all(has_mineral(amended)),sprintf('%d of %d amended columns', ...
    sum(has_mineral(amended)),sum(amended)));

%% ---------------------------------------------------------------------
%% Lateral conservation across the amendment
%% ---------------------------------------------------------------------
L = S.Domain.lateral;
species = {'Na','Al','An','DIC'};
has_uncancelled_erw = isfield(L,'erw_mass_abs_residual_umol') && ...
    isfield(L,'erw_mass_throughput_umol') && ...
    isequal(size(L.erw_mass_abs_residual_umol), ...
    size(L.erw_mass_throughput_umol)) && ...
    size(L.erw_mass_abs_residual_umol,2) == numel(species);
check('the driver records uncancelled ERW mass residuals',has_uncancelled_erw);
if has_uncancelled_erw
    for s = 1:numel(species)
        residual_series = L.erw_mass_abs_residual_umol(:,s);
        throughput_series = L.erw_mass_throughput_umol(:,s);
        physical = all(isfinite(residual_series)) && all(residual_series >= 0) && ...
            all(isfinite(throughput_series)) && all(throughput_series >= 0);
        r = sum(residual_series);
        moved = sum(throughput_series);
        rel = r/max(eps,moved);
        check(sprintf('lateral %s conserved across the amendment',species{s}), ...
            physical && moved > 0 && isfinite(rel) && rel < 1e-6, ...
            sprintf('absolute residual %.6g of %.6g moved (relative %.3e)', ...
            r,moved,rel));
    end
end
water_physical = all(isfinite(L.water_buf_to_main));
mass_physical = all(isfinite(L.mass_buf_to_main),'all');
water_moved = sum(abs(L.water_buf_to_main));
mass_moved = sum(abs(L.mass_buf_to_main),'all');
check('the amendment produces lateral water transport', ...
    water_physical && water_moved > 0, ...
    sprintf('moved %.6g m3',water_moved));
check('the amendment produces lateral solute transport', ...
    mass_physical && mass_moved > 0, ...
    sprintf('moved %.6g g',mass_moved));
heat_physical = all(isfinite(L.heat_residual_relative));
heat_rel = max(abs(L.heat_residual_relative));
check('lateral energy conserved across the amendment', ...
    heat_physical && isfinite(heat_rel) && heat_rel < 1e-6, ...
    sprintf('max relative %.3e',heat_rel));

%% Adaptive sub-stepping must not have saturated: a capped solver limits
%% fluxes instead of resolving them, which would hide a real gradient.
check('water sub-stepping did not run away', ...
    isfinite(max(L.sub_steps_max)) && max(L.sub_steps_max) < 1e4, ...
    sprintf('peak %g',max(L.sub_steps_max)));
check('heat sub-stepping did not run away', ...
    isfinite(max(L.heat_sub_steps_max)) && max(L.heat_sub_steps_max) < 1e4, ...
    sprintf('peak %g',max(L.heat_sub_steps_max)));

[water_residual_m3,water_relative] = water_closure(S);
check('domain water ledger closes', ...
    isfinite(water_relative) && water_relative < 1e-6, ...
    sprintf('residual %.6g m3 (relative %.3e)', ...
    water_residual_m3,water_relative));
S_first_irrigation = S;
S_first_irrigation.IrD(1) = S_first_irrigation.IrD(1) + 1;
[first_irrigation_residual_m3,~] = water_closure(S_first_irrigation);
check('the ledger excludes the unapplied first irrigation row', ...
    abs(first_irrigation_residual_m3-water_residual_m3) < 1e-12, ...
    sprintf('residual changed by %.6g m3', ...
    first_irrigation_residual_m3-water_residual_m3));
S_deep_storage = S;
S_deep_storage.FROCK(end,1,1) = S_deep_storage.FROCK(end,1,1) + 1;
[deep_storage_residual_m3,~] = water_closure(S_deep_storage);
expected_deep_shift_m3 = -S.Domain.cell_area_m2(1)/1000;
check('bottom leakage is retained as fracture-rock storage', ...
    abs(deep_storage_residual_m3-water_residual_m3- ...
    expected_deep_shift_m3) < 1e-12, ...
    sprintf('residual shift %.6g m3', ...
    deep_storage_residual_m3-water_residual_m3));

crown_history = permute(S.Ccrown_t(2:last_daily_row,:,:),[3 2 1]);
crown_change = crown_history-reshape(S.CcrownFIX, ...
    size(S.CcrownFIX,1),size(S.CcrownFIX,2),1);
check('the carbon closure window has fixed crown areas', ...
    max(abs(crown_change),[],'all') < 1e-12, ...
    'crown area changed inside the test window');
[carbon_residual_gCm2,carbon_relative] = carbon_closure(S);
%% Require closure within 1 mg C m-2 and 0.01% of assimilated plus seed C.
check('vegetation carbon ledger closes', ...
    isfinite(carbon_relative) && abs(carbon_residual_gCm2) < 1e-3 && ...
    (carbon_relative < 1e-4 || abs(carbon_residual_gCm2) < 1e-4), ...
    sprintf('residual %.6g gC/m2 (relative %.3e)', ...
    carbon_residual_gCm2,carbon_relative));
S_zero_final_ra = S;
S_zero_final_ra.RA_H(last_daily_row,:,:) = 0;
S_zero_final_ra.RA_L(last_daily_row,:,:) = 0;
[zero_ra_residual_gCm2,~] = carbon_closure(S_zero_final_ra);
check('the carbon endpoint is independent of final respiration', ...
    abs(zero_ra_residual_gCm2-carbon_residual_gCm2) < 1e-12, ...
    sprintf('residual changed by %.6g gC/m2', ...
    zero_ra_residual_gCm2-carbon_residual_gCm2));

%% ---------------------------------------------------------------------
%% The state stays physical while the pulse dissolves
%% ---------------------------------------------------------------------
check('soil moisture is finite and nonnegative', ...
    all(isfinite(S.O(:))) && all(S.O(:) >= 0), 'O left the physical range');
check('soil water is finite and nonnegative', ...
    all(isfinite(S.V(:))) && all(S.V(:) >= 0), 'V left the physical range');
ph = S.PH_d(1:last_daily_row,:);
check('pH stays inside 0 to 14', ...
    ~isempty(ph) && all(isfinite(ph),'all') && all(ph > 0 & ph < 14,'all'), ...
    sprintf('range %.4g to %.4g',min(ph),max(ph)));
p_state = S.P(1:last_daily_row,:,:);
check('biogeochemical pools are finite', ...
    all(isfinite(p_state),'all'), 'P contains NaN or Inf');

for c = 1:numel(S.ERW)
    bg = S.ERW{c}.bg;
    bad = false;
    for name = {'Ca','Mg','Na','K','Al','Si','DIC','NO3','NH4'}
        v = bg.(name{1});
        if any(~isfinite(v(:))) || any(v(:) < 0); bad = true; end
    end
    if bad
        check(sprintf('column %d chemistry is finite and nonnegative',c), ...
            false,'negative or non-finite species');
        break
    end
end
if ~bad
    check('all columns keep finite nonnegative chemistry',true);
end

fprintf('\n  %d passed, %d failed\n',n_pass,n_fail);
if n_fail > 0
    error('test_2d_amendment_conservation:Failed', ...
        '%d amendment-period check(s) failed',n_fail);
end
fprintf(['PASS: the 2-D invariants hold while feedstock is applied.' ...
    '\n']);
end

function restore(result_dir,old_ckpt,old_workers)
setenv('TC_CKPT_MINUTES',old_ckpt);
setenv('TC_PARALLEL_WORKERS',old_workers);
pool = gcp('nocreate');
if ~isempty(pool); delete(pool); end
if isfolder(result_dir); rmdir(result_dir,'s'); end
end

function [domain_residual_m3,relative] = water_closure(S)
n_col = numel(S.PAR);
cell_residual_mm = zeros(n_col,1);
cell_input_mm = zeros(n_col,1);
for c = 1:n_col
    p = S.PAR{c};
    soil_storage = p.Asur*p.Ared*( ...
        sum(S.V(1,:,c)-S.V(end,:,c),'all') + ...
        sum(S.Vice(1,:,c)-S.Vice(end,:,c),'all'));
    inputs = sum(S.Pr_liq(2:end,1,c)+S.Pr_sno(2:end,1,c),'all')*S.dth + ...
        sum(S.IrD(2:end))*S.dth + sum(S.Qi_in(:,:,c),'all')*S.dth + ...
        sum(S.q_runon(:,1,c),'all')*S.dth;
    outputs = (sum(S.EG(:,1,c),'all') + sum(S.ELitter(:,1,c),'all') + ...
        sum(S.T_L(:,:,c),'all') + sum(S.T_H(:,:,c),'all') + ...
        sum(S.EIn_L(:,:,c),'all') + sum(S.EIn_H(:,:,c),'all') + ...
        sum(S.Qi_out(:,:,c),'all') + sum(S.EWAT(:,1,c),'all') + ...
        sum(S.ESN(:,1,c),'all') + sum(S.ESN_In(:,1,c),'all') + ...
        sum(S.EIn_urb(:,1,c),'all') + sum(S.EIn_rock(:,1,c),'all') + ...
        sum(S.EICE(:,1,c),'all'))*S.dth + ...
        sum(S.Rh(:,1,c),'all') + sum(S.Rd(:,1,c),'all');
    surface_storage = S.SWE(1,1,c)-S.SWE(end,1,c) + ...
        S.In_SWE(1,1,c)-S.In_SWE(end,1,c) + ...
        S.SP_wc(1,1,c)-S.SP_wc(end,1,c) + ...
        sum(S.In_H(1,:,c)-S.In_H(end,:,c),'all') + ...
        sum(S.In_L(1,:,c)-S.In_L(end,:,c),'all') + ...
        S.In_Litter(1,1,c)-S.In_Litter(end,1,c) + ...
        S.In_urb(1,1,c)-S.In_urb(end,1,c) + ...
        S.In_rock(1,1,c)-S.In_rock(end,1,c) + ...
        S.IP_wc(1,1,c)-S.IP_wc(end,1,c) + ...
        S.ICE(1,1,c)-S.ICE(end,1,c) + ...
        S.WAT(1,1,c)-S.WAT(end,1,c) + ...
        S.FROCK(1,1,c)-S.FROCK(end,1,c);
    plant_storage = p.Asur*sum(( ...
        S.Vx_H(1,:,c)-S.Vx_H(end,:,c) + ...
        S.Vl_H(1,:,c)-S.Vl_H(end,:,c) + ...
        S.Vx_L(1,:,c)-S.Vx_L(end,:,c) + ...
        S.Vl_L(1,:,c)-S.Vl_L(end,:,c)).*S.Ccrown_c(c,:));
    cell_residual_mm(c) = inputs-outputs+soil_storage+ ...
        surface_storage+plant_storage;
    cell_input_mm(c) = inputs;
end
area = S.Domain.cell_area_m2(:);
domain_residual_m3 = sum(cell_residual_mm.*area)/1000;
domain_input_m3 = sum(cell_input_mm.*area)/1000;
relative = abs(domain_residual_m3)/max(eps,domain_input_m3);
end

function [domain_residual_gCm2,relative] = carbon_closure(S)
n_col = numel(S.PAR);
n_pft = size(S.Ccrown_c,2);
last_assimilated_hour = find(S.Datam(:,4) == 1,1,'last') - 1;
assert(last_assimilated_hour >= 1, ...
    'The closure window has no completed daily vegetation update.');
last_daily_row = nnz(S.Datam(:,4) == 1) + 1;
assert(last_daily_row <= size(S.B_H,1), ...
    'The final daily vegetation row is outside the saved state.');
cell_residual = zeros(n_col,1);
cell_input = zeros(n_col,1);
for c = 1:n_col
    for k = 1:n_pft
        assimilation_h = 0.0432*sum(S.An_H(1:last_assimilated_hour,k,c),'all');
        assimilation_l = 0.0432*sum(S.An_L(1:last_assimilated_hour,k,c),'all');
        residual_h = sum(S.B_H(1,k,:,c)-S.B_H(last_daily_row,k,:,c),'all') + ...
            assimilation_h - sum(S.Rmr_H(1:last_daily_row,k,c)+ ...
            S.Rmc_H(1:last_daily_row,k,c)+S.Rms_H(1:last_daily_row,k,c)+ ...
            S.Rg_H(1:last_daily_row,k,c)+S.TexC_H(1:last_daily_row,k,c),'all');
        residual_l = sum(S.B_L(1,k,:,c)-S.B_L(last_daily_row,k,:,c),'all') + ...
            assimilation_l - sum(S.Rmr_L(1:last_daily_row,k,c)+ ...
            S.Rmc_L(1:last_daily_row,k,c)+S.Rms_L(1:last_daily_row,k,c)+ ...
            S.Rg_L(1:last_daily_row,k,c)+S.TexC_L(1:last_daily_row,k,c),'all');
        crown = S.Ccrown_c(c,k);
        cell_residual(c) = cell_residual(c) + crown*(residual_h+residual_l);
        cell_input(c) = cell_input(c) + crown*(assimilation_h+assimilation_l);
    end
    seed_input = sum(S.SeedInput(:,1,c),'all');
    cell_residual(c) = cell_residual(c) + seed_input;
    cell_input(c) = cell_input(c) + seed_input;
end
area = S.Domain.cell_area_m2(:);
domain_residual_gCm2 = sum(cell_residual.*area)/S.Domain.area_m2;
domain_input_gCm2 = sum(cell_input.*area)/S.Domain.area_m2;
relative = abs(domain_residual_gCm2)/max(eps,domain_input_gCm2);
end
