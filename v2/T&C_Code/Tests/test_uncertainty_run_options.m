function test_uncertainty_run_options
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% The uncertainty-ensemble knobs of Run_One_Subfield: BiogeoOverrides,
%% DissolutionFactor and SaturationExponent are validated before any
%% forcing is loaded, reach the column configuration and the provenance,
%% and spell themselves in the result and checkpoint tags. Source pins
%% keep the frame, BIOGEO_UNIT and the daily step on the same path.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

test_dir = fileparts(mfilename('fullpath'));
code_dir = fileparts(test_dir);
run_dir = fullfile(fileparts(code_dir),'run');
addpath(code_dir,fullfile(code_dir,'Parameters'),run_dir);

%% Option validation, all before the workbook and forcing are read.
assert_error(@() Run_One_Subfield(11,'DissolutionFactor',0), ...
    'Run_One_Subfield:BadOptions');
assert_error(@() Run_One_Subfield(11,'DissolutionFactor',[0.8 1.2]), ...
    'Run_One_Subfield:BadOptions');
assert_error(@() Run_One_Subfield(11,'SaturationExponent',-0.5), ...
    'Run_One_Subfield:BadOptions');
assert_error(@() Run_One_Subfield(11,'SaturationExponent','sqrt'), ...
    'Run_One_Subfield:BadOptions');

%% The parameter script owns the override rules.
assert_error(@() Run_One_Subfield(11,'NDays',1,'BiogeoOverrides', ...
    struct('KNmaxd',0.0064)),'Biogeochemistry_Parameter:InvalidOverride');
assert_error(@() Run_One_Subfield(11,'NDays',1,'BiogeoOverrides', ...
    struct('NoSuchLiteral',1)),'Biogeochemistry_Parameter:UnknownOverride');

%% Source pins: the driver records and tags every knob, the frame carries
%% them into the identity string and BIOGEO_UNIT, the daily step applies
%% the exponent where the saturation series is formed.
driver = fileread(fullfile(run_dir,'Run_One_Subfield.m'));
driver_tokens = { ...
    "'BiogeoOverrides',[],'DissolutionFactor',[],'SaturationExponent',[]", ...
    'run_provenance.biogeo_overrides = opt.BiogeoOverrides;', ...
    'run_provenance.dissolution_factor = opt.DissolutionFactor;', ...
    'run_provenance.saturation_exponent = saturation_exponent;', ...
    "'biogeo_overrides',opt.BiogeoOverrides, ...", ...
    "'saturation_exponent',saturation_exponent), ...", ...
    'feedstock_rows = isfinite(ERW_PARAM_input.diss_f);', ...
    'Biogeochemistry_Parameter(1,[],opt.BiogeoOverrides);', ...
    "sprintf('%s__bg%s',tag,biogeo_override_tag(opt.BiogeoOverrides))", ...
    "sprintf('%s__fd%s',tag,number_tag(opt.DissolutionFactor))", ...
    "sprintf('%s__sexp%s',tag,number_tag(opt.SaturationExponent))", ...
    "sprintf('%s__bg%s',ckpt_tag,biogeo_override_tag(opt.BiogeoOverrides))", ...
    "sprintf('%s__fd%s',ckpt_tag,number_tag(opt.DissolutionFactor))", ...
    "sprintf('%s__sexp%s',ckpt_tag,number_tag(opt.SaturationExponent))"};
for k = 1:numel(driver_tokens)
    assert(contains(driver,driver_tokens{k}), ...
        'Run_One_Subfield omits %s.',driver_tokens{k});
end
frame = fileread(fullfile(code_dir,'MAIN_FRAME_BG_ERW_2D.m'));
assert(contains(frame,'biogeo_overrides{c} = ColCfg(c).biogeo_overrides;') && ...
       contains(frame,'lastapp=%s;bgovr=%s;sexp=%s') && ...
       contains(frame,'biogeo_KNmaxd{c}, ...') && ...
       contains(frame,'biogeo_overrides{c});'), ...
    'The frame does not carry the overrides into the identity and BIOGEO_UNIT.');
unit = fileread(fullfile(code_dir,'BIOGEO_UNIT.m'));
assert(contains(unit,'Biogeochemistry_Parameter(opt_cons_CUE,KNmaxd_override,biogeo_overrides)'), ...
    'BIOGEO_UNIT does not pass the overrides to the parameter script.');
daily = fileread(fullfile(code_dir,'ERW_Daily_Step_2D.m'));
assert(numel(strfind(daily,'erw_pore_saturation(p,O_c,pdind,C.n,cfg.saturation_exponent)')) == 2 && ...
       contains(daily,'if exponent ~= 1') && ...
       ~contains(daily,'= sum(p.Bio_Zs.*mean(O_c(pdind,:)))/C.n;'), ...
    'The daily step must form the saturation series through erw_pore_saturation only.');

%% The literals the ensemble may move, and nothing else.
p = Biogeochemistry_Parameter(1);
moved = Biogeochemistry_Parameter(1,[],struct('Vm',1.2,'Vpc',4.8,'Km',0.057, ...
    'rem',0.0075,'rep',0.0075,'pepf',0.0031,'mrb',0.0012,'mrf',0.0012, ...
    'fd',0.2,'Vpl',4.8,'Vdb',0.0024,'Vdf',0.0024));
names = fieldnames(p);
for k = 1:numel(names)
    same = isequal(p.(names{k}),moved.(names{k}));
    is_moved = ismember(names{k},{'Vm','Vpc','Km','rem','rep','pepf', ...
        'mrb','mrf','fd','Vpl','Vdb','Vdf'});
    assert(same ~= is_moved, ...
        'Override of the twelve literals touched %s unexpectedly.',names{k});
end

fprintf('PASS: uncertainty-ensemble run options are validated, recorded and tagged.\n');
end

function assert_error(fun,identifier)
try
    fun();
catch ME
    assert(strcmp(ME.identifier,identifier), ...
        'Expected %s, got %s: %s',identifier,ME.identifier,ME.message);
    return
end
error('Expected error %s was not raised.',identifier);
end
