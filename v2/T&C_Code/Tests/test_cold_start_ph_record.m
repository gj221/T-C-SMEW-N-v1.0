function test_cold_start_ph_record
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Cold-start pH records: the pore-water and bulk-soil pH records must not
%% both start at the bulk observation.
%%
%% The parameter file's PH is the OBSERVED BULK-SOIL pH, the quantity
%% BIOGEO_UNIT consumes.  With bulk_pH_params.initial_pH_mode =
%% 'bulk_observed', ERW_MOD_PARAM_excel inverts that observation to the
%% pore-water H state the ERW chemistry starts from (Invert_Bulk_pH) and
%% stores it in row 1 of the biogeochem pH series, with row 1 of the
%% pH_bulk series the bulk pH Porewater_to_Bulk_pH returns for that state;
%% the ERW daily loops (ERW_Daily_Step_2D.m and the single-column frame)
%% start at row 2, so row 1 stays the t = 0 initial condition.  That
%% inversion happens inside the first ERW call (the day-2 boundary), after
%% the daily records for rows 1..2 have been written from the driver's
%% seed, so before this fix both PH_pore_d and PH_bulk_d started at the
%% bulk observation and the pore record showed a spurious step at the
%% first ERW update.  Both drivers now backfill rows 1..j from the ERW
%% initial condition at the first ERW call -- the same pairing SCEPTER
%% uses (one pore-water H state solved at t = 0, soil pH a derived
%% diagnostic of it).  Only the records change; the pH values BIOGEO_UNIT
%% and the ERW chemistry consume are what they were.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

fprintf('\n=== test_cold_start_ph_record ===\n');
test_dir = fileparts(mfilename('fullpath'));
code_dir = fileparts(test_dir);
v2_dir = fileparts(code_dir);
addpath(code_dir,fullfile(code_dir,'Parameters'),fullfile(v2_dir,'run'));

%% Source checks: both drivers seed the bulk value from the observation,
%% both carry the backfill, and the ERW daily loops the backfill relies on
%% never overwrite row 1.
frame_2d = flatten(fileread(fullfile(code_dir,'MAIN_FRAME_BG_ERW_2D.m')));
frame_1d = flatten(fileread(fullfile(code_dir,'MAIN_FRAME_BG_ERW_10mins.m')));
daily_2d = flatten(fileread(fullfile(code_dir,'ERW_Daily_Step_2D.m')));
assert(contains(frame_2d,'PH_c(c) = p.PH(1); PH_bulk_c(c) = p.PH(1);') && ...
       contains(frame_1d,'PH_pore_d(1) = PH(1); PH_bulk = PH(1);'), ...
    'test_cold_start_ph_record:SeedChanged', ...
    'The drivers must still seed the bulk-soil pH BIOGEO_UNIT consumes from the parameter file''s bulk observation.');
assert(contains(frame_2d,'PH_pore_d(1:j,c) = ERW{c}.bg.pH(1,1);') && ...
       contains(frame_2d,'PH_bulk_d(1:j,c) = ERW{c}.bg.pH_bulk(1,1);') && ...
       contains(frame_2d,'PH_d(1:j,c) = ERW{c}.bg.pH_bulk(1,1);'), ...
    'test_cold_start_ph_record:Missing2DBackfill', ...
    'MAIN_FRAME_BG_ERW_2D.m must backfill PH_pore_d/PH_bulk_d/PH_d rows 1:j from ERW{c}.bg row 1 at the first ERW call.');
assert(contains(frame_1d,'PH_pore_d(1:j) = ERW_biogeochem.pH(1,1);') && ...
       contains(frame_1d,'PH_bulk_d(1:j) = ERW_biogeochem.pH_bulk(1,1);') && ...
       contains(frame_1d,'PH_d(1:j) = ERW_biogeochem.pH_bulk(1,1);'), ...
    'test_cold_start_ph_record:Missing1DBackfill', ...
    'MAIN_FRAME_BG_ERW_10mins.m must backfill PH_pore_d/PH_bulk_d/PH_d rows 1:j from ERW_biogeochem row 1 at the first ERW call.');
assert(contains(daily_2d,'for dt_m = max(dm_start,2):dm_end') && ...
       contains(frame_1d,'for dt_m = max(dm_start,2):dm_end'), ...
    'test_cold_start_ph_record:Row1Overwritten', ...
    'The ERW daily loops must start at row 2 so row 1 stays the t = 0 initial condition the backfill reads.');
fprintf('PASS  both drivers backfill the cold-start pH records from the ERW t = 0 state; row 1 is never overwritten\n');

%% End-to-end: one short single-column run (Run_Matrix_12 entry 10,
%% control x vertical_1d) through the 2-D driver.
result_dir = tempname; mkdir(result_dir);
old_ckpt = getenv('TC_CKPT_MINUTES');
old_workers = getenv('TC_PARALLEL_WORKERS');
cleanup = onCleanup(@() restore(result_dir,old_ckpt,old_workers));
setenv('TC_CKPT_MINUTES','0');
setenv('TC_PARALLEL_WORKERS','');

result_file = Run_One_Subfield(10,'StartDate',datenum(2016,1,1),'NDays',3, ...
    'ParallelWorkers',0,'SaveResults',true,'ResultDirectory',result_dir);
S = load(result_file,'PH_d','PH_pore_d','PH_bulk_d','ERW','PAR');
assert(all(isfield(S,{'PH_d','PH_pore_d','PH_bulk_d','ERW','PAR'})), ...
    'test_cold_start_ph_record:MissingRecords', ...
    'The result file must carry PH_d, PH_pore_d, PH_bulk_d, ERW and PAR.');
bg = S.ERW{1}.bg;
pore0 = bg.pH(1,1);
bulk0 = bg.pH_bulk(1,1);
pH_obs = S.PAR{1}.PH(1);
assert(isfinite(pore0) && isfinite(bulk0) && isfinite(pH_obs), ...
    'test_cold_start_ph_record:NonFiniteInitial', ...
    'The ERW t = 0 pore (%g) and bulk (%g) pH and the observation (%g) must be finite.',pore0,bulk0,pH_obs);
assert(isequal(S.PH_pore_d(1:2,1),[pore0; pore0]), ...
    'test_cold_start_ph_record:PoreRecordNotBackfilled', ...
    'PH_pore_d rows 1-2 [%.6f %.6f] must be the ERW t = 0 pore-water pH %.6f, not the bulk observation %.6f.', ...
    S.PH_pore_d(1,1),S.PH_pore_d(2,1),pore0,pH_obs);
assert(isequal(S.PH_bulk_d(1:2,1),[bulk0; bulk0]) && isequal(S.PH_d(1:2,1),[bulk0; bulk0]), ...
    'test_cold_start_ph_record:BulkRecordNotBackfilled', ...
    'PH_bulk_d and PH_d rows 1-2 must be the ERW t = 0 bulk pH %.6f (PH_bulk_d = [%.6f %.6f], PH_d = [%.6f %.6f]).', ...
    bulk0,S.PH_bulk_d(1,1),S.PH_bulk_d(2,1),S.PH_d(1,1),S.PH_d(2,1));
assert(abs(pore0-bulk0) > 1e-3, ...
    'test_cold_start_ph_record:SplitNotExercised', ...
    'The inverted pore-water pH (%.6f) equals the bulk pH (%.6f): the split initial condition is not being exercised.',pore0,bulk0);
assert(abs(bulk0-pH_obs) < 1e-3, ...
    'test_cold_start_ph_record:BulkNotObservation', ...
    'Row 1 of the bulk record (%.6f) must reproduce the bulk observation (%.6f): Porewater_to_Bulk_pH of the inverted state is a confirming no-op under initial_pH_mode = bulk_observed.',bulk0,pH_obs);
assert(S.PH_pore_d(3,1) ~= S.PH_pore_d(2,1) || S.PH_bulk_d(3,1) ~= S.PH_bulk_d(2,1), ...
    'test_cold_start_ph_record:NoUpdate', ...
    'Row 3 must carry the first ERW daily update (pore %.6f -> %.6f, bulk %.6f -> %.6f).', ...
    S.PH_pore_d(2,1),S.PH_pore_d(3,1),S.PH_bulk_d(2,1),S.PH_bulk_d(3,1));
fprintf(['PASS  cold start: PH_pore_d(1:2) = %.4f (ERW t = 0 pore-water pH), PH_bulk_d(1:2) = PH_d(1:2) = %.4f ' ...
    '(bulk observation %.4f); row 3 pore %.4f bulk %.4f\n'], ...
    pore0,bulk0,pH_obs,S.PH_pore_d(3,1),S.PH_bulk_d(3,1));
end

function s = flatten(s)
s = regexprep(s,'\s+',' ');
end

function restore(result_dir,old_ckpt,old_workers)
setenv('TC_CKPT_MINUTES',old_ckpt);
setenv('TC_PARALLEL_WORKERS',old_workers);
pool = gcp('nocreate');
if ~isempty(pool); delete(pool); end
if isfolder(result_dir); rmdir(result_dir,'s'); end
end
