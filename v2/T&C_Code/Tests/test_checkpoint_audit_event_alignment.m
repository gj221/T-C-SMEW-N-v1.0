function test_checkpoint_audit_event_alignment
test_dir = fileparts(mfilename('fullpath'));
audit_dir = fullfile(test_dir,'..','..','audit');
addpath(audit_dir);

dates = (datetime(2016,9,10):days(1):datetime(2016,9,14))';
lai = [1.1;1.8;2.2;0;0];
plantC = [90;140;180;0;0];
[growthEnd,harvestRow,harvested,failure] = ...
    Audit_Managed_Crop_Season(dates,lai,plantC,datetime(2016,9,12));
assert(harvested && growthEnd == 3 && harvestRow == 4 && isempty(failure), ...
    'The scheduled removal boundary was not separated from crop growth.');

audit_source = fileread(fullfile(audit_dir, ...
    'Audit_Post_Emergence_Checkpoints.m'));
assert(~isempty(regexp(audit_source, ...
    'root_length_growth_endpoint\s*=\s*rootLength\(growthEnd\)', ...
    'once')) && ~isempty(regexp(audit_source, ...
    'root_length_growth_endpoint\s*>\s*0','once')) && ...
    ~isempty(regexp(audit_source, ...
    'root_length_growth_endpoint\s*>=\s*rootLength\(emerge\)','once')), ...
    'The fine-root gate must assess the managed growth endpoint.');

[~,~,~,failure] = Audit_Managed_Crop_Season( ...
    dates,lai,[90;140;180;170;160],datetime(2016,9,12));
assert(~isempty(failure), ...
    'A missing scheduled removal boundary must remain assessable as a failure.');

amendment = datetime(2016,11,10);
identityDates = (datetime(2016,11,8):days(1):datetime(2016,11,11))';
values = [6 6 6;6 6 6;6 6.5 7;6 7 8];
spread = Audit_Preapplication_Treatment_Spread( ...
    identityDates,values,amendment);
assert(spread == 0, ...
    'Treatment differences on and after amendment entered the identity gate.');
values(1,3) = 6.1;
spread = Audit_Preapplication_Treatment_Spread( ...
    identityDates,values,amendment);
assert(abs(spread-0.1) < 1e-12, ...
    'A real pre-amendment treatment difference was not detected.');

assert(~contains(audit_source,'max(nh4) <= 20') && ...
    ~contains(audit_source,'max(no3) <= 20') && ...
    ~contains(audit_source,'max(nh4+no3) <= 30'), ...
    'Unsourced absolute mineral-N screens must not reject a closed run.');
assert(contains(audit_source,'year(dates) == 2016'), ...
    'The soybean fertilizer gate must inspect 2016 rather than the full run.');

fprintf('PASS: checkpoint audit aligns harvest and amendment boundaries.\n');
end
