function test_erw_strict_acceptance
% ERW must reject invalid states and conserve every primary mineral.

here = fileparts(mfilename('fullpath'));
code = fileparts(here);
erw_source = fileread(fullfile(code,'ERW_function.m'));
parameter_source = fileread(fullfile(code,'Parameters','ERW_MOD_PARAM_excel.m'));

assert(~contains(erw_source,'cation_mass_relative_residual <= 2e-2'), ...
    'ERW must not accept a relaxed 2 percent cation mass residual.');
assert(contains(erw_source,"error('ERW:NoConverge'"), ...
    'A nonconverged ERW algebraic solve must stop before state write-back.');
assert(~contains(erw_source,'T_K = 298.15; end % guard invalid T_K'), ...
    'Invalid soil temperature must not be replaced silently by 25 C.');
assert(contains(erw_source,'EW_inventory_max') && ...
    contains(parameter_source,'EW_inventory_max'), ...
    'Every primary mineral flux must be bounded by remaining inventory.');
assert(~contains(erw_source,'min(i_best,end)'), ...
    'The no-physical-solution reporter must not reference an undefined root index.');
assert(contains(erw_source,'sign_change(1)'), ...
    'The no-physical-solution reporter must select an available scan root deterministically.');
assert(~contains(erw_source,'10*res_threshold') && ...
    contains(erw_source,'max_scaled_res > res_threshold'), ...
    'The final ERW acceptance gate must use the declared residual tolerance.');
assert(contains(erw_source,'charge_raw = abs(aqueous_charge_res_fn(sol));') && ...
    contains(erw_source,'max_scaled_res > res_threshold || charge_raw > charge_tol || bad_state'), ...
    'The final acceptance gate must test direct aqueous charge, not only carbonate speciation.');

fprintf('PASS: ERW acceptance and primary inventory gates are strict.\n');
end
