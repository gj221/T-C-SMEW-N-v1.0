function [Omega_CaCO3,Omega_MgCO3] = ERW_Derived_Carbonate_Omega( ...
    Ca,Mg,CO3,K_CaCO3,K_MgCO3)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Derive carbonate saturation from retained aqueous concentrations.
%%
%% Ca, Mg, and CO3 are stored in umol L^-1 and each K is stored in
%% (umol L^-1)^2, so the returned saturation indices are dimensionless.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

if ~(isnumeric(Ca) && isnumeric(Mg) && isnumeric(CO3) && ...
        isequal(size(Ca),size(Mg),size(CO3)))
    error('ERW_Derived_Carbonate_Omega:BadInput', ...
        'Ca, Mg, and CO3 must be numeric arrays with identical dimensions.');
end
if any(~isfinite(Ca),'all') || any(~isfinite(Mg),'all') || ...
        any(~isfinite(CO3),'all') || any(Ca < 0,'all') || ...
        any(Mg < 0,'all') || any(CO3 < 0,'all')
    error('ERW_Derived_Carbonate_Omega:BadConcentration', ...
        'Ca, Mg, and CO3 must contain finite nonnegative concentrations.');
end
if ~(isnumeric(K_CaCO3) && isscalar(K_CaCO3) && isfinite(K_CaCO3) && ...
        K_CaCO3 > 0 && isnumeric(K_MgCO3) && isscalar(K_MgCO3) && ...
        isfinite(K_MgCO3) && K_MgCO3 > 0)
    error('ERW_Derived_Carbonate_Omega:BadSolubilityProduct', ...
        'Carbonate solubility products must be finite positive scalars.');
end

Omega_CaCO3 = Ca.*CO3./K_CaCO3;
Omega_MgCO3 = Mg.*CO3./K_MgCO3;
if any(~isfinite(Omega_CaCO3),'all') || ...
        any(~isfinite(Omega_MgCO3),'all') || ...
        any(Omega_CaCO3 < 0,'all') || any(Omega_MgCO3 < 0,'all')
    error('ERW_Derived_Carbonate_Omega:InvalidResult', ...
        'Derived carbonate saturation is nonfinite or negative.');
end

end
